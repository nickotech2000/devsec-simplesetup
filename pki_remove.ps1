    @'
====================================================================================================
 pki_remove.ps1  -  list the PKIs and remove one release, one PKI, or all of them
 Version 7.9.5
 Author : Nicko Satria Utama
 Company: Agantra Inovatif OÜ (NextMantra)
 Email  : nicko@nextmantra.com
====================================================================================================
 On a terminal: SPACE = next page, ENTER = next line, Q = quit.
 Manual : docs\pki_setup-MANUAL.txt (section 13)   Design: PKI-Design-with-FIPS-and-PQC.txt (21)
 Needs  : PowerShell 7+. Removing trust in Windows needs an ELEVATED PowerShell (administrator).

WHAT IT IS
  Every PKI lives in its own folder inside .\pki\ :
     pki\pki-<name>-01   pki\pki-<name>-02 ...          the normal family
     pki\pki-<name>-nocr-01 ...                          made with pki_setup.ps1 -NoCaRevocationInfo
  A PKI of an older version sits directly in pki\ and counts as release 1.
  This script lists them, and removes the TRUST of one of them (or of all of them) from this
  Windows computer. If you say so, it also deletes the files.

QUICK START
  1. Look first. Changes nothing, needs no administrator:   .\pki_remove.ps1 -List
  2. Remove the trust of release 2. The files stay:         .\pki_remove.ps1 -Release 2
  3. Remove everything of every PKI (asks you to type yes): .\pki_remove.ps1 -AllPki
  WARNING: deleting a folder deletes the CA PRIVATE KEYS in it. Nobody can bring them back. Make a
  backup first (Backup-Pki.ps1) if there is any chance you need them.

WHAT TO REMOVE
  -List                  Show every PKI: release, variant, folder, number of CAs, expiry, and (on
                         Windows) whether its roots are in the Local Machine store. Changes nothing.
  -Release <n>           Remove the trust of release R<n>: its CA certificates (matched by
                         thumbprint and by name) and its leaf certificates from LocalMachine Root,
                         Intermediate (CA) and Personal (My). The files stay.
                         The release number is always required for removing. Nothing is guessed.
  -NoCaRevocationInfo    With -Release: the NoCR family instead of the normal one. The two families
                         are separate: removing R2 never touches NoCR R2, and the other way round.
  -DeleteFiles           With -Release: also delete the folder of that release, with its keys.
                         Leaf certificates in .\leafcerts are never touched. Delete them yourself.
  -All                   With -Pki <name>: every release and variant of that ONE PKI (trust and
