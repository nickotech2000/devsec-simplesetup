    function Get-Reg([string]$Path, [string]$Name) { try { return (Get-ItemProperty -Path $Path -Name $Name -ErrorAction Stop).$Name } catch { return $null } }

    # ---- the operating system
    $kind = 'other'; $osName = ''; $osVer = ''; $patch = ''; $platform = ''; $arch = ''
