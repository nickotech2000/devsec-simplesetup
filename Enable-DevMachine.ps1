        if ($rt.Count -gt 0) { Add-Row 'Runtime' ((($rt.Keys | Sort-Object) | ForEach-Object { $_ + ' ' + $rt[$_] }) -join "`n") } else { Add-Row 'Runtime' 'none installed' }
