$engines = New-Object System.Collections.Generic.List[object]
function Add-Engine([string]$Name, [string]$Exe) { if ($Exe -and (Test-Path -LiteralPath $Exe)) { foreach ($e in $engines) { if ($e.Exe -ieq $Exe) { return } }; [void]$engines.Add([pscustomobject]@{ Name = $Name; Exe = $Exe }) } }
$sys = Join-Path $env:SystemRoot 'System32\WindowsPowerShell\v1.0\powershell.exe'
$wow = Join-Path $env:SystemRoot 'SysWOW64\WindowsPowerShell\v1.0\powershell.exe'
$sysnative = Join-Path $env:SystemRoot 'Sysnative\WindowsPowerShell\v1.0\powershell.exe'   # a 32-bit host sees the 64-bit one here
if (Test-Path -LiteralPath $sysnative) { Add-Engine 'Windows PowerShell 5.1 (64 bit)' $sysnative } else { Add-Engine 'Windows PowerShell 5.1 (64 bit)' $sys }
Add-Engine 'Windows PowerShell 5.1 (32 bit)' $wow
foreach ($pf in @($env:ProgramFiles, ${env:ProgramFiles(x86)}, "$env:LOCALAPPDATA\Microsoft\PowerShell")) {
    if (-not $pf) { continue }
    foreach ($d in @(Get-ChildItem -LiteralPath (Join-Path $pf 'PowerShell') -Directory -ErrorAction SilentlyContinue)) { Add-Engine ('PowerShell ' + $d.Name + ' (pwsh)') (Join-Path $d.FullName 'pwsh.exe') }
}
foreach ($c in @(Get-Command pwsh.exe -All -ErrorAction SilentlyContinue)) { Add-Engine 'PowerShell 7 (pwsh, PATH)' $c.Source }

function Invoke-Engine([string]$Exe, [string]$Code) {
    $o = & $Exe -NoProfile -NonInteractive -Command $Code 2>&1
    return ($o | ForEach-Object { [string]$_ }) -join "`n"
}

function Show-Status {
    Write-Host ''
    Write-Host 'Execution policy of every PowerShell on this computer' -ForegroundColor Cyan
    foreach ($e in $engines) {
        Write-Host ('  {0}' -f $e.Name) -ForegroundColor White
        $out = Invoke-Engine $e.Exe 'Get-ExecutionPolicy -List | ForEach-Object { ''{0,-16} {1}'' -f $_.Scope, $_.ExecutionPolicy }'
        foreach ($l in ($out -split "`n")) { Write-Host ('      ' + $l) }
        $eff = (Invoke-Engine $e.Exe 'Get-ExecutionPolicy').Trim()
        Write-Host ('      EFFECTIVE        ' + $eff) -ForegroundColor $(if ($eff -eq 'Bypass') { 'Green' } else { 'Yellow' })
    }
    $blocked = 0; $total = 0
    foreach ($p in $Path) { if (Test-Path -LiteralPath $p) { foreach ($f in @(Get-ChildItem -LiteralPath $p -Recurse -File -Force -ErrorAction SilentlyContinue)) { $total++; if (Get-Item -LiteralPath $f.FullName -Stream Zone.Identifier -ErrorAction SilentlyContinue) { $blocked++ } } } }
    Write-Host ''
    Write-Host ('Files below {0}: {1}, still blocked (downloaded mark): {2}' -f ($Path -join ', '), $total, $blocked)
    Write-Host ('Administrator: {0}  (needed for the machine-wide setting)' -f $isAdmin)
}

Write-Host ('Enable-DevMachine.ps1 7.9.12   PowerShell {0}   {1}' -f $PSVersionTable.PSVersion, $(if ($isAdmin) { 'Administrator' } else { 'normal user' }))
if ($engines.Count -eq 0) { Write-Host '[ERROR] No PowerShell found.' -ForegroundColor Red; exit 1 }

if ($Status) { Show-Status; exit 0 }

$policy = if ($Undo) { 'Undefined' } else { 'Bypass' }
if (-not $Yes) {
    if ($Undo) { Write-Host 'This removes the Bypass setting of the user' -NoNewline; if ($isAdmin) { Write-Host ' and of the computer.' } else { Write-Host '.' } }
    else {
        Write-Host 'This switches the PowerShell script protection OFF (policy Bypass) for every session, now and later,' -ForegroundColor Yellow
        Write-Host ('for the current user' + $(if ($isAdmin) { ' AND for all users of this computer.' } else { ' only (start as Administrator for all users).' })) -ForegroundColor Yellow
        if (-not $NoUnblock) { Write-Host ('It also unblocks all files below: ' + ($Path -join ', ')) -ForegroundColor Yellow }
        Write-Host 'Use it on your own development computer only.' -ForegroundColor Yellow
    }
    $a = Read-Host 'Continue? (Y/N)'
    if ($a -notmatch '^(y|yes)$') { Write-Host 'Nothing changed.'; exit 2 }
}

$fail = 0
foreach ($e in $engines) {
    $scopes = @('CurrentUser'); if ($isAdmin) { $scopes += 'LocalMachine' }
    foreach ($s in $scopes) {
        $out = Invoke-Engine $e.Exe ("try { Set-ExecutionPolicy -ExecutionPolicy $policy -Scope $s -Force -ErrorAction Stop; 'ok' } catch { 'ERROR: ' + `$_.Exception.Message }")
        if ($out.Trim() -eq 'ok') { Write-Host ('[OK]    {0}: {1} = {2}' -f $e.Name, $s, $policy) -ForegroundColor Green }
        else { Write-Host ('[WARN]  {0}: {1}: {2}' -f $e.Name, $s, $out.Trim()) -ForegroundColor Yellow; $fail++ }
    }
}
if (-not $isAdmin) { Write-Host '[INFO]  Not Administrator: only the current user was changed. For all users: start PowerShell as Administrator and run it again.' }

if (-not $Undo -and -not $NoUnblock) {
    $n = 0
    foreach ($p in $Path) {
        if (-not (Test-Path -LiteralPath $p)) { Write-Host ('[WARN]  Folder not found: ' + $p) -ForegroundColor Yellow; continue }
        foreach ($f in @(Get-ChildItem -LiteralPath $p -Recurse -File -Force -ErrorAction SilentlyContinue)) {
            try { Unblock-File -LiteralPath $f.FullName -ErrorAction Stop } catch { }
            try { if ($f.IsReadOnly) { $f.IsReadOnly = $false } } catch { }
            $n++
        }
    }
    Write-Host ('[OK]    Unblocked {0} file(s) below {1}' -f $n, ($Path -join ', ')) -ForegroundColor Green
}

Show-Status
Write-Host ''
if ($Undo) { Write-Host 'Done. Open a NEW PowerShell window.' }
else {
    Write-Host 'Done. Open a NEW PowerShell window; scripts run without a question. The scripts you copy LATER from the Internet'
    Write-Host 'run too, but keep the "downloaded" mark: run this file again (or Unblock-File) to clear it.'
}
if ($fail -gt 0) { Write-Host ('{0} setting(s) could not be changed. Often a Group Policy: see the table above (MachinePolicy / UserPolicy).' -f $fail) -ForegroundColor Yellow; exit 1 }
exit 0
