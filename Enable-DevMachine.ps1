    foreach ($c in @('python3', 'python')) { foreach ($p in (Find-Tool $c)) { $t = First-Line (Run-Tool $p '--version' ''); if ($t -match '^Python (3\.\d+\S*)') { $py = $Matches[1]; $pp = $p; break } }; if ($py) { break } }
