kind_of() {  # file -> kind or ""
  local b ext; b="$(basename "${1%/}")"; ext="${b##*.}"; [ "$ext" = "$b" ] && ext=''; ext="$(printf '%s' "$ext" | tr '[:upper:]' '[:lower:]')"
  if [ -n "$ext" ] && [ -n "${KIND[$ext]:-}" ]; then printf '%s' "${KIND[$ext]}"; return; fi
  if [ -z "$ext" ] && [ -f "$1" ]; then
    case "$(head -c4 "$1" 2>/dev/null | od -An -tx1 | tr -d ' \n')" in feedface|feedfacf|cefaedfe|cffaedfe|cafebabe|bebafeca) printf apple ;; esac
  fi
}
matches() {  # name, include / exclude
  local n="$1" g ok=1
  if [ "${#INCL[@]}" -gt 0 ]; then ok=0; for g in "${INCL[@]}"; do [[ "$n" == $g ]] && ok=1; done; fi
  for g in "${EXCL[@]}"; do [[ "$n" == $g ]] && ok=0; done
  [ "$ok" = 1 ]
}
LIST=()
for f in "${FILES[@]}"; do
  [ -e "$f" ] || { echo "[ERROR] File not found: $f" >&2; exit 1; }
  if [ -n "$(kind_of "$f")" ]; then LIST+=("$f"); else say WARN "Not a supported file type, skipped: $f"; fi
done
for d in "${FOLDERS[@]}"; do
  [ -d "$d" ] || { echo "[ERROR] Folder not found: $d" >&2; exit 1; }
  depth=(); [ "$NOREC" = 1 ] && depth=(-maxdepth 1)
  while IFS= read -r -d '' f; do
    n="$(basename "$f")"; [ -n "$(kind_of "$f")" ] || continue; matches "$n" || continue
    case "$f" in *.app/*|*.framework/*) continue ;; esac
    LIST+=("$f")
  done < <(find "$d" "${depth[@]}" \( -type f -o -type d \( -name '*.app' -o -name '*.framework' \) \) -print0 2>/dev/null | sort -z)
done
[ "${#LIST[@]}" -gt 0 ] || { say ERROR 'No supported file to check. Give --file and / or --folder (see --help).'; exit 7; }

