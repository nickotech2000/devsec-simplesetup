  [ -n "$APKSIGNER" ] || missing+=("apksigner (Android SDK build-tools: sdkmanager \"build-tools;36.0.0\", and set ANDROID_HOME)")
fi
if [ -n "${NEEDK[nuget]:-}" ]; then command -v dotnet >/dev/null 2>&1 || missing+=("dotnet (the .NET SDK 8+: https://dot.net)"); fi
if [ -n "${NEEDK[apple]:-}" ]; then command -v rcodesign >/dev/null 2>&1 || missing+=("rcodesign (apple-codesign: cargo install apple-codesign, or the release from GitHub)"); fi
if [ "${#missing[@]}" -gt 0 ]; then
  for m in "${missing[@]}"; do say ERROR "Missing tool: $m"; done
  say ERROR 'Install the missing tool(s) and run again. No file was checked.'; exit 4
fi

WORK="$(mktemp -d "${TMPDIR:-/tmp}/verify-codesign.XXXXXX")"; trap 'rm -rf "$WORK"' EXIT
run() { detail "> $*"; "$@" >"$WORK/out.log" 2>&1 </dev/null; local rc=$?; [ "$VERBOSE" = 1 ] && sed 's/^/[VERBOSE]   /' "$WORK/out.log"; return $rc; }
OUTLOG="$WORK/out.log"

# ---------------------------------------------------------------- helpers for the certificates
split_certs() { rm -f "$WORK"/c-*.pem; awk -v d="$WORK" '/-----BEGIN CERTIFICATE-----/{n++; f=sprintf("%s/c-%02d.pem", d, n)} f{print > f} /-----END CERTIFICATE-----/{close(f); f=""}' "$1"; }
pick_signer() {  # $1 = PEM with certificates -> $WORK/signer.pem (code signing leaf) and $WORK/others.pem
  split_certs "$1"; : > "$WORK/others.pem"; rm -f "$WORK/signer.pem"; local f best='' second=''
  for f in "$WORK"/c-*.pem; do [ -f "$f" ] || continue
    if ! "$OPENSSL" x509 -in "$f" -noout -ext basicConstraints 2>/dev/null | grep -q 'CA:TRUE'; then
      if "$OPENSSL" x509 -in "$f" -noout -ext extendedKeyUsage 2>/dev/null | grep -q 'Code Signing'; then [ -z "$best" ] && best="$f"; else [ -z "$second" ] && second="$f"; fi
    fi
  done
  [ -z "$best" ] && best="$second"; [ -z "$best" ] && [ -f "$WORK/c-01.pem" ] && best="$WORK/c-01.pem"
  [ -n "$best" ] || return 1
  cp "$best" "$WORK/signer.pem"; for f in "$WORK"/c-*.pem; do [ "$f" = "$best" ] || cat "$f" >> "$WORK/others.pem"; done
}
to_epoch() { date -u -d "$1" +%s 2>/dev/null || date -u -j -f '%b %d %H:%M:%S %Y %Z' "$1" +%s 2>/dev/null; }
json() { printf '%s' "$1" | sed 's/\\/\\\\/g; s/"/\\"/g' | tr -d '\000-\037'; }

# ---------------------------------------------------------------- one file
# sets: ST (signed|unsigned|tampered|error) NOTE TS TSA DIG and $WORK/certs.pem (all certificates of the signature)
check_authenticode() {
  local f="$1" ca=(); [ -n "$CHAINF" ] && ca=(-CAfile "$CHAINF" -TSA-CAfile "$CHAINF")
  run osslsigncode verify -in "$f" "${ca[@]}"; TRUST_NATIVE=$?
  if grep -q 'Unable to extract existing signature\|No signature found' "$OUTLOG"; then ST=unsigned; return; fi
  local cur calc; cur="$(awk -F': *' '/^Current message digest/{print $2; exit}' "$OUTLOG" | tr -d ' ')"; calc="$(awk -F': *' '/^Calculated message digest/{print $2; exit}' "$OUTLOG" | awk '{print $1}')"
  if grep -q 'MISMATCH' "$OUTLOG" || { [ -n "$cur" ] && [ -n "$calc" ] && [ "$cur" != "$calc" ]; }; then ST=tampered; NOTE='the file hash differs from the signed hash'
  elif [ -n "$cur" ] || grep -q 'Signature verification: ok' "$OUTLOG"; then ST=signed
  else ST=error; NOTE="osslsigncode: $(grep -m1 -iE 'error|failed' "$OUTLOG")"; fi
  DIG="$(awk -F': *' '/^Message digest algorithm/{print $2; exit}' "$OUTLOG" | tr -d ' ')"
  TS="$(grep -m1 'Timestamp time:' "$OUTLOG" | sed 's/.*Timestamp time: *//')"
  [ -n "$TS" ] && TSA="$(awk '/^Timestamp verified using:/{f=1} f && /Subject:/{s=$0} f && /^Timestamp Server Signature/{print s; exit}' "$OUTLOG" | sed 's/.*Subject: *//')"
  [ -n "$TS" ] && [ -z "$TSA" ] && TSA='(timestamp server certificate not shown)'
  osslsigncode extract-signature -in "$f" -out "$WORK/sig.der" >/dev/null 2>&1 \
    && "$OPENSSL" pkcs7 -in "$WORK/sig.der" -inform DER -print_certs -out "$WORK/certs.pem" 2>/dev/null
}
check_java() {
  local f="$1"
  run jarsigner -verify -verbose -certs "$f"; local rc=$?
  if grep -q 'jar is unsigned' "$OUTLOG" && ! grep -qi 'digest error\|SecurityException' "$OUTLOG"; then ST=unsigned; return; fi
  if [ "$rc" = 0 ] && grep -q 'jar verified' "$OUTLOG"; then ST=signed
  elif grep -qiE 'digest error|SecurityException|invalid .*signature|has been tampered|not signed by' "$OUTLOG"; then ST=tampered; NOTE="$(grep -m1 -iE 'digest error|SecurityException|tampered|invalid' "$OUTLOG" | sed 's/^jarsigner: //')"
  else ST=error; NOTE="jarsigner: $(grep -m1 -v '^Picked up' "$OUTLOG")"; fi
  DIG="$(grep -m1 '^ *Digest algorithm:' "$OUTLOG" | sed 's/.*: *//')"
  local tl; tl="$(grep -m1 'Timestamped by' "$OUTLOG")"
  if [ -n "$tl" ]; then TSA="$(printf '%s' "$tl" | sed -E 's/.*Timestamped by "([^"]*)".*/\1/')"; TS="$(printf '%s' "$tl" | sed -E 's/.* on //')"; fi
  local sf; sf="$(unzip -Z1 "$f" 2>/dev/null | grep -E '^META-INF/[^/]+\.(RSA|EC|DSA)$' | head -n1)"
  [ -n "$sf" ] && unzip -p "$f" "$sf" > "$WORK/sig.der" 2>/dev/null && "$OPENSSL" pkcs7 -in "$WORK/sig.der" -inform DER -print_certs -out "$WORK/certs.pem" 2>/dev/null
  grep -q 'certificate chain is invalid' "$OUTLOG" && TRUST_NATIVE=1 || TRUST_NATIVE=0
}
check_apk() {
  local f="$1"
  run "$APKSIGNER" verify --verbose --print-certs --print-certs-pem "$f"; local rc=$?
  if [ "$rc" != 0 ] && grep -q 'print-certs-pem' "$OUTLOG"; then run "$APKSIGNER" verify --verbose --print-certs "$f"; rc=$?; fi
  if [ "$rc" = 0 ]; then ST=signed
  elif grep -qiE 'integrity check failed|did not verify|digest.*mismatch|DOES NOT VERIFY.*signer|Malformed' "$OUTLOG" && grep -qi 'signer' "$OUTLOG"; then ST=tampered; NOTE="$(grep -m1 -i 'ERROR' "$OUTLOG")"
  elif grep -qiE 'Missing META-INF/MANIFEST.MF|No JAR signatures|no signers|not signed' "$OUTLOG"; then ST=unsigned; return
  else ST=error; NOTE="apksigner: $(grep -m1 -i 'error' "$OUTLOG")"; fi
  DIG="$(grep -E '^Verified using v[0-9.]+ scheme.*: true' "$OUTLOG" | sed -E 's/^Verified using (v[0-9.]+) scheme.*/\1/' | tr '\n' ' ' | sed 's/ $//')"; [ -n "$DIG" ] && DIG="APK signature scheme $DIG"
  TS='n/a (APK signatures have no timestamp)'; TSA=''
  awk '/-----BEGIN CERTIFICATE-----/,/-----END CERTIFICATE-----/' "$OUTLOG" > "$WORK/certs.pem"
  if [ ! -s "$WORK/certs.pem" ]; then
    local sf; sf="$(unzip -Z1 "$f" 2>/dev/null | grep -E '^META-INF/[^/]+\.(RSA|EC|DSA)$' | head -n1)"
    [ -n "$sf" ] && unzip -p "$f" "$sf" > "$WORK/sig.der" 2>/dev/null && "$OPENSSL" pkcs7 -in "$WORK/sig.der" -inform DER -print_certs -out "$WORK/certs.pem" 2>/dev/null
  fi
  TRUST_NATIVE=na
}
check_nuget() {
  local f="$1"
  run dotnet nuget verify --all "$f" -v n; local rc=$?
  if grep -q 'NU3004' "$OUTLOG"; then ST=unsigned; return; fi
  if [ "$rc" = 0 ]; then ST=signed
  elif grep -qE 'NU3008|NU3036|integrity check failed' "$OUTLOG"; then ST=tampered; NOTE="$(grep -m1 -E 'NU3008|NU3036' "$OUTLOG")"
  elif grep -qE 'NU3018|NU3028|NU3037|untrusted|not trusted' "$OUTLOG"; then ST=signed; TRUST_NATIVE=1
  else ST=error; NOTE="dotnet nuget verify: $(grep -m1 -E 'NU[0-9]{4}|error' "$OUTLOG")"; fi
  DIG="$(grep -m1 -i 'Signature Hash Algorithm' "$OUTLOG" | sed 's/.*: *//')"
  TS="$(awk '/Timestamp/{f=1} f && /Valid from|Timestamp:/{print; exit}' "$OUTLOG" | sed 's/.*: *//')"
  unzip -p "$f" .signature.p7s > "$WORK/sig.der" 2>/dev/null && "$OPENSSL" pkcs7 -in "$WORK/sig.der" -inform DER -print_certs -out "$WORK/certs.pem" 2>/dev/null
}
check_apple() {
  local f="$1"
  run rcodesign verify "$f"; local rc=$?
  if grep -qiE 'no signature|not signed|does not have a code signature' "$OUTLOG"; then ST=unsigned; return; fi
  if [ "$rc" = 0 ]; then ST=signed; else ST=tampered; NOTE="rcodesign: $(grep -m1 -iE 'error|problem' "$OUTLOG")"; fi
  TS='(see rcodesign print-signature-info)'; TRUST_NATIVE=na
}

# ---------------------------------------------------------------- check every file
declare -a R_FILE R_KIND R_STATUS R_SUBJ R_KEY R_TS R_NOTE
JSONROWS=(); failed=0; n_ok=0; i=0
for f in "${LIST[@]}"; do
  i=$((i+1)); k="$(kind_of "$f")"
  ST=error; NOTE=''; TS=''; TSA=''; DIG=''; TRUST_NATIVE=0; rm -f "$WORK/certs.pem" "$WORK/sig.der" "$WORK/signer.pem"
  echo "----- [$i/${#LIST[@]}] $f  ($k)"
  case "$k" in authenticode) check_authenticode "$f" ;; java) check_java "$f" ;; apk) check_apk "$f" ;; nuget) check_nuget "$f" ;; apple) check_apple "$f" ;; esac
  problems=(); warns=()
  SUBJ=''; ISS=''; SER=''; NB=''; NA=''; KEYT=''; FP256=''; FP512=''; EKU=''; TRUST='not checked'
  if [ "$ST" = signed ] || [ "$ST" = tampered ]; then
    if [ -s "$WORK/certs.pem" ] && pick_signer "$WORK/certs.pem"; then
      S="$WORK/signer.pem"; X() { "$OPENSSL" x509 -in "$S" -noout "$@" 2>/dev/null; }
      SUBJ="$(X -subject -nameopt RFC2253 | sed 's/^subject=//')"; ISS="$(X -issuer -nameopt RFC2253 | sed 's/^issuer=//')"
      SER="$(X -serial | sed 's/^serial=//')"; NB="$(X -startdate | sed 's/^notBefore=//')"; NA="$(X -enddate | sed 's/^notAfter=//')"
      KEYT="$(X -text | awk '/Public Key Algorithm/{a=$NF} /Public-Key:/{gsub(/[()]/,""); b=$(NF-1)} /NIST CURVE|ASN1 OID/{c=$NF} END{if(a~/rsa/) print "RSA-" b; else if (a~/ec/) print "EC " c " (" b " bit)"; else print a " " b}')"
      FP256="$(X -fingerprint -sha256 | sed 's/^.*=//; s/://g' | tr '[:upper:]' '[:lower:]')"; FP512="$(X -fingerprint -sha512 | sed 's/^.*=//; s/://g' | tr '[:upper:]' '[:lower:]')"
      EKU="$(X -ext extendedKeyUsage | tail -n +2 | sed 's/^ *//' | tr '\n' ' ')"
      # trust: the chain from the signature (+ --chain-file) up to a trusted root, at the time of the timestamp if there is one
      va=(); [ -n "$CHAINF" ] && va+=(-CAfile "$CHAINF"); [ -s "$WORK/others.pem" ] && va+=(-untrusted "$WORK/others.pem")
      te=''; [ -n "$TS" ] && case "$TS" in n/a*|\(*) ;; *) te="$(to_epoch "$TS")" ;; esac; [ -n "$te" ] && va+=(-attime "$te")
      if "$OPENSSL" verify "${va[@]}" "$S" >"$WORK/v.log" 2>&1; then TRUST=trusted; else TRUST="NOT trusted: $(grep -m1 -E 'error [0-9]+' "$WORK/v.log" | sed 's/.*error [0-9]* at [0-9]* depth lookup: //; s/^error [0-9]*[^:]*: //')"; fi
      [ "$k" = apk ] && [ "$TRUST" != trusted ] && TRUST="$TRUST (normal for Android: the key itself is the identity)"
      bits="${KEYT#RSA-}"; if [ "$bits" != "$KEYT" ] && [ "$bits" -lt "$MINRSA" ] 2>/dev/null; then problems+=("RSA key of $bits bits is smaller than --min-rsa-bits $MINRSA"); fi
      case "$EKU" in *'Code Signing'*) ;; *) [ "$k" = apk ] || warns+=('the certificate has no Code Signing purpose (EKU)') ;; esac
      if [ "${#EXPECT[@]}" -gt 0 ]; then hit=0; for e in "${EXPECT[@]}"; do [ "$e" = "$FP256" ] && hit=1; done; [ "$hit" = 1 ] || problems+=('signed by ANOTHER certificate than --expect-sha256'); fi
      if [ -n "$SUBJ_WANT" ]; then case "$SUBJ" in *"$SUBJ_WANT"*) ;; *) problems+=("the subject does not contain \"$SUBJ_WANT\"") ;; esac; fi
    else
      warns+=('the signing certificate could not be read from the signature')
      [ "${#EXPECT[@]}" -gt 0 ] && problems+=('--expect-sha256 cannot be checked: no certificate')
    fi
    case "$(printf '%s' "$DIG" | tr '[:upper:]' '[:lower:]' | tr -d ' -')" in md5*|sha1|sha1with*) problems+=("weak signature digest $DIG (MD5 / SHA-1)") ;; esac
    if [ -z "$TS" ]; then TS='NONE'; if [ "$REQTS" = 1 ] && [ "$k" != apk ]; then problems+=('no timestamp (--require-timestamp)'); else [ "$k" = apk ] || warns+=('no timestamp: the signature ends when the certificate expires'); fi; fi
    if [ "$TRUST" != trusted ] && [ "$TRUST" != 'not checked' ] && [ "$k" != apk ]; then if [ "$STRICT" = 1 ]; then problems+=("chain $TRUST"); else warns+=("chain $TRUST (give --chain-file for a private PKI)"); fi; fi
  fi
  # hash files next to the file (Sign-Code: <file>-signed.sha256 / .sha512; Convert-CodeSignCert: <file>.sha256 / .sha512)
  HASHF='none'
  if [ -f "$f" ]; then for hf in "$f-signed.sha256" "$f-signed.sha512" "$f.sha256" "$f.sha512"; do
      [ -f "$hf" ] || continue; a="${hf##*.}"; want="$(awk '{print tolower($1); exit}' "$hf")"; got="$("$OPENSSL" dgst "-$a" -r "$f" | cut -d' ' -f1)"
      if [ "$want" = "$got" ]; then HASHF="match ($(basename "$hf"))"; else HASHF="MISMATCH ($(basename "$hf"))"; ST=tampered; NOTE="${NOTE:+$NOTE; }the file differs from $(basename "$hf")"; break; fi
    done; fi
  FSHA256="$( [ -f "$f" ] && "$OPENSSL" dgst -sha256 -r "$f" | cut -d' ' -f1)"; FSHA512="$( [ -f "$f" ] && "$OPENSSL" dgst -sha512 -r "$f" | cut -d' ' -f1)"
  # the verdict
  case "$ST" in
    signed) if [ "${#problems[@]}" -gt 0 ]; then VERDICT=FAILED; else VERDICT=VERIFIED; fi ;;
    unsigned) VERDICT=UNSIGNED ;; tampered) VERDICT=TAMPERED ;; *) VERDICT=ERROR ;;
  esac
  printf '  %-14s: %s\n' Result "$VERDICT${NOTE:+  ($NOTE)}"
  if [ -n "$SUBJ" ]; then
    printf '  %-14s: %s\n' 'Signed by' "$SUBJ" Issuer "$ISS" Serial "$SER" Valid "$NB  to  $NA" Key "$KEYT" Digest "${DIG:-unknown}" \
      Purposes "${EKU:-none listed}" 'Cert SHA-256' "$FP256" 'Cert SHA-512' "$FP512" Timestamp "$TS${TSA:+  by $TSA}" Chain "$TRUST"
  fi
  printf '  %-14s: %s\n' 'Hash file' "$HASHF" 'File SHA-256' "$FSHA256" 'File SHA-512' "$FSHA512"
  for w in "${warns[@]}"; do say WARN "$f: $w"; done
  for p in "${problems[@]}"; do say ERROR "$f: $p"; done
  case "$VERDICT" in VERIFIED) n_ok=$((n_ok+1)); say OK "$f: signed, unchanged$( [ "$TRUST" = trusted ] && echo ', trusted')." ;;
    UNSIGNED) failed=$((failed+1)); say ERROR "$f: NOT signed." ;; TAMPERED) failed=$((failed+1)); say ERROR "$f: TAMPERED - changed after signing. Do not ship it." ;;
    *) failed=$((failed+1)); [ "$VERDICT" = ERROR ] && say ERROR "$f: could not be checked. $NOTE" ;; esac
  R_FILE+=("$f"); R_KIND+=("$k"); R_STATUS+=("$VERDICT"); R_SUBJ+=("$SUBJ"); R_KEY+=("$KEYT"); R_TS+=("$TS")
  pj=''; for m in "${problems[@]}" "${warns[@]}"; do [ -n "$m" ] && pj+="\"$(json "$m")\","; done
  JSONROWS+=("{\"file\":\"$(json "$f")\",\"kind\":\"$k\",\"result\":\"$VERDICT\",\"note\":\"$(json "$NOTE")\",\"subject\":\"$(json "$SUBJ")\",\"issuer\":\"$(json "$ISS")\",\"serial\":\"$SER\",\"notBefore\":\"$NB\",\"notAfter\":\"$NA\",\"key\":\"$(json "$KEYT")\",\"digest\":\"$(json "$DIG")\",\"certSha256\":\"$FP256\",\"certSha512\":\"$FP512\",\"timestamp\":\"$(json "$TS")\",\"timestampServer\":\"$(json "$TSA")\",\"chain\":\"$(json "$TRUST")\",\"hashFile\":\"$(json "$HASHF")\",\"fileSha256\":\"$FSHA256\",\"fileSha512\":\"$FSHA512\",\"messages\":[${pj%,}]}")
done

# ---------------------------------------------------------------- summary
echo '===== SUMMARY ======================================================================'
for j in "${!R_FILE[@]}"; do printf '  %-9s %-13s %-10s %s\n' "${R_STATUS[$j]}" "${R_KIND[$j]}" "${R_KEY[$j]:--}" "${R_FILE[$j]}"; done
if [ -n "$REPDIR" ]; then
  mkdir -p "$REPDIR" && rep="$REPDIR/verify-report_$(date -u +%Y%m%d-%H%M%S).json"
  { printf '{"tool":"Verify-CodeSign.sh","version":"%s","time":"%s","verified":%d,"failed":%d,"files":[' "$VERSION" "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$n_ok" "$failed"
    (IFS=,; printf '%s' "${JSONROWS[*]}"); printf ']}\n'; } > "$rep" && say INFO "Report: $rep"
fi
if [ "$ENVK" = github ] && [ -n "${GITHUB_STEP_SUMMARY:-}" ]; then echo "### Verify-CodeSign: $n_ok verified, $failed failed (of ${#LIST[@]})" >> "$GITHUB_STEP_SUMMARY"; fi
if [ "$failed" -gt 0 ]; then say ERROR "Verified $n_ok, FAILED $failed (of ${#LIST[@]})."; exit 6; fi
say OK "Verified $n_ok of ${#LIST[@]}: signed, unchanged and within the rules."
exit 0
