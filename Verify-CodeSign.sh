    local t=error; [ "$lvl" = WARN ] && t=warning
    case "$ENVK" in github) echo "::$t::$*" ;; azure) echo "##vso[task.logissue type=$t]$*" ;; msbuild) echo "Verify-CodeSign : $t VC0001: $*" ;; esac
  fi
}
