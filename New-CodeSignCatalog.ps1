function Show-Cert($c, [string]$Title = 'CERTIFICATE') {
    Write-Host ("----- $Title " + ('-' * [Math]::Max(3, 74 - $Title.Length)))
    $rsa = [System.Security.Cryptography.X509Certificates.RSACertificateExtensions]::GetRSAPublicKey($c)
    $key = if ($rsa) { "RSA-$($rsa.ExportParameters($false).Modulus.Length * 8)" } else {
        $ec = [System.Security.Cryptography.X509Certificates.ECDsaCertificateExtensions]::GetECDsaPublicKey($c); if ($ec) { "EC ($($ec.KeySize) bit)" } else { $c.PublicKey.Oid.FriendlyName } }
    foreach ($r in @(@('Subject', $c.Subject), @('Issuer', $c.Issuer), @('Valid', "$($c.NotBefore.ToUniversalTime().ToString('yyyy-MM-dd HH:mm')) UTC  to  $($c.NotAfter.ToUniversalTime().ToString('yyyy-MM-dd HH:mm')) UTC"), @('Key', $key),
            @('Cert SHA-256', $c.GetCertHashString([System.Security.Cryptography.HashAlgorithmName]::SHA256).ToLowerInvariant()),
            @('Cert SHA-512', $c.GetCertHashString([System.Security.Cryptography.HashAlgorithmName]::SHA512).ToLowerInvariant()))) { Write-Host ('  {0,-14}: {1}' -f $r[0], $r[1]) }
}
