            if ($Include) { $ok = $false; foreach ($g in $Include) { if ($rel -like $g.Replace('\', '/') -or $f.Name -like $g) { $ok = $true } } }
            foreach ($g in $Exclude) { if ($rel -like $g.Replace('\', '/') -or $f.Name -like $g) { $ok = $false } }
            if ($ok) { [pscustomobject]@{ Rel = $rel; Full = $f.FullName } }
