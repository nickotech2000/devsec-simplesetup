            $skip = @(Get-ChildItem -LiteralPath $Root -File -Recurse | Where-Object { $_.FullName -in $own } | ForEach-Object { $_.Name })
            $r = Test-FileCatalog -Path $Root -CatalogFilePath $listF -Detailed -FilesToSkip $skip
            foreach ($k in @($r.CatalogItems.Keys)) {
                $p = Join-Path $Root $k
                if (-not (Test-Path -LiteralPath $p)) { & $fail "MISSING: $k" }
                elseif ($r.PathItems[$k] -ne $r.CatalogItems[$k]) { & $fail "TAMPERED: $k (the hash differs from the catalog)" }
            }
            foreach ($k in @($r.PathItems.Keys)) { if (-not $r.CatalogItems.ContainsKey($k)) { if ($Strict) { & $fail "NOT in the catalog (added later): $k" } else { & $warn "NOT in the catalog (added later): $k" } } }
            Write-Say 'INFO' "Test-FileCatalog: $($r.Status), files in the catalog: $($r.CatalogItems.Count)."
        } else {
            $alg = if ($listF -match '(?i)\.sha512$') { 'SHA512' } elseif ($listF -match '(?i)\.sha256$') { 'SHA256' } else { Stop-Catalog 1 '-Verify takes a .cat, <name>.sha256 or <name>.sha512.' }
            $listBytes = [System.IO.File]::ReadAllBytes($listF); $p7s = "$listF.p7s"
            if (-not (Test-Path -LiteralPath $p7s)) { if ($Strict) { & $fail "No signature ($p7s): the list is not signed." } else { & $warn "No signature ($p7s): only the hashes are checked." } }
            else {
                $p7sBytes = [System.IO.File]::ReadAllBytes($p7s)
                $cms = [System.Security.Cryptography.Pkcs.SignedCms]::new([System.Security.Cryptography.Pkcs.SubjectIdentifierType]::IssuerAndSerialNumber, [System.Security.Cryptography.Pkcs.ContentInfo]::new($listBytes), $true)
                $okSig = $true
                try { $cms.Decode($p7sBytes); $cms.CheckSignature($true) } catch { $okSig = $false; & $fail "TAMPERED: the list $(Split-Path -Leaf $listF) does not match its signature." }
                if ($okSig) {
                    $leaf = $cms.SignerInfos[0].Certificate
                    Show-Cert $leaf 'SIGNED BY'
                    Write-Say 'OK' "Signature of the list: valid ($(Split-Path -Leaf $p7s))."
                    if ($expect.Count -gt 0 -and $leaf.GetCertHashString([System.Security.Cryptography.HashAlgorithmName]::SHA256).ToLowerInvariant() -notin $expect) { & $fail 'Signed by ANOTHER certificate than -ExpectSha256.' }
                    if (-not (Test-CodeSignEku $leaf)) { & $warn 'The signing certificate has no Code Signing purpose.' }
                    $tsTime = $null; $tsr = "$p7s.tsr"
                    if (Test-Path -LiteralPath $tsr) {
                        $tok = Read-TimestampReply ([System.IO.File]::ReadAllBytes($tsr)); $tsaCert = $null
                        if (-not $tok) { & $warn 'The timestamp file cannot be read.' }
                        elseif (-not $tok.VerifySignatureForData($p7sBytes, [ref]$tsaCert, $chainExtra)) { & $fail 'TAMPERED: the timestamp does not belong to this signature.' }
                        else {
                            $tsTime = $tok.TokenInfo.Timestamp.UtcDateTime
                            Write-Say 'OK' "Timestamp: $($tsTime.ToString('yyyy-MM-dd HH:mm:ss')) UTC  by $($tsaCert.Subject)"
                            if (-not (Test-Trust $tsaCert @($tok.AsSignedCms().Certificates) $null)) { & $warn 'The timestamp server certificate is not trusted here.' }
                        }
                    } else { & $warn 'No timestamp: the signature ends when the certificate expires.' }
                    $others = @($cms.Certificates | Where-Object { $_.Thumbprint -ne $leaf.Thumbprint })
                    if (Test-Trust $leaf $others $tsTime) { Write-Say 'OK' 'Chain: trusted.' }
                    elseif ($Strict) { & $fail 'Chain: NOT trusted (give -ChainFile for a private PKI).' }
                    else { & $warn 'Chain: not trusted here (give -ChainFile for a private PKI).' }
                }
            }
            # every file of the list
            $inList = @{}; $n = 0; $bad = 0
            foreach ($line in [System.IO.File]::ReadAllLines($listF)) {
                if (-not $line) { continue }
                $i = $line.IndexOf('  '); if ($i -lt 1) { continue }
                $want = $line.Substring(0, $i).ToLowerInvariant(); $rel = $line.Substring($i + 2); $n++; $inList[$rel] = $true
                $p = Join-Path $Root $rel
                if (-not (Test-Path -LiteralPath $p -PathType Leaf)) { & $fail "MISSING: $rel"; $bad++; continue }
                if ((Get-FileHex $p $alg) -ne $want) { & $fail "TAMPERED: $rel (the hash differs from the catalog)"; $bad++ } else { Write-Detail "ok: $rel" }
            }
            Write-Say 'INFO' "Files in the catalog: $n, changed or missing: $bad."
            $base = $listF.Substring(0, $listF.Length - 7)
            $own = @('.sha256', '.sha512', '.sha256.p7s', '.sha512.p7s', '.sha256.p7s.tsr', '.sha512.p7s.tsr') | ForEach-Object { "$base$_" }
            foreach ($f in Get-ChildItem -LiteralPath $Root -File -Recurse -Force) {
                if ($f.FullName -in $own) { continue }
                $rel = $f.FullName.Substring($Root.Length + 1).Replace('\', '/')
                if (-not $inList.ContainsKey($rel)) { if ($Strict) { & $fail "NOT in the catalog (added later): $rel" } else { & $warn "NOT in the catalog (added later): $rel" } }
            }
        }
        if ($script:failedN -gt 0) { Stop-Catalog 6 "Catalog check FAILED ($($script:failedN) problem(s), $($script:warnN) warning(s))." }
        Write-Say 'OK' "Catalog check passed$(if ($script:warnN) { " with $($script:warnN) warning(s)" })."
    }
}
catch [CatalogExit] { Write-Say 'ERROR' $_.Exception.Message; $exit = $_.Exception.Code }
catch { Write-Say 'ERROR' "$($_.Exception.Message) (line $($_.InvocationInfo.ScriptLineNumber))"; $exit = 1 }
exit $exit
