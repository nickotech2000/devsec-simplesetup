    # ---------------------------------------------------------------- RFC 3161 timestamp of some bytes -> the raw answer (.tsr)
    function Get-TimestampReply([byte[]]$Data) {
        $req = [System.Security.Cryptography.Pkcs.Rfc3161TimestampRequest]::CreateFromData($Data, [System.Security.Cryptography.HashAlgorithmName]::SHA256, $null, [System.Security.Cryptography.RandomNumberGenerator]::GetBytes(8), $true, $null)
        foreach ($u in $tsUrls) {
            Write-Detail "POST $u (RFC 3161)"
            $hc = [System.Net.Http.HttpClient]::new(); $hc.Timeout = [TimeSpan]::FromSeconds(20)
            try {
                $content = [System.Net.Http.ByteArrayContent]::new($req.Encode()); $content.Headers.ContentType = [System.Net.Http.Headers.MediaTypeHeaderValue]::new('application/timestamp-query')
                $resp = $hc.PostAsync($u, $content).GetAwaiter().GetResult()
                if (-not $resp.IsSuccessStatusCode) { Write-Say 'WARN' "Timestamp server $u answered HTTP $([int]$resp.StatusCode). Trying the next one."; continue }
                $bytes = $resp.Content.ReadAsByteArrayAsync().GetAwaiter().GetResult()
                $read = 0; [void]$req.ProcessResponse($bytes, [ref]$read)
                $script:TsUsed = $u; return , $bytes
            }
            catch { Write-Say 'WARN' "Timestamp server ${u}: $($_.Exception.GetBaseException().Message). Trying the next one." }
            finally { $hc.Dispose() }
        }
        Stop-Catalog 3 "No timestamp server answered (tried: $($tsUrls -join ', ')). Nothing was written. Use -Timestamp None for a test without one."
    }
    function Read-TimestampReply([byte[]]$Reply) {  # TimeStampResp -> the token (or $null)
        $r = [System.Formats.Asn1.AsnReader]::new([ReadOnlyMemory[byte]]$Reply, [System.Formats.Asn1.AsnEncodingRules]::DER)
        $seq = $r.ReadSequence(); $si = $seq.ReadSequence(); if ([int]$si.ReadInteger() -gt 1 -or -not $seq.HasData) { return $null }
        $tok = $null; $n = 0; if ([System.Security.Cryptography.Pkcs.Rfc3161TimestampToken]::TryDecode($seq.ReadEncodedValue(), [ref]$tok, [ref]$n)) { return $tok }; return $null
    }
    function Test-Trust($c, $Others, $AtTime) {
        foreach ($custom in $false, $true) {
            if ($custom -and $chainExtra.Count -eq 0) { break }
            $ch = [System.Security.Cryptography.X509Certificates.X509Chain]::new(); $p = $ch.ChainPolicy
            $p.RevocationMode = [System.Security.Cryptography.X509Certificates.X509RevocationMode]::NoCheck
            foreach ($o in @($Others) + @($chainExtra)) { if ($o) { [void]$p.ExtraStore.Add($o) } }
            if ($custom) { $p.TrustMode = [System.Security.Cryptography.X509Certificates.X509ChainTrustMode]::CustomRootTrust; foreach ($o in $chainExtra) { [void]$p.CustomTrustStore.Add($o) } }
            if ($AtTime) { $p.VerificationTime = $AtTime }
            $ok = $ch.Build($c); $ch.Dispose(); if ($ok) { return $true }
        }
        return $false
    }

    # ---------------------------------------------------------------- the files of a folder (relative paths, '/' separated)
    function Get-CatalogFiles([string]$Dir, [string[]]$Skip) {
