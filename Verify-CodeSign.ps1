    function Get-Slice([byte[]]$b, [int]$Offset, [int]$Length) { $r = [byte[]]::new($Length); [Array]::Copy($b, $Offset, $r, 0, $Length); return , $r }
    function Get-PeSignature([string]$Path) {  # the PKCS#7 of a signed PE file (exe dll sys ...), from the security directory
        $b = [System.IO.File]::ReadAllBytes($Path)
        if ($b.Length -lt 0x40 -or $b[0] -ne 0x4D -or $b[1] -ne 0x5A) { return $null }
        $pe = [BitConverter]::ToInt32($b, 0x3C); if ($pe -lt 0 -or $pe + 0x100 -gt $b.Length -or [BitConverter]::ToUInt32($b, $pe) -ne 0x4550) { return $null }
        $opt = $pe + 24; $dd = if ([BitConverter]::ToUInt16($b, $opt) -eq 0x20B) { $opt + 112 } else { $opt + 96 }
        $off = [BitConverter]::ToInt32($b, $dd + 32); $size = [BitConverter]::ToInt32($b, $dd + 36)
        if ($off -le 0 -or $size -le 8 -or $off + $size -gt $b.Length) { return $null }
        $len = [BitConverter]::ToInt32($b, $off); if ([BitConverter]::ToUInt16($b, $off + 6) -ne 2 -or $len -le 8 -or $off + $len -gt $b.Length) { return $null }
        return , (Get-Slice $b ($off + 8) ($len - 8))
    }
    function Get-ScriptSignature([string]$Path) {  # the Base64 signature block at the end of a PowerShell file
        $in = $false; $sb = [System.Text.StringBuilder]::new()
        foreach ($l in [System.IO.File]::ReadAllLines($Path)) {
            if ($l -match 'SIG # Begin signature block') { $in = $true; [void]$sb.Clear(); continue }
            if ($l -match 'SIG # End signature block') { $in = $false; continue }
            if ($in) { [void]$sb.Append(($l -replace '^\s*(#|<!--)\s*SIG\s*#\s*', '' -replace '\s*-->\s*$', '').Trim()) }
        }
        if ($sb.Length -eq 0) { return $null }
        try { return , [Convert]::FromBase64String($sb.ToString()) } catch { return $null }
    }
    function Get-ZipEntryBytes([string]$Path, [string]$Pattern) {
        $z = [System.IO.Compression.ZipFile]::OpenRead($Path)
        try {
            $e = $z.Entries | Where-Object { $_.FullName -match $Pattern } | Select-Object -First 1
