  -ExpectSubject <text>   The subject of the signing certificate must contain this text.
  -MinRsaBits <n>         Smallest RSA key accepted. Default 2048 (3072 or more is advised).
  -RequireTimestamp       A signature without a timestamp fails (Android APK: not applicable).
