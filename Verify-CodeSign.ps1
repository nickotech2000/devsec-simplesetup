            $sig = Get-AuthenticodeSignature -LiteralPath $f
            Write-Detail "Get-AuthenticodeSignature: $($sig.Status)  $($sig.StatusMessage)"
            switch ($sig.Status) {
                'NotSigned' { $R.St = 'unsigned'; return }
                'HashMismatch' { $R.St = 'tampered'; $R.Note = 'the file hash differs from the signed hash' }
                'Valid' { $R.St = 'signed' }
                default { if ($sig.SignerCertificate) { $R.St = 'signed'; $R.TrustNative = "$($sig.Status): $($sig.StatusMessage)" } else { $R.St = 'error'; $R.Note = "$($sig.Status): $($sig.StatusMessage)" } }
            }
            if (-not $der -and $sig.SignerCertificate) {  # msi, cab, msix ...: the certificates from Windows
                $c = [System.Security.Cryptography.X509Certificates.X509Certificate2Collection]::new(); [void]$c.Add($sig.SignerCertificate)
                $R.Cms = @{ Certs = $c; Signer = $sig.SignerCertificate; Digest = ''; TsTime = $null; TsServer = '' }
                if ($sig.TimeStamperCertificate) { $R.TsText = 'present (time not shown by Windows for this file type)'; $R.TsServer = $sig.TimeStamperCertificate.Subject }
            }
        } else {
            [void](Invoke-Tool $osslsigncode @('verify', '-in', $f))
            $log = $script:LastLog
            if ($log -match 'Unable to extract existing signature|No signature found') { $R.St = 'unsigned'; return }
            $cur = if ($log -match '(?m)^Current message digest\s*:\s*(.+)$') { ($Matches[1] -replace '\s', '') } else { '' }
            $calc = if ($log -match '(?m)^Calculated message digest\s*:\s*(\S+)') { $Matches[1] } else { '' }
            if ($log -match 'MISMATCH' -or ($cur -and $calc -and $cur -ne $calc)) { $R.St = 'tampered'; $R.Note = 'the file hash differs from the signed hash' }
            elseif ($cur -or $log -match 'Signature verification: ok') { $R.St = 'signed' }
            else { $R.St = 'error'; $R.Note = "osslsigncode: $((($log -split "`n") | Where-Object { $_ -match 'error|failed' } | Select-Object -First 1))" }
            if (-not $der) { $p = Join-Path $work 'sig.der'; if (Invoke-Tool $osslsigncode @('extract-signature', '-in', $f, '-out', $p)) { $der = [System.IO.File]::ReadAllBytes($p) } }
        }
        if ($der) { $m = Read-Cms $der; if ($m) { $R.Cms = $m } }
    }
