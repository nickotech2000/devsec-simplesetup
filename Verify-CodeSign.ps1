    }
    function Read-Cms([byte[]]$Der) {  # -> @{ Certs; Signer; Digest; TsTime; TsServer } or $null
        if (-not $Der) { return $null }
        $cms = [System.Security.Cryptography.Pkcs.SignedCms]::new()
        try { $cms.Decode($Der) } catch { Write-Detail "not a PKCS#7 signature: $($_.Exception.Message)"; return $null }
        $r = @{ Certs = $cms.Certificates; Signer = $null; Digest = ''; TsTime = $null; TsServer = '' }
        if ($cms.SignerInfos.Count -gt 0) {
            $si = $cms.SignerInfos[0]; $r.Signer = $si.Certificate
            $r.Digest = if ($si.DigestAlgorithm.FriendlyName) { $si.DigestAlgorithm.FriendlyName } else { $si.DigestAlgorithm.Value }
            foreach ($a in $si.UnsignedAttributes) {  # RFC 3161 timestamp: Microsoft (1.3.6.1.4.1.311.3.3.1) and CMS / Java (1.2.840.113549.1.9.16.2.14)
                if ($a.Oid.Value -in '1.3.6.1.4.1.311.3.3.1', '1.2.840.113549.1.9.16.2.14') {
                    $tok = $null
                    if ([System.Security.Cryptography.Pkcs.Rfc3161TimestampToken]::TryDecode($a.Values[0].RawData, [ref]$tok, [ref]$null)) {
                        $r.TsTime = $tok.TokenInfo.Timestamp.UtcDateTime
                        $tsi = $tok.AsSignedCms().SignerInfos; if ($tsi.Count -gt 0 -and $tsi[0].Certificate) { $r.TsServer = $tsi[0].Certificate.Subject }
                    }
                }
            }
            if (-not $r.TsTime -and $si.CounterSignerInfos.Count -gt 0) {  # the old Authenticode timestamp (a counter-signature)
                $cs = $si.CounterSignerInfos[0]
                foreach ($a in $cs.SignedAttributes) { if ($a.Oid.Value -eq '1.2.840.113549.1.9.5') { $r.TsTime = ([System.Security.Cryptography.Pkcs.Pkcs9SigningTime]::new($a.Values[0].RawData)).SigningTime.ToUniversalTime() } }
                if ($cs.Certificate) { $r.TsServer = $cs.Certificate.Subject }
            }
        }
        return $r
    }
