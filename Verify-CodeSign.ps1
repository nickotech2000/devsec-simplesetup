    function Test-Authenticode([string]$f, $R) {
        $ext = [System.IO.Path]::GetExtension($f).ToLowerInvariant()
        $der = if ($ext -in '.ps1', '.psm1', '.psd1', '.ps1xml', '.psc1', '.cdxml') { Get-ScriptSignature $f } elseif ($ext -eq '.cat') { [System.IO.File]::ReadAllBytes($f) } else { Get-PeSignature $f }
