        if ($log -match 'NU3004') { $R.St = 'unsigned'; return }
        if ($ok) { $R.St = 'signed' }
        elseif ($log -match 'NU3008|NU3036|integrity check failed') { $R.St = 'tampered'; $R.Note = (($log -split "`n") | Where-Object { $_ -match 'NU3008|NU3036' } | Select-Object -First 1) }
        elseif ($log -match 'NU3018|NU3028|NU3037|untrusted|not trusted') { $R.St = 'signed'; $R.TrustNative = 'dotnet nuget verify: not trusted' }
        else { $R.St = 'error'; $R.Note = "dotnet nuget verify: $((($log -split "`n") | Where-Object { $_ -match 'NU[0-9]{4}|error' } | Select-Object -First 1))" }
        $m = Read-Cms (Get-ZipEntryBytes $f '^\.signature\.p7s$'); if ($m) { $R.Cms = $m }
    }
    function Test-Apple([string]$f, $R) {
        $ok = Invoke-Tool $rcodesign @('verify', $f); $log = $script:LastLog
        if ($log -match '(?i)no signature|not signed|does not have a code signature') { $R.St = 'unsigned'; return }
        if ($ok) { $R.St = 'signed' } else { $R.St = 'tampered'; $R.Note = "rcodesign: $((($log -split "`n") | Where-Object { $_ -match '(?i)error|problem' } | Select-Object -First 1))" }
        $R.TsText = '(see rcodesign print-signature-info)'; $R.TrustNative = 'na'
    }

    # ---------------------------------------------------------------- the chain of trust (.NET X509Chain)
    function Test-Trust($Cert, $Others, $AtTime) {
        $try = { param([bool]$Custom)
            $ch = [System.Security.Cryptography.X509Certificates.X509Chain]::new()
            $p = $ch.ChainPolicy
            $p.RevocationMode = [System.Security.Cryptography.X509Certificates.X509RevocationMode]::NoCheck
            foreach ($o in $Others) { [void]$p.ExtraStore.Add($o) }
            foreach ($o in $chainCerts) { [void]$p.ExtraStore.Add($o) }
            if ($Custom) { $p.TrustMode = [System.Security.Cryptography.X509Certificates.X509ChainTrustMode]::CustomRootTrust; foreach ($o in $chainCerts) { [void]$p.CustomTrustStore.Add($o) } }
            if ($AtTime) { $p.VerificationTime = $AtTime }
            $ok = $ch.Build($Cert)
            $why = (@($ch.ChainStatus | Where-Object { $_.Status -ne 'NoError' } | ForEach-Object { $_.StatusInformation.Trim() }) | Select-Object -Unique) -join '; '
            $ch.Dispose(); return @($ok, $why)
        }
        $r = & $try $false
        if (-not $r[0] -and $chainCerts.Count -gt 0) { $r = & $try $true }
        if ($r[0]) { return 'trusted' }
        return "NOT trusted: $(if ($r[1]) { $r[1] } else { 'no trusted root' })"
    }

    # ---------------------------------------------------------------- check every file
    $rows = [System.Collections.Generic.List[object]]::new(); $failed = 0; $nOk = 0; $i = 0
    foreach ($f in $list) {
        $i++; $k = Get-Kind $f
        Write-Host "----- [$i/$($list.Count)] $f  ($k)"
        $R = @{ St = 'error'; Note = ''; Cms = $null; Digest = ''; TsText = ''; TsServer = ''; TrustNative = '' }
        try {
            switch ($k) { 'authenticode' { Test-Authenticode $f $R } 'java' { Test-Java $f $R } 'apk' { Test-Apk $f $R } 'nuget' { Test-NuGet $f $R } 'apple' { Test-Apple $f $R } }
        } catch { $R.St = 'error'; $R.Note = $_.Exception.Message }
        $problems = [System.Collections.Generic.List[string]]::new(); $warns = [System.Collections.Generic.List[string]]::new()
        $o = [ordered]@{ file = $f; kind = $k; result = ''; note = ''; subject = ''; issuer = ''; serial = ''; notBefore = ''; notAfter = ''; key = ''; digest = ''
            certSha256 = ''; certSha512 = ''; timestamp = ''; timestampServer = ''; chain = 'not checked'; hashFile = 'none'; fileSha256 = ''; fileSha512 = ''; messages = @() }
        $eku = ''
        if ($R.St -in 'signed', 'tampered') {
            if ($R.Cms) {
                if (-not $R.Digest) { $R.Digest = $R.Cms.Digest }
                if (-not $R.TsText -and $R.Cms.TsTime) { $R.TsText = $R.Cms.TsTime.ToString('yyyy-MM-dd HH:mm:ss') + ' UTC'; $R.TsServer = $R.Cms.TsServer }
            }
            $s = $null; if ($R.Cms) { $s = if ($R.Cms.Signer -and $k -ne 'apk') { $R.Cms.Signer } else { Select-Signer $R.Cms.Certs } }
            if ($s) {
                $o.subject = $s.Subject; $o.issuer = $s.Issuer; $o.serial = $s.SerialNumber
                $o.notBefore = $s.NotBefore.ToUniversalTime().ToString('yyyy-MM-dd HH:mm:ss') + ' UTC'; $o.notAfter = $s.NotAfter.ToUniversalTime().ToString('yyyy-MM-dd HH:mm:ss') + ' UTC'
                $rsa = [System.Security.Cryptography.X509Certificates.RSACertificateExtensions]::GetRSAPublicKey($s)
                $bits = 0
                if ($rsa) { $bits = $rsa.ExportParameters($false).Modulus.Length * 8; $o.key = "RSA-$bits" }
                else {
                    $ec = [System.Security.Cryptography.X509Certificates.ECDsaCertificateExtensions]::GetECDsaPublicKey($s)
                    if ($ec) { $cv = $ec.ExportParameters($false).Curve.Oid; $o.key = "EC $(if ($cv.FriendlyName) { $cv.FriendlyName } else { $cv.Value }) ($($ec.KeySize) bit)" }
                    else { $o.key = $s.PublicKey.Oid.FriendlyName }
                }
                $o.certSha256 = $s.GetCertHashString([System.Security.Cryptography.HashAlgorithmName]::SHA256).ToLowerInvariant()
                $o.certSha512 = $s.GetCertHashString([System.Security.Cryptography.HashAlgorithmName]::SHA512).ToLowerInvariant()
                $ekuExt = $s.Extensions | Where-Object { $_ -is [System.Security.Cryptography.X509Certificates.X509EnhancedKeyUsageExtension] }
                if ($ekuExt) { $eku = (@($ekuExt.EnhancedKeyUsages | ForEach-Object { if ($_.FriendlyName) { $_.FriendlyName } else { $_.Value } })) -join ', ' }
                $others = @($R.Cms.Certs | Where-Object { $_.Thumbprint -ne $s.Thumbprint })
                $o.chain = Test-Trust $s $others $R.Cms.TsTime
                if ($k -eq 'apk' -and $o.chain -ne 'trusted') { $o.chain += ' (normal for Android: the key itself is the identity)' }
                if ($bits -gt 0 -and $bits -lt $MinRsaBits) { $problems.Add("RSA key of $bits bits is smaller than -MinRsaBits $MinRsaBits") }
                if ($k -ne 'apk' -and -not ($ekuExt -and ($ekuExt.EnhancedKeyUsages | Where-Object { $_.Value -eq '1.3.6.1.5.5.7.3.3' }))) { $warns.Add('the certificate has no Code Signing purpose (EKU)') }
                if ($expect.Count -gt 0 -and $o.certSha256 -notin $expect) { $problems.Add('signed by ANOTHER certificate than -ExpectSha256') }
                if ($ExpectSubject -and $o.subject -notlike "*$ExpectSubject*") { $problems.Add("the subject does not contain `"$ExpectSubject`"") }
            } else {
                $warns.Add('the signing certificate could not be read from the signature')
                if ($expect.Count -gt 0) { $problems.Add('-ExpectSha256 cannot be checked: no certificate') }
            }
            if (($R.Digest -replace '[\s-]', '').ToLowerInvariant() -match '^(md5|sha1$|sha1with)') { $problems.Add("weak signature digest $($R.Digest) (MD5 / SHA-1)") }
            if (-not $R.TsText) {
                $R.TsText = 'NONE'
                if ($RequireTimestamp -and $k -ne 'apk') { $problems.Add('no timestamp (-RequireTimestamp)') } elseif ($k -ne 'apk') { $warns.Add('no timestamp: the signature ends when the certificate expires') }
            }
            if ($o.chain -ne 'trusted' -and $o.chain -ne 'not checked' -and $k -ne 'apk') {
                if ($Strict) { $problems.Add("chain $($o.chain)") } else { $warns.Add("chain $($o.chain) (give -ChainFile for a private PKI)") }
            }
        }
        # hash files next to the file (Sign-Code: <file>-signed.sha256 / .sha512; Convert-CodeSignCert: <file>.sha256 / .sha512)
        if (Test-Path -LiteralPath $f -PathType Leaf) {
            foreach ($hf in "$f-signed.sha256", "$f-signed.sha512", "$f.sha256", "$f.sha512") {
                if (-not (Test-Path -LiteralPath $hf -PathType Leaf)) { continue }
                $alg = if ($hf.EndsWith('512')) { 'SHA512' } else { 'SHA256' }
                $wantH = ((Get-Content -LiteralPath $hf -TotalCount 1) -split '\s+')[0].ToLowerInvariant()
                $got = (Get-FileHash -LiteralPath $f -Algorithm $alg).Hash.ToLowerInvariant()
                if ($wantH -eq $got) { $o.hashFile = "match ($(Split-Path -Leaf $hf))" }
                else { $o.hashFile = "MISMATCH ($(Split-Path -Leaf $hf))"; $R.St = 'tampered'; $R.Note = (@($R.Note, "the file differs from $(Split-Path -Leaf $hf)") | Where-Object { $_ }) -join '; '; break }
            }
            $o.fileSha256 = (Get-FileHash -LiteralPath $f -Algorithm SHA256).Hash.ToLowerInvariant()
            $o.fileSha512 = (Get-FileHash -LiteralPath $f -Algorithm SHA512).Hash.ToLowerInvariant()
        }
        # the verdict
        $verdict = switch ($R.St) { 'signed' { if ($problems.Count -gt 0) { 'FAILED' } else { 'VERIFIED' } } 'unsigned' { 'UNSIGNED' } 'tampered' { 'TAMPERED' } default { 'ERROR' } }
        $o.result = $verdict; $o.note = $R.Note; $o.digest = $R.Digest; $o.timestamp = $R.TsText; $o.timestampServer = $R.TsServer
        $line = { param($l, $v) Write-Host ('  {0,-14}: {1}' -f $l, $v) }
        & $line 'Result' ($verdict + $(if ($R.Note) { "  ($($R.Note))" }))
        if ($o.subject) {
            & $line 'Signed by' $o.subject; & $line 'Issuer' $o.issuer; & $line 'Serial' $o.serial; & $line 'Valid' "$($o.notBefore)  to  $($o.notAfter)"
            & $line 'Key' $o.key; & $line 'Digest' $(if ($o.digest) { $o.digest } else { 'unknown' }); & $line 'Purposes' $(if ($eku) { $eku } else { 'none listed' })
            & $line 'Cert SHA-256' $o.certSha256; & $line 'Cert SHA-512' $o.certSha512
            & $line 'Timestamp' ($o.timestamp + $(if ($o.timestampServer) { "  by $($o.timestampServer)" })); & $line 'Chain' $o.chain
        }
        & $line 'Hash file' $o.hashFile; & $line 'File SHA-256' $o.fileSha256; & $line 'File SHA-512' $o.fileSha512
        foreach ($w in $warns) { Write-Say 'WARN' "${f}: $w" }
        foreach ($p in $problems) { Write-Say 'ERROR' "${f}: $p" }
        switch ($verdict) {
            'VERIFIED' { $nOk++; Write-Say 'OK' "${f}: signed, unchanged$(if ($o.chain -eq 'trusted') { ', trusted' })." }
            'UNSIGNED' { $failed++; Write-Say 'ERROR' "${f}: NOT signed." }
            'TAMPERED' { $failed++; Write-Say 'ERROR' "${f}: TAMPERED - changed after signing. Do not ship it." }
            default { $failed++; if ($verdict -eq 'ERROR') { Write-Say 'ERROR' "${f}: could not be checked. $($R.Note)" } }
        }
        $o.messages = @($problems) + @($warns)
        $rows.Add([pscustomobject]$o)
    }

    # ---------------------------------------------------------------- summary
    Write-Host '===== SUMMARY ======================================================================'
    foreach ($r in $rows) { Write-Host ('  {0,-9} {1,-13} {2,-10} {3}' -f $r.result, $r.kind, $(if ($r.key) { $r.key } else { '-' }), $r.file) }
    if ($ReportFolder) {
        [void](New-Item -ItemType Directory -Path $ReportFolder -Force)
        $rep = Join-Path $ReportFolder ("verify-report_{0}.json" -f [DateTime]::UtcNow.ToString('yyyyMMdd-HHmmss'))
        $doc = [ordered]@{ tool = 'Verify-CodeSign.ps1'; version = $script:ToolVersion; time = [DateTime]::UtcNow.ToString('yyyy-MM-ddTHH:mm:ssZ'); verified = $nOk; failed = $failed; files = @($rows) }
        [System.IO.File]::WriteAllText($rep, ($doc | ConvertTo-Json -Depth 5), [System.Text.UTF8Encoding]::new($false))
        Write-Say 'INFO' "Report: $rep"
    }
    if ($script:Env -eq 'github' -and $env:GITHUB_STEP_SUMMARY) { Add-Content -LiteralPath $env:GITHUB_STEP_SUMMARY -Value "### Verify-CodeSign: $nOk verified, $failed failed (of $($list.Count))" }
    if ($failed -gt 0) { Stop-Verify 6 "Verified $nOk, FAILED $failed (of $($list.Count))." }
    Write-Say 'OK' "Verified $nOk of $($list.Count): signed, unchanged and within the rules."
}
catch [VerifyExit] { Write-Say 'ERROR' $_.Exception.Message; $exit = $_.Exception.Code }
catch { Write-Say 'ERROR' "$($_.Exception.Message) (line $($_.InvocationInfo.ScriptLineNumber))"; $exit = 1 }
finally {
    if ($work -and (Test-Path -LiteralPath $work)) { Remove-Item -LiteralPath $work -Recurse -Force -ErrorAction SilentlyContinue }
}
exit $exit
