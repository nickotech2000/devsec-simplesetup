    function Select-Signer($Certs) {  # the code-signing leaf: not a CA, with the Code Signing purpose first
        $best = $null; $second = $null
        foreach ($c in $Certs) {
            $bc = $c.Extensions | Where-Object { $_ -is [System.Security.Cryptography.X509Certificates.X509BasicConstraintsExtension] }
            if ($bc -and $bc.CertificateAuthority) { continue }
            $eku = $c.Extensions | Where-Object { $_ -is [System.Security.Cryptography.X509Certificates.X509EnhancedKeyUsageExtension] }
            if ($eku -and ($eku.EnhancedKeyUsages | Where-Object { $_.Value -eq '1.3.6.1.5.5.7.3.3' })) { if (-not $best) { $best = $c } } elseif (-not $second) { $second = $c }
        }
        if ($best) { return $best }; if ($second) { return $second }; if ($Certs.Count -gt 0) { return $Certs[0] }; return $null
    }

