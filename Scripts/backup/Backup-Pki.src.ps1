        $rel = $f.FullName.Substring($root.Length).TrimStart('\', '/') -replace '\\', '/'
        if (Test-BkExcluded -Rel $rel -Inventory $inv) { [void]$skipped.Add($rel); continue }
        [void]$items.Add(@{ Source = $f.FullName; Entry = "data/$rel"; Rel = $rel })
