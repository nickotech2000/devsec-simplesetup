  5. Copy backup-pki\pki-payload-....zip to ANOTHER disk or computer.
  6. Check the copy:                                .\Test-PkiBackup.ps1 -Backup <the copy>

WHAT IS BACKED UP
  pki\ (all PKIs, all releases, all keys), leafcerts\, external-ca\, csr-signed\, every
