function Add-BkTree {
    param([string]$Dir)
    foreach ($sd in @(Get-ChildItem -LiteralPath $Dir -Recurse -Directory -Force) + @(Get-Item -LiteralPath $Dir)) {
        $r = (($sd.FullName.Substring($root.Length).TrimStart('\', '/')) -replace '\\', '/')
