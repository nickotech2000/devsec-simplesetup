  nothing.

QUICK START
  1. Open PowerShell 7 as administrator.
  2. In the unzipped backup folder:       .\Test-PkiBackup.ps1
  3. For a zip or a whole backup folder:  .\Test-PkiBackup.ps1 -Backup .\backup-pki
