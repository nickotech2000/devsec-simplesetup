# Build-BackupScripts.ps1  -  maker of the three STANDALONE backup scripts (a maintainer tool, not for users)
#
# Backup-Pki.ps1, Restore-Pki.ps1 and Test-PkiBackup.ps1 in the project root must not depend on any other .ps1 (they travel alone inside a backup zip).
# Their source is here:  Backup-Pki.src.ps1  Restore-Pki.src.ps1  Test-PkiBackup.src.ps1  (each has the line  #@@EMBED-LIBRARY@@ )
# plus the shared code  PkiBackupCommon.ps1  and the zip engine  ..\16_CertPack.ps1 (the zip / AES part only). This script pastes the shared code
# into each source and writes the finished script to the project root. Edit the sources, run this, never edit the three root scripts by hand.
#     pwsh -File .\scripts\backup\Build-BackupScripts.ps1
# ============================================================
param([string]$ProjectRoot)
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
if (-not $ProjectRoot) { $ProjectRoot = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path }
$common = [System.IO.File]::ReadAllText((Join-Path $PSScriptRoot 'PkiBackupCommon.ps1'))
$pack = [System.IO.File]::ReadAllText((Join-Path $ProjectRoot 'Scripts/16_CertPack.ps1'))

# the zip / AES engine only: everything before the 7-Zip section
$cut = $pack.IndexOf("# ------------------------------------------------------------`n# 7-Zip")
if ($cut -lt 0) { $cut = $pack.IndexOf("# ------------------------------------------------------------`r`n# 7-Zip") }
if ($cut -lt 0) { throw 'The 7-Zip marker was not found in 16_CertPack.ps1' }
$engine = $pack.Substring(0, $cut)
$engine = ($engine -split "`r?`n" | Where-Object { $_ -notmatch '^\s*Set-StrictMode|^\s*\$ErrorActionPreference' }) -join "`n"
$tail = @'

function Expand-PkiArchive {
    # a backup .certpacked is always a zip with AES-256: extracts it (or only tests it when -Destination is empty)
    param([Parameter(Mandatory)][string]$Path, [string]$Destination, [Parameter(Mandatory)][string]$Password, [string[]]$Prefix)
    if ((Get-PkiArchiveType -Path $Path) -ne 'zip') { throw "$Path is not a zip archive (first bytes not recognised): it is not a PKI backup, or it is damaged." }
    return (Expand-PkiAesZipArchive -Path $Path -Destination $Destination -Password $Password -Prefix $Prefix)
}
'@
$common = ($common -split "`r?`n" | Where-Object { $_ -notmatch '^\s*Set-StrictMode|^\s*\$ErrorActionPreference = ' }) -join "`n"
$embed = "#region embedded library (generated by scripts\backup\Build-BackupScripts.ps1 - do not edit here)`n" + $common + "`n`n# ---- zip / AES-256 engine (from scripts\16_CertPack.ps1)`n" + $engine + $tail + "`n#endregion embedded library`nSet-StrictMode -Version Latest`n"
foreach ($n in 'Backup-Pki', 'Restore-Pki', 'Test-PkiBackup') {
    $src = [System.IO.File]::ReadAllText((Join-Path $PSScriptRoot "$n.src.ps1"))
    if ($src -notmatch '#@@EMBED-LIBRARY@@') { throw "$n.src.ps1 has no #@@EMBED-LIBRARY@@ line" }
    $out = $src.Replace('#@@EMBED-LIBRARY@@', $embed)
    $out = ($out -replace "`r`n", "`n")
    # Windows PowerShell 5.1 reads a file without BOM as ANSI: the standalone scripts stay pure ASCII
    $out = $out.Replace([string][char]0x00DC, 'U')
    if ($out -match '[^\x00-\x7F]') { throw "$n.ps1 would hold a non-ASCII character: write it as ASCII in the source" }
    [System.IO.File]::WriteAllText((Join-Path $ProjectRoot "$n.ps1"), $out, [System.Text.UTF8Encoding]::new($false))
    Write-Host ("[OK] {0}.ps1  ({1:N0} KB, standalone)" -f $n, ($out.Length / 1KB))
}
