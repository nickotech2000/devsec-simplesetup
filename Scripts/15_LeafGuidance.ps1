# 15_LeafGuidance.ps1  -  what GenerateLeafCertificate.ps1 writes NEXT TO a leaf
#
#   convert-formats.ps1   Clean PowerShell: the exact OpenSSL syntax to convert THIS leaf between every
#                         format (PEM, DER, CER, CERT, P7B, RFC 7468, PKCS#8, PKCS#12), with its real file
#                         names and the real OpenSSL path. Nothing but code and one-line headings.
#   tls-guidance.txt      TLS 1.2 / 1.3, HTTP/2, HTTP/3 (QUIC): protocols, cipher suites, key-exchange
#                         groups and server settings for this leaf's profile (Classic, FIPS or Quantum).
#
# Provides : Get-PkiLeafConversionScript, Get-PkiLeafTlsGuidance, Write-PkiLeafGuidance
# Requires : 14_LeafGenerator (Spec and result), 13_ExternalRoot (Get-PkiTrustAnchor)
# ============================================================
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

function ConvertTo-PkiPsLiteral {
    # a safe single-quoted PowerShell string
    param([Parameter(Mandatory)][string]$Text)
    return "'" + ($Text -replace "'", "''") + "'"
}

# ------------------------------------------------------------
# convert-formats.ps1
# ------------------------------------------------------------
function Get-PkiLeafConversionScript {
    param([Parameter(Mandatory)][hashtable]$Spec, [Parameter(Mandatory)][hashtable]$R)
    $stem = $R.Stem
    $anchor = (Get-PkiTrustAnchor).Anchor
    $fam = $R.Actual.Family
    $L = [System.Collections.Generic.List[string]]::new()
    $add = { param($t) [void]$L.Add($t) }

    & $add "# convert-formats.ps1 - $stem"
    & $add "# Generated by GenerateLeafCertificate.ps1 $($script:PkiGeneratorVersion). Run a block, or the whole file, from this folder."
    & $add "`$openssl = $(ConvertTo-PkiPsLiteral $script:Pki.OpenSslExe)"
    & $add "`$stem    = $(ConvertTo-PkiPsLiteral $stem)"
    & $add "`$name    = $(ConvertTo-PkiPsLiteral $Spec.FriendlyName)"
    & $add "`$rootCa  = $(ConvertTo-PkiPsLiteral $anchor)"
    & $add "`$pfxPassword = Read-Host 'PFX password'"
    & $add 'Set-Location -LiteralPath $PSScriptRoot'
    & $add ''
    & $add '# Certificate: PEM -> DER, CER (DER binary, opens in Windows), DER -> PEM'
    & $add '& $openssl x509 -in "$stem.crt" -outform DER -out "$stem.der" -provider default'
    & $add 'Copy-Item -LiteralPath "$stem.der" -Destination "$stem.cer" -Force'
    & $add '& $openssl x509 -in "$stem.der" -inform DER -outform PEM -out "$stem.pem" -provider default'
    & $add ''
    & $add '# Certificate: PEM text under the extensions .crt .pem .cert'
    & $add 'Copy-Item -LiteralPath "$stem.crt" -Destination "$stem.cert" -Force'
    & $add ''
    & $add '# Certificate: RFC 7468 strict PEM (64-character lines, LF only, no text around the block)'
    & $add '$b64   = [Convert]::ToBase64String([IO.File]::ReadAllBytes((Join-Path $PWD "$stem.der")))'
    & $add '$lines = for ($i = 0; $i -lt $b64.Length; $i += 64) { $b64.Substring($i, [Math]::Min(64, $b64.Length - $i)) }'
    & $add '[IO.File]::WriteAllText((Join-Path $PWD "$stem.rfc7468.pem"), "-----BEGIN CERTIFICATE-----`n" + ($lines -join "`n") + "`n-----END CERTIFICATE-----`n")'
    & $add ''
    & $add '# Certificate chain: PKCS#7 (.p7b), PEM and DER; and back to PEM certificates'
    & $add '& $openssl crl2pkcs7 -nocrl -certfile "$stem-fullchain.crt" -out "$stem.p7b" -provider default'
    & $add '& $openssl crl2pkcs7 -nocrl -certfile "$stem-fullchain.crt" -outform DER -out "$stem.p7b.der" -provider default'
    & $add '& $openssl pkcs7 -in "$stem.p7b" -print_certs -out "$stem.p7b-certs.pem" -provider default'
    & $add ''
    & $add '# Private key (PKCS#8, RFC 7468 label PRIVATE KEY): PEM -> DER, encrypted, decrypted'
    & $add '& $openssl pkey -in "$stem.key" -outform DER -out "$stem.key.der" -provider default'
    & $add '& $openssl pkcs8 -topk8 -in "$stem.key" -v2 aes-256-cbc -out "$stem.key.enc.pem" -passout "pass:$pfxPassword" -provider default'
    & $add '& $openssl pkey -in "$stem.key.enc.pem" -passin "pass:$pfxPassword" -out "$stem.key.dec.pem" -provider default'
    switch ($fam) {
        'rsa'   { & $add ''; & $add '# RSA key: traditional PKCS#1 (BEGIN RSA PRIVATE KEY)'; & $add '& $openssl pkey -in "$stem.key" -traditional -out "$stem.key.rsa.pem" -provider default' }
        'ecdsa' { & $add ''; & $add '# ECDSA key: traditional SEC1 (BEGIN EC PRIVATE KEY)'; & $add '& $openssl pkey -in "$stem.key" -traditional -out "$stem.key.ec.pem" -provider default' }
        default { & $add ''; & $add '# ML-DSA key: PKCS#8 is the only private-key format (no traditional form exists)' }
    }
    & $add ''
    & $add '# PKCS#12 (.pfx): create (certificate, key, chain), list, extract'
    & $add '& $openssl pkcs12 -export -inkey "$stem.key" -in "$stem.crt" -certfile "$stem-chain.crt" -name $name -out "$stem.new.pfx" -passout "pass:$pfxPassword" -provider default'
    & $add '& $openssl pkcs12 -in "$stem.pfx" -info -noout -passin "pass:$pfxPassword" -provider default'
    & $add '& $openssl pkcs12 -in "$stem.pfx" -nodes -out "$stem.pfx-all.pem" -passin "pass:$pfxPassword" -provider default'
    & $add '& $openssl pkcs12 -in "$stem.pfx" -nokeys -clcerts -out "$stem.pfx-leaf.pem" -passin "pass:$pfxPassword" -provider default'
    & $add '# PKCS#12 for very old software (3DES / SHA-1)'
    & $add '& $openssl pkcs12 -export -inkey "$stem.key" -in "$stem.crt" -certfile "$stem-chain.crt" -keypbe PBE-SHA1-3DES -certpbe PBE-SHA1-3DES -macalg sha1 -out "$stem.legacy.pfx" -passout "pass:$pfxPassword" -provider default'
    & $add ''
    & $add '# Inspect and verify'
    & $add '& $openssl x509 -in "$stem.crt" -noout -text -provider default'
    & $add '& $openssl x509 -in "$stem.crt" -noout -fingerprint -sha256 -provider default'
    & $add '& $openssl x509 -in "$stem.crt" -noout -subject -issuer -dates -provider default'
    & $add '& $openssl verify -CAfile $rootCa -untrusted "$stem-chain.crt" -provider default "$stem.crt"'
    return (($L -join "`r`n") + "`r`n")
}

# ------------------------------------------------------------
# tls-guidance.txt
# ------------------------------------------------------------
function Get-PkiLeafTlsGuidance {
    param([Parameter(Mandatory)][hashtable]$Spec, [Parameter(Mandatory)][hashtable]$R)
    $stem = $R.Stem
    $quantum = ($Spec.Track -eq 'Quantum')
    $fips = [bool]$Spec.Fips
    $fam = $R.Actual.Family
    $profileText = "$(if ($quantum) { 'QUANTUM' } else { 'CLASSIC' }) $(if ($fips) { 'FIPS' } else { 'non-FIPS' })   leaf $($R.Actual.Algorithm)"

    $suites13 = if ($fips) { 'TLS_AES_256_GCM_SHA384:TLS_AES_128_GCM_SHA256' } else { 'TLS_AES_256_GCM_SHA384:TLS_CHACHA20_POLY1305_SHA256:TLS_AES_128_GCM_SHA256' }
    $kex = if ($fam -eq 'rsa') { 'RSA' } else { 'ECDSA' }
    $suites12 = @("ECDHE-$kex-AES256-GCM-SHA384", "ECDHE-$kex-AES128-GCM-SHA256")
    if (-not $fips) { $suites12 += "ECDHE-$kex-CHACHA20-POLY1305" }
    $suites12s = $suites12 -join ':'
    $groups = if ($fips) { 'SecP256r1MLKEM768:SecP384r1MLKEM1024:secp256r1:secp384r1' } else { 'X25519MLKEM768:X25519:secp256r1:secp384r1' }
    $groupsNginx = if ($fips) { '?SecP256r1MLKEM768:?SecP384r1MLKEM1024:prime256v1:secp384r1' } else { '?X25519MLKEM768:X25519:prime256v1:secp384r1' }
    $firstGroup = $groups.Split(':')[0]
    $sigalg = switch ($fam) {
        'rsa'   { 'rsa_pss_rsae_sha256 / rsa_pss_rsae_sha384 (TLS 1.3), rsa_pkcs1_sha256 (TLS 1.2)' }
        'ecdsa' { 'ecdsa_secp256r1_sha256 / ecdsa_secp384r1_sha384' }
        default { $R.Actual.Algorithm.ToLowerInvariant().Replace('-', '') }
    }
    $dir = "/etc/pki/$($Spec.Folder)"
    $crt = "$dir/$stem-fullchain.crt"; $key = "$dir/$stem.key"
    $protocols = if ($quantum) { 'TLS 1.3 only (ML-DSA signature schemes exist only in TLS 1.3)' } else { 'TLS 1.3 and TLS 1.2 (TLS 1.0 / 1.1 off)' }
    $sslProto = if ($quantum) { 'TLSv1.3' } else { 'TLSv1.3 TLSv1.2' }
    $peerSig = if ($quantum) { '   Peer signature type: ' + $R.Actual.Algorithm.ToLowerInvariant().Replace('-', '') } else { '' }

    $t = [System.Text.StringBuilder]::new()
    $w = { param($x) [void]$t.AppendLine($x) }
    & $w "TLS GUIDANCE  -  $stem"
    & $w "Generated by GenerateLeafCertificate.ps1 $($script:PkiGeneratorVersion)   $([DateTime]::Now.ToString('yyyy-MM-dd HH:mm'))"
    & $w ('=' * 100)
    & $w "Profile : $profileText"
    & $w "Level   : $($Spec.Level)   Issuer: $($Spec.Ca.Id)   Valid until $($R.NotAfter)   Purposes: $($Spec.Eku -join ', ')"
    & $w "Key pair: $stem.key (private, PKCS#8)  +  $stem.pub (public key, PEM)  +  $stem.pub.der (public key, DER)"
    & $w 'Line endings: every PEM file is written with LF only (no CRLF, no BOM). OpenSSL 3.5+ on Linux (nginx on Ubuntu 26.04) refuses a key with CRLF'
    & $w '  ("PEM_read_bio_PrivateKey() failed ... No supported data to decode"). If you edited a file on Windows:  sed -i "s/\r$//" <file>'
    if ($quantum) { & $w "Files   : $stem-fullchain.crt + $stem.key  (OpenSSL-based servers: nginx, Apache, Node.js, Python)" }
    else { & $w "Files   : $stem-fullchain.crt + $stem.key  (nginx, Apache, Node, Go, Python)    $stem.pfx  (Kestrel, IIS)" }
    & $w ''
    & $w 'PROTOCOLS AND SUITES'
    & $w "  Protocols        $protocols"
    & $w "  TLS 1.3 suites   $suites13"
    if (-not $quantum) { & $w "  TLS 1.2 suites   $suites12s   (AEAD only, forward secrecy)" }
    & $w "  Key exchange     $groups"
    & $w "  Signature        $sigalg"
    if ($fips) {
        & $w '  FIPS             AES-GCM only: ChaCha20-Poly1305 and X25519 are left out of this profile. Use the FIPS provider /'
        & $w '                   a FIPS-validated library on the server; the group names above need OpenSSL 3.5 or newer.'
    }
    else {
        & $w '  Hybrid groups    X25519MLKEM768 is the post-quantum key exchange browsers, Windows 11 and OpenSSL 3.5+ negotiate.'
    }
    & $w ''
    & $w 'HTTP/2 AND HTTP/3'
    & $w '  HTTP/2   ALPN "h2,http/1.1" over TLS 1.2 or 1.3 with the AEAD suites above (nginx: http2 on;  Apache: Protocols h2 http/1.1).'
    & $w '  HTTP/3   QUIC over UDP 443, TLS 1.3 only. Advertise it with  Alt-Svc: h3=":443"; ma=86400  and open UDP 443.'
    & $w '           nginx: listen 443 quic reuseport;   Kestrel: ListenOptions.Protocols = Http1AndHttp2AndHttp3.'
    & $w '           The same certificate serves HTTP/1.1, HTTP/2 and HTTP/3.'
    & $w ''

    if ($quantum) {
        & $w 'THIS IS AN ML-DSA (POST-QUANTUM) CERTIFICATE'
        & $w '  Works with OpenSSL 3.5+ clients and servers (nginx, Apache, Node.js, Python, curl, Kestrel on Linux).'
        & $w '  NOT accepted for HTTPS by Windows Schannel (Kestrel / IIS on Windows), Java 25 or the browsers today.'
        & $w '  Browser-facing sites and Windows servers: issue a Classic leaf (no -Quantum). An OpenSSL server can hold both.'
        & $w '  The chain is large (ML-DSA signatures are 3 to 5 KB each): check header / handshake size limits of proxies.'
        & $w ''
    }

    & $w 'SERVER SETTINGS (adjust the paths)'
    & $w '  nginx'
    & $w '    listen 443 ssl; listen 443 quic reuseport; http2 on;'
    & $w "    ssl_certificate $crt;"
    & $w "    ssl_certificate_key $key;"
    & $w "    ssl_protocols $sslProto;"
    & $w "    ssl_conf_command Ciphersuites $suites13;"
    if (-not $quantum) { & $w "    ssl_ciphers $suites12s;" }
    & $w "    ssl_ecdh_curve $groupsNginx;"
    & $w '    add_header Alt-Svc ''h3=":443"; ma=86400'';'
    & $w '  Apache httpd 2.4 (mod_ssl with OpenSSL 3.5+)'
    & $w "    SSLProtocol $(if ($quantum) { '-all +TLSv1.3' } else { '-all +TLSv1.3 +TLSv1.2' })"
    & $w "    SSLCertificateFile $crt"
    & $w "    SSLCertificateKeyFile $key"
    & $w "    SSLOpenSSLConfCmd Ciphersuites $suites13"
    & $w "    SSLOpenSSLConfCmd Groups $groups"
    if (-not $quantum) { & $w "    SSLCipherSuite $suites12s" }
    & $w '    Protocols h2 http/1.1'
    if (-not $quantum) {
        & $w "  Kestrel (.NET 10 / 11), certificate $stem.pfx"
        & $w '    options.SslProtocols = SslProtocols.Tls13 | SslProtocols.Tls12;     // do not hard-code groups: Schannel / OpenSSL negotiate them'
        & $w ('    options.ListenAnyIP(443, o => { o.UseHttps("' + $stem + '.pfx", password); o.Protocols = HttpProtocols.Http1AndHttp2AndHttp3; });')
    }
    & $w '  Node.js'
    & $w "    https.createServer({ key: fs.readFileSync('$stem.key'), cert: fs.readFileSync('$stem-fullchain.crt'), minVersion: '$(if ($quantum) { 'TLSv1.3' } else { 'TLSv1.2' })', ecdhCurve: '$groups' }, handler)"
    if (-not $quantum) {
        & $w '  Go'
        & $w "    cert, _ := tls.LoadX509KeyPair(`"$stem-fullchain.crt`", `"$stem.key`")   // tls.Config{MinVersion: tls.VersionTLS12} offers hybrid ML-KEM by default (Go 1.24+)"
    }
    & $w ''
    & $w 'CHECK IT'
    & $w "  openssl s_client -connect <host>:443 -servername <name> -CAfile <pki>\root\root.crt -groups $firstGroup < NUL"
    & $w "  Expect: Verification: OK   Negotiated TLS1.3 group: $firstGroup$peerSig"
    & $w '  curl --http2 / --http3 -I https://<name>/     (the HTTP version is in the first line of the answer)'
    & $w ''
    & $w 'Clients must trust pki\root\root.crt (manual, section 7). Keep the .key file private (mode 600 / owner only).'
    return $t.ToString()
}

function Write-PkiLeafGuidance {
    param([Parameter(Mandatory)][hashtable]$Spec, [Parameter(Mandatory)][hashtable]$R, [switch]$NoTls)
    $conv = Join-Path $R.Dir 'convert-formats.ps1'
    $tls = Join-Path $R.Dir 'tls-guidance.txt'
    [System.IO.File]::WriteAllText($conv, (Get-PkiLeafConversionScript -Spec $Spec -R $R), [System.Text.UTF8Encoding]::new($true))   # BOM: Windows PowerShell 5.1 reads it too
    if ($NoTls) { return @($conv) }          # code signing, S/MIME, time stamping, OCSP: no TLS server settings
    Write-Utf8NoBom -Path $tls -Content (Get-PkiLeafTlsGuidance -Spec $Spec -R $R)
    return @($conv, $tls)
}
