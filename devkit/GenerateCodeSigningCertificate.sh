cs_extras() {  # <dir> <stem> <token> <platforms>: the formats of --format (7.6.4); every key store has the PFX password
  local d="$1" s="$2" tok="$3" plats="$4" alias
  alias="$(printf '%s-%s' "$NAME" "$tok" | tr 'A-Z' 'a-z' | sed 's/[^a-z0-9._-]\{1,\}/_/g; s/__*/_/g; s/^[_.-]*//; s/[_.-]*$//')"
  CS_ALIAS="$alias"; CS_KS=""
  has_fmt p12 && cp "$d/$s.pfx" "$d/$s.p12"
  if has_fmt keystore || has_fmt jks; then
    ossl pkcs12 -export -inkey "$d/$s.key" -in "$d/$s.crt" -certfile "$CA_CHAIN" -name "$alias" -out "$d/$s.keystore" -passout env:PKI_PFX_PASSWORD \
      && CS_KS="$s.keystore" && pki_ok "  key store : $s.keystore  (PKCS#12, alias $alias)"
  fi
  if has_fmt jks && [ -n "$CS_KS" ]; then
    rm -f "$d/$s.jks"
    if "$KEYTOOL" -J-Duser.language=en -importkeystore -noprompt -srckeystore "$d/$s.keystore" -srcstoretype PKCS12 -srcstorepass:env PKI_PFX_PASSWORD -srcalias "$alias" \
         -destkeystore "$d/$s.jks" -deststoretype JKS -deststorepass:env PKI_PFX_PASSWORD -destkeypass:env PKI_PFX_PASSWORD -destalias "$alias" >/dev/null 2>&1; then
      pki_ok "  key store : $s.jks  (JKS, alias $alias)"
    else pki_warn "  .jks not made (keytool failed)"; rm -f "$d/$s.jks"; fi
    has_fmt keystore || { rm -f "$d/$s.keystore"; CS_KS=""; }
  fi
  if has_fmt pvk; then
    if [ "$KEYTYPE" = rsa ]; then
      ossl rsa -in "$d/$s.key" -outform PVK -pvk-strong -passout env:PKI_PFX_PASSWORD -out "$d/$s.pvk" -provider legacy -provider default 2>/dev/null \
        || { rm -f "$d/$s.pvk"; pki_warn "  .pvk not made (needs the OpenSSL legacy provider)"; }
    else pki_info "  .pvk not made: the PVK format holds RSA keys only."; fi
  fi
  has_fmt spc && ossl crl2pkcs7 -nocrl -certfile "$d/$s-fullchain.crt" -outform DER -out "$d/$s.spc"
  has_fmt vs && cs_visualstudio "$d" "$s" "$plats"
  return 0
}

