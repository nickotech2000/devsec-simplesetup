issue_cs() {  # <token> <platforms (space list)>
  local tok="$1" plats="$2" dir="$RUN/$1" eku="" days dv p ku="digitalSignature" ktag stem cnf polcab=""
  for p in $plats; do case "$p" in apple-installer) eku="$eku${eku:+,}1.2.840.113635.100.4.13" ;; *) case ",$eku," in *,codeSigning,*) ;; *) eku="codeSigning${eku:+,}$eku" ;; esac ;; esac; done
  case " $plats " in *" windows "*) [ $LIFETIME = 1 ] && eku="$eku,1.3.6.1.4.1.311.10.3.13"; [ $KERNEL = 1 ] && eku="$eku,1.3.6.1.4.1.311.61.1.1" ;; esac
  days="$DAYS"
  if [ -z "$days" ]; then if [ "$LEVEL" = EV ]; then days=397; else case " $plats " in *" android "*) days=9125 ;; *) days=1095 ;; esac; fi; fi
  [ "$LEVEL" = EV ] && [ "$days" -gt 397 ] && pki_die "an EV certificate may not be valid longer than 397 days"
  local room; room=$(( ( $(date -d "$("$OPENSSL" x509 -in "$CA_CRT" -noout -enddate | cut -d= -f2)" +%s) - $(date +%s) ) / 86400 - 1 ))
  [ "$days" -gt "$room" ] && { pki_warn "validity limited by the issuer: $days -> $room days"; days=$room; }
  case " $plats " in *" android "*) [ "$days" -lt 9125 ] && pki_warn "Android: the app signing key is valid $days days; Google Play wants a key valid after 2033 (use --ov and a long --days)." ;; esac
  if [ "$KEYTYPE" = rsa ]; then ktag="rsa$KEYBITS"; else ktag="ecdsa-$(printf '%s' "$CURVE" | tr -d '-' | tr 'P' 'p')"; fi
  stem="$NAME-codesign-$tok-$(pki_lc "$LEVEL")-q$QUAD-$ktag"
  mkdir -p "$dir"; cnf="$dir/$stem.cnf"; pki_author_hdr > "$cnf"
  pki_write_dn "$cnf" "$DN"
  POLICY_REFS=""
  if [ "$HAVE_ENV" = 1 ]; then
    PCNT=0; pki_write_policies "$cnf" "$LEVEL"
    # the CA/B Forum CODE SIGNING policy replaces the TLS level policy (2.23.140.1.1 / 2.23.140.1.2.x)
    if [ $CABF = 1 ]; then
      local keep="" r; for r in $(printf '%s' "$POLICY_REFS" | tr ',' ' '); do grep -A1 "^\[ ${r#@} \]" "$cnf" | grep -qE 'policyIdentifier = 2\.23\.140\.1\.(1|2\.[12])$' || keep="$keep${keep:+,}$r"; done
      POLICY_REFS="$keep"
    fi
  fi
  if [ $CABF = 1 ]; then polcab="$([ "$LEVEL" = EV ] && echo 2.23.140.1.3 || echo 2.23.140.1.4.1)"; POLICY_REFS="$POLICY_REFS${POLICY_REFS:+,}$polcab"; fi
  EXT_CRL=""; EXT_AIA=""; [ -n "$CA_SLUG" ] && pki_write_location "$cnf" "$CA_SLUG" "$NOCRL" "$NOOCSP"
  {
    printf '[ ext ]\nbasicConstraints = critical,CA:false\nkeyUsage = critical,%s\nextendedKeyUsage = %s\n' "$ku" "$eku"
    printf 'subjectKeyIdentifier = hash\nauthorityKeyIdentifier = keyid,issuer\n'
    [ -n "$POLICY_REFS" ] && printf 'certificatePolicies = %s\n' "$POLICY_REFS"
    [ -n "$EXT_CRL" ] && printf '%s\n' "$EXT_CRL"
    [ -n "$EXT_AIA" ] && printf '%s\n' "$EXT_AIA"
  } >> "$cnf"
  vlog "config $cnf:"; [ "$VERBOSE" = 1 ] && sed 's/^/          /' "$cnf" >&2
  pki_gen_key "$dir/$stem.key" "$KEYTYPE" "$KEYBITS" "$CURVE"
  vlog "openssl x509 -req -CA $CA_CRT -days $days -$MD -extfile $cnf -extensions ext"
  pki_sign "$cnf" "$dir/$stem.key" "$dir/$stem.crt" "$days" "$MD"
  pki_package "$dir" "$stem" "$PFXPW"
  # every format, like GenerateLeafCertificate
  cp "$dir/$stem.crt" "$dir/$stem.pem"; cp "$dir/$stem.crt" "$dir/$stem.cert"
  ossl x509 -in "$dir/$stem.crt" -outform DER -out "$dir/$stem.der"; cp "$dir/$stem.der" "$dir/$stem.cer"
  ossl crl2pkcs7 -nocrl -certfile "$dir/$stem-fullchain.crt" -out "$dir/$stem.p7b"
  { echo '-----BEGIN CERTIFICATE-----'; base64 -w 64 "$dir/$stem.der"; echo '-----END CERTIFICATE-----'; } > "$dir/$stem.rfc7468.pem"
  ossl pkey -in "$dir/$stem.key" -pubout -outform DER -out "$dir/$stem.pub.der"
  # checks: the chain, the purpose, the key
  local anchor="$dir/.anchor.tmp.pem"
  if [ "$EXTERNAL" = 1 ]; then cat "$CA_CHAIN" > "$anchor"; ossl verify -partial_chain -CAfile "$anchor" "$dir/$stem.crt" >/dev/null 2>&1 || pki_die "chain verification FAILED for $stem"; rm -f "$anchor"
  else pki_verify "$dir/$stem.crt" "$NOCRL" "$NOOCSP"; fi
  "$OPENSSL" x509 -in "$dir/$stem.crt" -noout -ext extendedKeyUsage | grep -qE 'Code Signing|1\.2\.840\.113635\.100\.4\.13' || pki_die "$stem: the code signing purpose is missing"
  pki_hash_files "$dir" "$stem" "$HASHFILES"
  local sha1 na; sha1="$("$OPENSSL" x509 -in "$dir/$stem.crt" -noout -fingerprint -sha1 | cut -d= -f2 | tr -d :)"; na="$(date -d "$("$OPENSSL" x509 -in "$dir/$stem.crt" -noout -enddate | cut -d= -f2)" +%Y-%m-%d)"
  cs_extras "$dir" "$stem" "$tok" "$plats"
  printf '{\n  "tool": "GenerateCodeSigningCertificate.sh %s",\n  "name": "%s", "platforms": "%s", "level": "%s", "quadrant": %s,\n  "issuer": "%s", "serial": "%s", "subject": "%s",\n  "extendedKeyUsage": "%s", "hash": "%s", "days": %s, "notAfter": "%s", "sha1": "%s",\n  "keyAlias": "%s", "keystore": "%s"\n}\n' \
    "$VERSION" "$stem" "$plats" "$LEVEL" "$QUAD" "$ISS_LABEL" "$PKI_LAST_SERIAL" "${DN//|/, }" "$eku" "$MD" "$days" "$na" "$sha1" "$CS_ALIAS" "$CS_KS" > "$dir/leaf-info.json"
  {
    echo "Code signing certificate - $plats"; echo "Subject : ${DN//|/, }"; echo "Issuer  : $ISS_LABEL   Level $LEVEL   valid until $na   SHA-1 $sha1"
    echo "PFX     : $stem.pfx (password from --pfx-password; default Abc12345! = lab password, CHANGE IT)"; echo
    echo "Sign:  export SIGN_PFX_PASSWORD='<password>';  ./Sign-Code.sh --pfx $stem.pfx --file <file> --verbose"
    echo "       ./Sign-Code.sh --use-generated --folder <build output>   (finds this certificate by platform)"
    case " $plats " in *" windows "*) echo "Windows : osslsigncode sign -pkcs12 $stem.pfx -pass <pw> -h sha256 -ts http://timestamp.digicert.com -in a.exe -out a-signed.exe" ;; esac
    case " $plats " in *" java "*) echo "Java    : jarsigner -keystore $stem.pfx -storetype PKCS12 -tsa http://timestamp.digicert.com app.jar <alias>" ;; esac
    case " $plats " in *" android "*) echo "Android : apksigner sign --ks $stem.pfx --ks-type PKCS12 --ks-pass env:SIGN_PFX_PASSWORD app.apk  (no timestamp in an APK)" ;; esac
    [ -n "$CS_KS" ] && echo "Key store: $CS_KS (alias $CS_ALIAS) for Gradle / apksigner / jarsigner / Visual Studio MAUI (VISUALSTUDIO-MAUI.txt)"
    case " $plats " in *" apple"*) echo "Apple   : rcodesign sign --p12-file $stem.pfx --p12-password-file pw.txt --timestamp-url http://timestamp.apple.com/ts01 MyApp.app (Gatekeeper accepts Apple Developer ID only)" ;; esac
    echo "This is a certificate of a private PKI. Only computers that trust its Root CA trust the signature."
  } > "$dir/CODESIGN-NOTES.txt"
  [ -f "$OUT/codesign-index.tsv" ] || printf '# platform\tlevel\tnotAfter\tsha1\tpfx\tcrt\tkey\n' > "$OUT/codesign-index.tsv"
  local p1; for p1 in $plats; do printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\n' "$p1" "$LEVEL" "$na" "$sha1" "${dir#$OUT/}/$stem.pfx" "${dir#$OUT/}/$stem.crt" "${dir#$OUT/}/$stem.key" >> "$OUT/codesign-index.tsv"; done
  [ "$EXTERNAL" = 1 ] || pki_log_issue "$OUT" codesign "$c_O" "$dir/$stem.crt"
  printf '  %-24s %-12s %-9s %-5s %-11s %s\n' "$tok" "$(pki_uc "$KEYTYPE")-${KEYBITS}${CURVE}" "$MD" "$days" "$na" "$dir/$stem.crt"
}

echo "  PLATFORM                 KEY          HASH      DAYS  EXPIRES     FILE"
if [ $COMBINED = 1 ]; then issue_cs multi "$PLIST"; else for p in $PLIST; do issue_cs "$p" "$p"; done; fi
RUN_OK=1
pki_ok "done. Folder: $RUN   Sign: ./Sign-Code.sh --use-generated --file <file>"
[ "$PFXPW" = 'Abc12345!' ] && pki_warn "The PFX password is the lab default Abc12345!. Use --pfx-password for real use."
exit 0
