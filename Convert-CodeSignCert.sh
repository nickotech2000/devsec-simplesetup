# ---------------------------------------------------------------- options
IN=''; KEY=''; CHAIN=''; ALIAS=''; TO=''; PLATFORM=''; OUT=''; NAME=''; PLAIN=0; LEGACY=0; FORCE=0; CHECK=0
IN_ENV=''; OUT_ENV=''; CI=0; VERBOSE=0
need() { [ $# -ge 2 ] && [ -n "$2" ] || { echo "[ERROR] $1 needs a value." >&2; exit 1; }; }
while [ $# -gt 0 ]; do
  case "$1" in
    --in) need "$@"; IN="$2"; shift 2 ;;
    --key) need "$@"; KEY="$2"; shift 2 ;;
    --chain) need "$@"; CHAIN="$2"; shift 2 ;;
    --alias) need "$@"; ALIAS="$2"; shift 2 ;;
    --to) need "$@"; TO="$TO,$2"; shift 2 ;;
    --platform) need "$@"; PLATFORM="$PLATFORM,$2"; shift 2 ;;
    --out-folder) need "$@"; OUT="$2"; shift 2 ;;
    --name) need "$@"; NAME="$2"; shift 2 ;;
    --in-password-env) need "$@"; IN_ENV="$2"; shift 2 ;;
    --out-password-env) need "$@"; OUT_ENV="$2"; shift 2 ;;
    --plain-key) PLAIN=1; shift ;;
    --legacy) LEGACY=1; shift ;;
    --force) FORCE=1; shift ;;
    --check-only) CHECK=1; shift ;;
    --ci) CI=1; shift ;;
    --verbose) VERBOSE=1; shift ;;
    -h|--help) show_help | help_pager; exit 0 ;;
    --version) pki_version_info; exit 0 ;;
    *) echo "[ERROR] Unknown option: $1  (see --help)" >&2; exit 1 ;;
  esac
done

# where we run (a pipeline never asks questions)
ENVK=local
if [ "${GITHUB_ACTIONS:-}" = true ]; then ENVK=github
elif [ "${TF_BUILD:-}" = True ]; then ENVK=azure
elif [ "${GITLAB_CI:-}" = true ] || [ -n "${JENKINS_URL:-}" ] || [ -n "${TEAMCITY_VERSION:-}" ] || [ -n "${BITBUCKET_BUILD_NUMBER:-}" ] || [ -n "${CODEBUILD_BUILD_ID:-}" ] || [ -n "${CLOUD_BUILD_ID:-}" ]; then ENVK=ci
elif [ -n "${MSBUILDEXTENSIONSPATH:-}${MSBuildExtensionsPath:-}" ]; then ENVK=msbuild
fi
[ "$ENVK" != local ] && [ "$ENVK" != msbuild ] && CI=1

if [ -t 1 ]; then C_R=$'\e[31m'; C_G=$'\e[32m'; C_Y=$'\e[33m'; C_0=$'\e[0m'; else C_R=''; C_G=''; C_Y=''; C_0=''; fi
say() {
  local lvl="$1"; shift; local c=''
  case "$lvl" in OK) c="$C_G" ;; WARN) c="$C_Y" ;; ERROR) c="$C_R" ;; esac
  printf '%s[%s]%s %s\n' "$c" "$lvl" "$C_0" "$*"
  if [ "$lvl" = ERROR ] || [ "$lvl" = WARN ]; then
    local t; t="$(echo "$lvl" | tr '[:upper:]' '[:lower:]')"; [ "$t" = warn ] && t=warning
    case "$ENVK" in
      github) echo "::$t::$*" ;;
      azure) echo "##vso[task.logissue type=$t]$*" ;;
      msbuild) echo "Convert-CodeSignCert : $t CC0001: $*" ;;
    esac
  fi
}
detail() { [ "$VERBOSE" = 1 ] && printf '[VERBOSE] %s\n' "$*"; return 0; }
stop() { local code="$1"; shift; say ERROR "$*"; exit "$code"; }

# ---------------------------------------------------------------- the formats
declare -A WANT=()
add_fmt() { local f; for f in $(echo "$1" | tr ',' ' ' | tr '[:upper:]' '[:lower:]'); do
  case "$f" in pfx|p12|keystore|jks|pem|crt|cer|key|p7b|spc|pvk|bundle) WANT[$f]=1 ;; '') ;; *) stop 1 "Unknown format in --to: $f" ;; esac; done; }
add_fmt "$TO"
for p in $(echo "$PLATFORM" | tr ',' ' ' | tr '[:upper:]' '[:lower:]'); do
  case "$p" in
    windows) add_fmt pfx,cer ;; java) add_fmt jks,keystore ;; android) add_fmt keystore,pfx ;; apple) add_fmt p12,cer ;;
    linux) add_fmt pem,crt,key ;; azure) add_fmt pfx ;; gcp) add_fmt pem,key ;;
    aws) add_fmt crt,key,pem; [ "$PLAIN" = 1 ] || stop 1 '--platform aws: AWS ACM imports an UNENCRYPTED key. Add --plain-key (and delete the .key after the import).' ;;
    all) add_fmt pfx,keystore,jks,pem,crt,cer,key,p7b ;;
    *) stop 1 "Unknown platform: $p (windows java android apple linux azure aws gcp all)" ;;
  esac
done
[ -n "$IN" ] || stop 1 'Give --in <certificate file> (see --help).'
[ -f "$IN" ] || stop 1 "File not found: $IN"
[ -z "$KEY" ] || [ -f "$KEY" ] || stop 1 "File not found: $KEY"
[ -z "$CHAIN" ] || [ -f "$CHAIN" ] || stop 1 "File not found: $CHAIN"
[ "$CHECK" = 1 ] || [ "${#WANT[@]}" -gt 0 ] || stop 1 'Give --to <formats> and / or --platform <platforms>, or --check-only.'

echo '============================================================'
echo " Convert-CodeSignCert.sh $VERSION"
echo '============================================================'

# ---------------------------------------------------------------- 1. the tools FIRST (nothing is written when one is missing)
in_is_jks=0
if [ "$(head -c4 "$IN" | od -An -tx1 | tr -d ' \n')" = feedfeed ]; then in_is_jks=1; fi
missing=()
OPENSSL="$(command -v openssl || true)"
if [ -z "$OPENSSL" ]; then missing+=("openssl 3 (Ubuntu: sudo apt install openssl   RHEL: sudo dnf install openssl   macOS: brew install openssl@3)")
else
  ov="$("$OPENSSL" version 2>/dev/null)"; case "$ov" in "OpenSSL 3."*|"OpenSSL 4."*) ;; *) missing+=("OpenSSL 3 or newer (found: ${ov:-unknown})") ;; esac
fi
if [ "$in_is_jks" = 1 ] || [ -n "${WANT[jks]:-}" ]; then
  command -v keytool >/dev/null 2>&1 || missing+=("keytool (Java JDK 17+: sudo apt install openjdk-21-jdk-headless   or   sudo dnf install java-21-openjdk-devel)")
fi
if [ "${#missing[@]}" -gt 0 ]; then
  for m in "${missing[@]}"; do say ERROR "Missing tool: $m"; done
  stop 4 'Install the missing tool(s) and run again. Nothing was written.'
fi
say OK "Tools: $("$OPENSSL" version | cut -d' ' -f1-2)$( [ "$in_is_jks" = 1 ] || [ -n "${WANT[jks]:-}" ] && echo ", keytool")"

