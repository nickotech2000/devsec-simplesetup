cleanup() { [ -n "${WORK:-}" ] && rm -rf "$WORK"; }
trap cleanup EXIT
pick_env() { local n; for n in "$@"; do [ -n "$n" ] && [ -n "${!n:-}" ] && { printf '%s' "$n"; return 0; }; done; return 1; }
IN_NAME="$(pick_env "$IN_ENV" CONVERT_IN_PASSWORD SIGN_PFX_PASSWORD || true)"
if [ -n "$IN_NAME" ]; then CVT_IN="${!IN_NAME}"
elif [ "$CI" = 0 ] && [ -t 0 ]; then read -r -s -p 'Password of the input (empty = none): ' CVT_IN; echo
else CVT_IN=''; fi
OUT_NAME="$(pick_env "$OUT_ENV" CONVERT_OUT_PASSWORD || true)"
if [ -n "$OUT_NAME" ]; then CVT_OUT="${!OUT_NAME}"; else CVT_OUT="$CVT_IN"; fi
[ "$ENVK" = github ] && { [ -n "$CVT_IN" ] && echo "::add-mask::$CVT_IN"; [ -n "$CVT_OUT" ] && echo "::add-mask::$CVT_OUT"; }
export CVT_IN CVT_OUT
need_out_pw() { [ -n "$CVT_OUT" ] || stop 1 "A password is needed for .$1 (set CONVERT_OUT_PASSWORD or --out-password-env)."; }

run() {  # run a tool quietly; its output goes to $WORK/last.log (shown with --verbose)
  detail "> $*"
  "$@" >"$WORK/last.log" 2>&1 </dev/null; local rc=$?   # never a password prompt of a tool
  [ "$VERBOSE" = 1 ] && sed 's/^/[VERBOSE]   /' "$WORK/last.log"
  return $rc
}
ossl() { run "$OPENSSL" "$@"; }

# ---------------------------------------------------------------- 2. read the input into PEM files in $WORK
LEAF="$WORK/leaf.pem"; PKEY="$WORK/key.pem"; CHN="$WORK/chain.pem"; : > "$CHN"
split_certs() {  # $1 = PEM with certificates -> $WORK/c-NN.pem
  rm -f "$WORK"/c-*.pem
  awk -v d="$WORK" '/-----BEGIN CERTIFICATE-----/{n++; f=sprintf("%s/c-%02d.pem", d, n)} f{print > f} /-----END CERTIFICATE-----/{close(f); f=""}' "$1"
}
is_ca() { "$OPENSSL" x509 -in "$1" -noout -ext basicConstraints 2>/dev/null | grep -q 'CA:TRUE'; }
take_certs() {  # $1 = PEM with one or more certificates: the leaf (not a CA) to $LEAF, the others to $CHN
  split_certs "$1"; local f got=0
  for f in "$WORK"/c-*.pem; do [ -f "$f" ] || continue
    if [ "$got" = 0 ] && ! is_ca "$f"; then cp "$f" "$LEAF"; got=1; else cat "$f" >> "$CHN"; fi
  done
  # only CA certificates (a self-signed test certificate): the first one is the leaf
  if [ "$got" = 0 ] && [ -f "$WORK/c-01.pem" ]; then cp "$WORK/c-01.pem" "$LEAF"; fi
  [ -s "$LEAF" ]
}
read_pkcs12() {  # $1 = file
  local leg=''
  if ! ossl pkcs12 -in "$1" -passin env:CVT_IN -noout; then
    if ossl pkcs12 -in "$1" -passin env:CVT_IN -noout -legacy; then leg='-legacy'; say WARN 'The input uses the old PKCS#12 algorithms (RC2 / 3DES): read with -legacy.'
    else stop 1 "Cannot read $1 as PKCS#12 (wrong password, or not a .pfx / .keystore)."; fi
  fi
  ossl pkcs12 -in "$1" -passin env:CVT_IN $leg -nokeys -out "$WORK/all.pem" || stop 1 "Cannot read the certificates of $1."
  ossl pkcs12 -in "$1" -passin env:CVT_IN $leg -nocerts -nodes -out "$WORK/k0.pem" || stop 1 "Cannot read the key of $1."
  grep -q 'PRIVATE KEY' "$WORK/k0.pem" || stop 2 "$1 holds no private key."
  ossl pkey -in "$WORK/k0.pem" -out "$PKEY" || stop 1 'Cannot read the private key.'
  # the leaf = the certificate of the key
  "$OPENSSL" pkey -in "$PKEY" -pubout 2>/dev/null > "$WORK/kpub.pem"
  split_certs "$WORK/all.pem"; local f
  for f in "$WORK"/c-*.pem; do [ -f "$f" ] || continue
    if [ ! -s "$LEAF" ] && cmp -s <("$OPENSSL" x509 -in "$f" -noout -pubkey 2>/dev/null) "$WORK/kpub.pem"; then cp "$f" "$LEAF"; else cat "$f" >> "$CHN"; fi
  done
  [ -s "$LEAF" ] || stop 2 "No certificate in $1 belongs to its private key."
}
read_jks() {  # Java KeyStore -> a temporary PKCS#12, then as PKCS#12
  local a=()
  [ -n "$ALIAS" ] && a=(-srcalias "$ALIAS" -destalias "$ALIAS")
  [ -n "$CVT_IN" ] || stop 1 'A .jks needs its password (CONVERT_IN_PASSWORD).'
  run keytool -importkeystore -noprompt -srckeystore "$IN" -srcstoretype JKS -srcstorepass:env CVT_IN \
      -destkeystore "$WORK/from-jks.p12" -deststoretype PKCS12 -deststorepass:env CVT_IN "${a[@]}" \
      $( [ -n "$ALIAS" ] && echo "-srckeypass:env CVT_IN -destkeypass:env CVT_IN" ) \
    || stop 1 "keytool cannot read $IN (password, or several entries: give --alias). $(tail -n1 "$WORK/last.log")"
  read_pkcs12 "$WORK/from-jks.p12"
}
read_key() {  # $1 = key file (any format) -> $PKEY
  if ossl pkey -in "$1" -passin env:CVT_IN -out "$PKEY"; then return 0; fi
  if ossl pkey -in "$1" -inform DER -passin env:CVT_IN -out "$PKEY"; then return 0; fi
  if ossl rsa -in "$1" -inform PVK -passin env:CVT_IN -out "$PKEY"; then return 0; fi
  if ossl rsa -in "$1" -inform PVK -passin env:CVT_IN -out "$PKEY" -provider default -provider legacy; then return 0; fi
  stop 1 "Cannot read the private key $1 (wrong password, or an unknown format)."
}
read_certfile() {  # PEM / DER certificate(s), or PKCS#7 -> $LEAF + $CHN (+ a key inside a PEM)
  if grep -q -- '-----BEGIN CERTIFICATE-----' "$1" 2>/dev/null; then take_certs "$1" || stop 1 "No certificate in $1."
    if grep -q 'PRIVATE KEY-----' "$1" && [ -z "$KEY" ]; then read_key "$1"; fi
  elif ossl pkcs7 -in "$1" -print_certs -out "$WORK/p7.pem" || ossl pkcs7 -in "$1" -inform DER -print_certs -out "$WORK/p7.pem"; then
    take_certs "$WORK/p7.pem" || stop 1 "No certificate in $1."
  elif ossl x509 -in "$1" -inform DER -out "$WORK/der.pem"; then cp "$WORK/der.pem" "$LEAF"
  else stop 1 "$1 is not a certificate, a .pfx / .keystore or a .p7b."; fi
}

# what is it? by its content: JKS magic, PEM text, a DER certificate / PKCS#7, else PKCS#12
if [ "$in_is_jks" = 1 ]; then say INFO "Input: Java KeyStore $IN"; read_jks
elif grep -q -- '-----BEGIN ' "$IN" 2>/dev/null \
  || "$OPENSSL" x509 -in "$IN" -inform DER -passin pass: -noout </dev/null 2>/dev/null || "$OPENSSL" pkcs7 -in "$IN" -inform DER -noout </dev/null 2>/dev/null; then
  say INFO "Input: certificate file $IN"; read_certfile "$IN"
else
  say INFO "Input: PKCS#12 $IN"; read_pkcs12 "$IN"
fi
[ -n "$KEY" ] && read_key "$KEY"
if [ -n "$CHAIN" ]; then
  if grep -q -- '-----BEGIN CERTIFICATE-----' "$CHAIN"; then cat "$CHAIN" >> "$CHN"
  elif ossl pkcs7 -in "$CHAIN" -print_certs -out "$WORK/c7.pem" || ossl pkcs7 -in "$CHAIN" -inform DER -print_certs -out "$WORK/c7.pem"; then cat "$WORK/c7.pem" >> "$CHN"
  else ossl x509 -in "$CHAIN" -inform DER -out "$WORK/c1.pem" && cat "$WORK/c1.pem" >> "$CHN" || stop 1 "Cannot read the chain $CHAIN."; fi
fi
# the chain without the leaf and without doubles, as clean PEM
if [ -s "$CHN" ]; then
  split_certs "$CHN"; : > "$WORK/chain2.pem"; declare -A SEEN=(); lf="$("$OPENSSL" x509 -in "$LEAF" -noout -fingerprint -sha256)"
  for f in "$WORK"/c-*.pem; do [ -f "$f" ] || continue; fp="$("$OPENSSL" x509 -in "$f" -noout -fingerprint -sha256 2>/dev/null)" || continue
    [ "$fp" = "$lf" ] && continue; [ -n "${SEEN[$fp]:-}" ] && continue; SEEN[$fp]=1; "$OPENSSL" x509 -in "$f" >> "$WORK/chain2.pem"; done
  mv "$WORK/chain2.pem" "$CHN"
fi
HAS_KEY=0; [ -s "$PKEY" ] && HAS_KEY=1

# ---------------------------------------------------------------- 3. check and show the certificate
if [ "$HAS_KEY" = 1 ]; then
  cmp -s <("$OPENSSL" pkey -in "$PKEY" -pubout 2>/dev/null) <("$OPENSSL" x509 -in "$LEAF" -noout -pubkey 2>/dev/null) \
    || stop 2 'The private key does NOT belong to the certificate.'
  say OK 'The private key belongs to the certificate.'
else
  say WARN 'No private key: only certificate formats (pem crt cer p7b spc) can be written.'
fi
X() { "$OPENSSL" x509 -in "$LEAF" -noout "$@" 2>/dev/null; }
fp() { X -fingerprint "-$1" | sed 's/^.*=//; s/://g' | tr '[:upper:]' '[:lower:]'; }
SUBJ="$(X -subject -nameopt RFC2253 | sed 's/^subject=//')"
ISS="$(X -issuer -nameopt RFC2253 | sed 's/^issuer=//')"
KTXT="$(X -text | awk '/Public Key Algorithm/{a=$NF} /Public-Key:/{gsub(/[()]/,""); b=$(NF-1)} /NIST CURVE|ASN1 OID/{c=$NF} END{if(a~/rsa/) print "RSA-" b; else if (a~/ec/) print "EC " c " (" b " bit)"; else print a " " b}')"
FP256="$(fp sha256)"; FP512="$(fp sha512)"
EKU="$(X -ext extendedKeyUsage | tail -n +2 | tr -d ' ')"
echo '----- CERTIFICATE ----------------------------------------------------------------'
printf '  %-13s: %s\n' Subject "$SUBJ" Issuer "$ISS" Serial "$(X -serial | sed 's/^serial=//')" \
  'Valid from' "$(X -startdate | sed 's/^notBefore=//')" 'Valid until' "$(X -enddate | sed 's/^notAfter=//')" \
  'Key' "$KTXT" 'Purposes' "${EKU:-none listed}" 'SHA-256' "$FP256" 'SHA-512' "$FP512" \
  'Chain' "$(grep -c -- '-----BEGIN CERTIFICATE-----' "$CHN") CA certificate(s)"
echo '----------------------------------------------------------------------------------'
case "$EKU" in *CodeSigning*|*codeSigning*) ;; *) say WARN 'This certificate has no Code Signing purpose (EKU): signing tools may refuse it.' ;; esac
X -checkend 0 >/dev/null || say WARN 'The certificate has EXPIRED.'
if [ "$CHECK" = 1 ]; then say OK 'Checks finished (--check-only): nothing was written.'; exit 0; fi

# ---------------------------------------------------------------- 4. write the outputs
[ -n "$NAME" ] || { NAME="$(basename "$IN")"; NAME="${NAME%.*}"; }
[ -n "$OUT" ] || OUT="$(dirname "$IN")/$NAME-converted"
mkdir -p "$OUT" || stop 1 "Cannot make $OUT"
if [ -z "$ALIAS" ]; then
  cn="$(X -subject -nameopt multiline | awk -F' = ' '/commonName/{print $2; exit}')"
  ALIAS="$(printf '%s' "${cn:-codesign}" | tr '[:upper:]' '[:lower:]' | sed -E 's/[^a-z0-9._-]+/_/g; s/^_+//; s/_+$//')"
  [ -n "$ALIAS" ] || ALIAS=codesign
fi
key_needed() { [ "$HAS_KEY" = 1 ] || stop 1 ".$1 needs the private key: give --key (or an input that holds it)."; }
target() { printf '%s' "$OUT/$NAME.$1"; }
# nothing is replaced without --force: checked for every output BEFORE the first one is written
if [ "$FORCE" = 0 ]; then for f in "${!WANT[@]}"; do [ -e "$(target "$f")" ] && stop 1 "$(target "$f") exists. Use --force to replace it."; done; fi
P12ALG=(-keypbe AES-256-CBC -certpbe AES-256-CBC -macalg sha256)
[ "$LEGACY" = 1 ] && { P12ALG=(-legacy -keypbe PBE-SHA1-3DES -certpbe PBE-SHA1-3DES -macalg sha1); say WARN '--legacy: PKCS#12 with 3DES and a SHA-1 MAC, only for old systems.'; }
make_p12() {  # $1 = output file
  local cf=(); [ -s "$CHN" ] && cf=(-certfile "$CHN")
  ossl pkcs12 -export -in "$LEAF" -inkey "$PKEY" "${cf[@]}" -name "$ALIAS" -passout env:CVT_OUT "${P12ALG[@]}" -out "$1" \
    || stop 5 "Cannot write $1: $(tail -n1 "$WORK/last.log")"
}
WRITTEN=()
for f in pfx p12 keystore jks pem crt cer key p7b spc pvk bundle; do
  [ -n "${WANT[$f]:-}" ] || continue
  t="$(target "$f")"
  case "$f" in
    pfx|p12|keystore) key_needed "$f"; need_out_pw "$f"; make_p12 "$t" ;;
    jks) key_needed jks; need_out_pw jks; make_p12 "$WORK/for-jks.p12"; rm -f "$t"
         run keytool -importkeystore -noprompt -srckeystore "$WORK/for-jks.p12" -srcstoretype PKCS12 -srcstorepass:env CVT_OUT \
             -destkeystore "$t" -deststoretype JKS -deststorepass:env CVT_OUT -destkeypass:env CVT_OUT -srcalias "$ALIAS" -destalias "$ALIAS" \
           || stop 5 "keytool cannot write $t: $(tail -n1 "$WORK/last.log")" ;;
    pem) { "$OPENSSL" x509 -in "$LEAF"; [ -s "$CHN" ] && cat "$CHN"; } > "$t" ;;
    crt) "$OPENSSL" x509 -in "$LEAF" -out "$t" ;;
    cer) "$OPENSSL" x509 -in "$LEAF" -outform DER -out "$t" ;;
    key) key_needed key
         if [ "$PLAIN" = 1 ]; then ossl pkey -in "$PKEY" -out "$t"; say WARN "$t is NOT encrypted (--plain-key): delete it after use."
         else need_out_pw key; ossl pkcs8 -topk8 -in "$PKEY" -v2 aes-256-cbc -v2prf hmacWithSHA256 -passout env:CVT_OUT -out "$t"; fi || stop 5 "Cannot write $t." ;;
    p7b|spc) cf=(-certfile "$LEAF"); [ -s "$CHN" ] && cf+=(-certfile "$CHN")
         ossl crl2pkcs7 -nocrl "${cf[@]}" -outform "$( [ "$f" = spc ] && echo DER || echo PEM )" -out "$t" || stop 5 "Cannot write $t." ;;
    pvk) key_needed pvk
         [ "$("$OPENSSL" pkey -in "$PKEY" -noout -text 2>/dev/null | head -n1 | grep -c 'Private-Key')" = 1 ] && "$OPENSSL" rsa -in "$PKEY" -noout 2>/dev/null || stop 1 '.pvk holds RSA keys only.'
         need_out_pw pvk
         ossl rsa -in "$PKEY" -outform PVK -passout env:CVT_OUT -out "$t" || ossl rsa -in "$PKEY" -outform PVK -passout env:CVT_OUT -out "$t" -provider default -provider legacy \
           || stop 5 "Cannot write $t: $(tail -n1 "$WORK/last.log")" ;;
    bundle) key_needed bundle
         if [ "$PLAIN" = 1 ]; then "$OPENSSL" pkey -in "$PKEY" > "$t"; else need_out_pw bundle; "$OPENSSL" pkcs8 -topk8 -in "$PKEY" -v2 aes-256-cbc -v2prf hmacWithSHA256 -passout env:CVT_OUT > "$t"; fi
         "$OPENSSL" x509 -in "$LEAF" >> "$t"; [ -s "$CHN" ] && cat "$CHN" >> "$t" ;;
  esac
  WRITTEN+=("$f:$t")
done

# ---------------------------------------------------------------- 5. read every output back: the same certificate and key?
LPUB="$("$OPENSSL" x509 -in "$LEAF" -noout -pubkey)"
back_fp() { "$OPENSSL" x509 -in "$1" -noout -fingerprint -sha256 2>/dev/null | sed 's/^.*=//; s/://g' | tr '[:upper:]' '[:lower:]'; }
check_out() {  # $1 = format, $2 = file -> "" or an error text
  local f="$1" t="$2" c="$WORK/back.pem" k="$WORK/backkey.pem"; rm -f "$c" "$k"
  case "$f" in
    pfx|p12|keystore) local leg=(); [ "$LEGACY" = 1 ] && leg=(-legacy)
      "$OPENSSL" pkcs12 -in "$t" -passin env:CVT_OUT "${leg[@]}" -nokeys -clcerts -out "$c" 2>/dev/null || { echo 'cannot be opened with the output password'; return; }
      "$OPENSSL" pkcs12 -in "$t" -passin env:CVT_OUT "${leg[@]}" -nocerts -nodes -out "$k" 2>/dev/null
      if [ "$f" = keystore ]; then "$OPENSSL" pkcs12 -in "$t" -passin env:CVT_OUT "${leg[@]}" -nokeys -clcerts 2>/dev/null | grep -q "friendlyName: $ALIAS" || { echo "alias $ALIAS not found"; return; }; fi ;;
    jks) keytool -exportcert -rfc -keystore "$t" -storetype JKS -storepass:env CVT_OUT -alias "$ALIAS" -file "$c" >/dev/null 2>&1 || { echo 'keytool cannot read it'; return; } ;;
    pem|crt) cp "$t" "$c" ;;
    cer) "$OPENSSL" x509 -in "$t" -inform DER -out "$c" 2>/dev/null ;;
    p7b) "$OPENSSL" pkcs7 -in "$t" -print_certs 2>/dev/null > "$WORK/b7.pem"; split_certs "$WORK/b7.pem"; for x in "$WORK"/c-*.pem; do [ "$(back_fp "$x")" = "$FP256" ] && cp "$x" "$c"; done ;;
    spc) "$OPENSSL" pkcs7 -in "$t" -inform DER -print_certs 2>/dev/null > "$WORK/b7.pem"; split_certs "$WORK/b7.pem"; for x in "$WORK"/c-*.pem; do [ "$(back_fp "$x")" = "$FP256" ] && cp "$x" "$c"; done ;;
    key) if [ "$PLAIN" = 1 ]; then "$OPENSSL" pkey -in "$t" -out "$k" 2>/dev/null; else "$OPENSSL" pkey -in "$t" -passin env:CVT_OUT -out "$k" 2>/dev/null; fi
         [ -s "$k" ] || { echo 'the key cannot be read back'; return; }
         [ "$("$OPENSSL" pkey -in "$k" -pubout 2>/dev/null)" = "$LPUB" ] || echo 'the key does not match the certificate'; return ;;
    pvk) "$OPENSSL" rsa -in "$t" -inform PVK -passin env:CVT_OUT -out "$k" 2>/dev/null || "$OPENSSL" rsa -in "$t" -inform PVK -passin env:CVT_OUT -out "$k" -provider default -provider legacy 2>/dev/null
         [ "$("$OPENSSL" pkey -in "$k" -pubout 2>/dev/null)" = "$LPUB" ] || echo 'the key does not match the certificate'; return ;;
    bundle) awk '/-----BEGIN CERTIFICATE-----/{p=1} p{print} /-----END CERTIFICATE-----/{exit}' "$t" > "$c" ;;
  esac
  [ -s "$c" ] && [ "$(back_fp "$c")" = "$FP256" ] || { echo 'it does not hold the same certificate'; return; }
  if [ -s "$k" ] && [ "$("$OPENSSL" pkey -in "$k" -pubout 2>/dev/null)" != "$LPUB" ]; then echo 'the key does not match the certificate'; fi
}
bad=0
for w in "${WRITTEN[@]}"; do
  f="${w%%:*}"; t="${w#*:}"; e="$(check_out "$f" "$t")"
  if [ -n "$e" ]; then say ERROR "$t: $e"; bad=1; else detail "read back OK: $t"; fi
done
rm -f "$WORK/back.pem" "$WORK/backkey.pem"
[ "$bad" = 0 ] || stop 5 'An output is not correct (see above). Do not use these files.'

# ---------------------------------------------------------------- 6. checksums (SHA-256 and SHA-512 only)
sum_of() { "$OPENSSL" dgst "-$1" -r "$2" | cut -d' ' -f1; }
for w in "${WRITTEN[@]}"; do
  t="${w#*:}"; b="$(basename "$t")"
  for a in sha256 sha512; do printf '%s  %s\n' "$(sum_of "$a" "$t")" "$b" > "$t.$a"; done
done
FPF="$OUT/$NAME-certificate-fingerprints.txt"
{ echo "Certificate fingerprints (hash of the DER certificate). Made by Convert-CodeSignCert.sh $VERSION"
  echo "Subject : $SUBJ"; echo "Issuer  : $ISS"; echo "Serial  : $(X -serial | sed 's/^serial=//')"
  echo "SHA-256 : $FP256"; echo "SHA-512 : $FP512"; } > "$FPF"

echo '----- WRITTEN (each with .sha256 and .sha512) ------------------------------------'
for w in "${WRITTEN[@]}"; do printf '  %-9s %s\n' "${w%%:*}" "${w#*:}"; done
printf '  %-9s %s\n' fingerprints "$FPF"
case " ${!WANT[*]} " in *" keystore "*|*" jks "*|*" pfx "*|*" p12 "*) say INFO "Alias in .keystore / .jks / .pfx: $ALIAS" ;; esac
say OK "Converted: ${#WRITTEN[@]} file(s), every one read back and checked."
exit 0
