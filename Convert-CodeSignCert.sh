cat <<'HELP_EOF'
====================================================================================================
 Convert-CodeSignCert.sh  -  convert a code-signing certificate to the format a platform needs
 Version 7.9.9
 Author : Nicko Satria Utama
 Company: Agantra Inovatif OÜ (NextMantra)
 Email  : nicko@nextmantra.com
====================================================================================================
 On a terminal: SPACE = next page, ENTER = next line, Q = quit.
 Manual : docs/Convert-CodeSignCert-MANUAL.txt            Windows twin: Convert-CodeSignCert.ps1
 Runs on: Linux and macOS (bash 4+), Git Bash / WSL on Windows. By hand, in Visual Studio 2026,
          VS Code or JetBrains (a terminal or a task), or on a build agent: GitHub Actions, Azure
          DevOps Services (cloud) and Server (on premises), GitLab CI/CD, AWS CodeBuild, Alibaba
          Cloud Yunxiao Flow, Azure, Google Cloud Build, Jenkins, Bitbucket, TeamCity.
 STANDALONE: copy this one file into your repository (for example build/Convert-CodeSignCert.sh).

WHAT IT DOES
  Reads ONE certificate with its private key (from a public CA such as DigiCert, Sectigo, GlobalSign,
  SSL.com, Certum, or from your private PKI) and writes it in the formats you ask for:
  1. Checks the tools first. A missing tool stops the run before anything is written (exit 4).
  2. Reads the input, checks that the key belongs to the certificate (exit 2 if not) and prints
     the certificate: subject, issuer, serial, validity, key, SHA-256 and SHA-512 fingerprints.
  3. Writes every format, then READS EACH OUTPUT BACK and checks that it holds the same
     certificate (and the same key) - a broken output stops the run (exit 5).
  4. Writes <file>.sha256 and <file>.sha512 next to EVERY output (sha256sum / sha512sum format)
     and <name>-certificate-fingerprints.txt with the SHA-256 and SHA-512 of the certificate.
     Never MD5 or SHA-1.

QUICK START
  From a public CA .pfx to everything Android and Java need:
     CONVERT_IN_PASSWORD='...' ./Convert-CodeSignCert.sh --in codesign.pfx --platform android,java
  From .crt + .key (+ the CA chain) to .pfx for Windows:
     ./Convert-CodeSignCert.sh --in codesign.crt --key codesign.key --chain ca-bundle.crt --to pfx
  From an Android / Java .keystore back to .pfx, .crt and .key:
     ./Convert-CodeSignCert.sh --in release.keystore --to pfx,crt,key

THE INPUT
  --in <file>          The certificate. Recognised by its content (the extension only helps):
                         .pfx .p12 .keystore (PKCS#12)   .jks / .keystore (Java KeyStore, needs keytool)
                         .pem .crt .cer .der (one certificate, PEM or DER; a PEM may also hold the key
                         and the chain)   .p7b .p7c .spc (a certificate chain, PEM or DER)
  --key <file>         The private key when --in is a certificate only: .key .pem (PKCS#8 or
                       traditional, encrypted or not), .der, .pvk (Microsoft).
  --chain <file>       Extra CA certificates (PEM bundle or .p7b) added to the outputs.
  --alias <name>       The entry to read from a .jks / .keystore with several entries, and the alias
                       written into .keystore / .jks / .pfx. Default: from the certificate name,
                       lower case, [a-z0-9._-] (the same rule as GenerateCodeSigningCertificate).

THE OUTPUT
  --to <list>          Formats, comma separated:
                         pfx p12      PKCS#12 with key and chain (AES-256, SHA-256 MAC)
                         keystore     PKCS#12 with ONE alias: Android (apksigner, Gradle, MAUI) and Java
                         jks          Java KeyStore (keytool), for old Java tools only
                         pem          certificate + chain (PEM)        crt  certificate (PEM)
                         cer          certificate (DER, Windows)       key  private key (PKCS#8 PEM,
                                                                             AES-256 encrypted)
                         p7b          certificate + chain (PKCS#7 PEM) spc  the same as DER (signcode)
                         pvk          private key for the old Microsoft tools (RSA only)
                         bundle       key + certificate + chain in one PEM (encrypted key)
  --platform <list>    Presets (comma separated), added to --to:
                         windows   pfx cer          java      jks keystore      android  keystore pfx
                         apple     p12 cer          linux     pem crt key       azure    pfx
                         aws       crt key pem (needs --plain-key: AWS ACM imports an unencrypted key)
                         gcp       pem key          all       pfx keystore jks pem crt cer key p7b
  --out-folder <dir>   Where the files go. Default: <name>-converted next to --in.
  --name <base>        File name of the outputs (without extension). Default: the name of --in.
  --plain-key          Write .key / bundle WITHOUT encryption (only for a platform that needs it, such as
                       AWS ACM). Keep that file out of git and delete it after the import.
  --legacy             PKCS#12 with the old algorithms (3DES, SHA-1 MAC) for Windows Server 2016 /
                       macOS 11 and older. Only when such a system refuses the normal .pfx.
  --force              Replace output files that already exist (default: stop, exit 1).
  --check-only         Read and check the input, print the certificate, write nothing.

PASSWORDS (never on the command line)
  --in-password-env <NAME>   Variable with the password of --in / --key. Default: CONVERT_IN_PASSWORD,
                             then SIGN_PFX_PASSWORD. Not set + a terminal = you are asked.
  --out-password-env <NAME>  Variable with the password of the outputs. Default: CONVERT_OUT_PASSWORD,
                             else the input password. The tools get it as env:..., never as an argument.

OTHER
  --ci            Pipeline mode: no questions (also on by itself in a known build system).
  --verbose       Every step and command line (passwords shown as ***).
  --help          This text.        --version     Version and system report.

EXIT CODES
  0 done   1 wrong input / option   2 the key does not belong to the certificate, or no certificate
  4 a needed tool is missing (nothing written)   5 an output could not be read back correctly

CI EXAMPLES (the certificate comes from a secret as Base64)
  GitHub Actions:   echo "$CODESIGN_PFX_B64" | base64 -d > cs.pfx
                    ./build/Convert-CodeSignCert.sh --in cs.pfx --to keystore --out-folder out
                    (env: CONVERT_IN_PASSWORD: ${{ secrets.CODESIGN_PFX_PASSWORD }})
  Azure DevOps:     the same in a Bash@3 task; the password from a secret variable mapped in env:.
  GitLab / AWS CodeBuild / Alibaba Yunxiao / Google Cloud Build: the same two lines in a script step.
