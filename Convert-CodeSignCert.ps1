            'jks' {
                Assert-Key 'jks'; Assert-OutPw 'jks'; New-P12 (W 'for-jks.p12'); if (Test-Path -LiteralPath $t) { Remove-Item -LiteralPath $t -Force }
                if (-not (Invoke-Tool $keytool @('-importkeystore', '-noprompt', '-srckeystore', (W 'for-jks.p12'), '-srcstoretype', 'PKCS12', '-srcstorepass:env', 'CVT_OUT',
                            '-destkeystore', $t, '-deststoretype', 'JKS', '-deststorepass:env', 'CVT_OUT', '-destkeypass:env', 'CVT_OUT', '-srcalias', $Alias, '-destalias', $Alias))) { Stop-Convert 5 "keytool cannot write ${t}: $(($script:LastLog -split "`n")[-1])" }
            }
            'pem' { Set-Content -LiteralPath $t -Value (@([System.IO.File]::ReadAllText($leaf).Trim()) + @($clean) -join "`n") }
            'crt' { Copy-Item -LiteralPath $leaf -Destination $t -Force }
            'cer' { [System.IO.File]::WriteAllBytes($t, $cert.RawData) }
            'key' {
                Assert-Key 'key'
                $ok = if ($PlainKey) { Ossl pkey -in $pkey -out $t } else { Assert-OutPw 'key'; Ossl pkcs8 -topk8 -in $pkey -v2 aes-256-cbc -v2prf hmacWithSHA256 -passout env:CVT_OUT -out $t }
                if (-not $ok) { Stop-Convert 5 "Cannot write $t." }
                if ($PlainKey) { Write-Say 'WARN' "$t is NOT encrypted (-PlainKey): delete it after use." }
            }
            { $_ -in 'p7b', 'spc' } {
                $cf = @('-certfile', $leaf); if ($chainCount -gt 0) { $cf += @('-certfile', $chn) }
                if (-not (Ossl crl2pkcs7 -nocrl @cf -outform $(if ($f -eq 'spc') { 'DER' } else { 'PEM' }) -out $t)) { Stop-Convert 5 "Cannot write $t." }
            }
            'pvk' {
                Assert-Key 'pvk'; if (-not $isRsa) { Stop-Convert 1 '.pvk holds RSA keys only.' }; Assert-OutPw 'pvk'
                if (-not ((Ossl rsa -in $pkey -outform PVK -passout env:CVT_OUT -out $t) -or (Ossl rsa -in $pkey -outform PVK -passout env:CVT_OUT -out $t -provider default -provider legacy))) { Stop-Convert 5 "Cannot write ${t}: $(($script:LastLog -split "`n")[-1])" }
            }
            'bundle' {
                Assert-Key 'bundle'
                $ok = if ($PlainKey) { Ossl pkey -in $pkey -out (W 'bk.pem') } else { Assert-OutPw 'bundle'; Ossl pkcs8 -topk8 -in $pkey -v2 aes-256-cbc -v2prf hmacWithSHA256 -passout env:CVT_OUT -out (W 'bk.pem') }
                if (-not $ok) { Stop-Convert 5 "Cannot write $t." }
                Set-Content -LiteralPath $t -Value (@([System.IO.File]::ReadAllText((W 'bk.pem')).Trim(), [System.IO.File]::ReadAllText($leaf).Trim()) + @($clean) -join "`n")
            }
        }
        $written.Add([pscustomobject]@{ Format = $f; File = $t })
    }

    # ---------------------------------------------------------------- 5. read every output back: the same certificate and key?
    function Get-Fp([string]$PemFile) { $p = Split-Pem $PemFile; foreach ($x in $p) { $h = (Get-CertObj $x).GetCertHashString([System.Security.Cryptography.HashAlgorithmName]::SHA256).ToLowerInvariant(); if ($h -eq $fp256) { return $h } }; if ($p) { return 'other' }; return $null }
    function Test-Output([string]$f, [string]$t) {
        $c = W 'back.pem'; $k = W 'backkey.pem'; Remove-Item -LiteralPath $c, $k -Force -ErrorAction SilentlyContinue
        [string[]]$leg = if ($Legacy) { '-legacy' } else { @() }
        switch ($f) {
            { $_ -in 'pfx', 'p12', 'keystore' } {
                if (-not (Ossl pkcs12 -in $t -passin env:CVT_OUT @leg -nokeys -clcerts -out $c)) { return 'cannot be opened with the output password' }
                [void](Ossl pkcs12 -in $t -passin env:CVT_OUT @leg -nocerts -nodes -out $k)
                if ($f -eq 'keystore' -and [System.IO.File]::ReadAllText($c) -notmatch "friendlyName: $([regex]::Escape($Alias))") { return "alias $Alias not found" }
            }
            'jks' { if (-not (Invoke-Tool $keytool @('-exportcert', '-rfc', '-keystore', $t, '-storetype', 'JKS', '-storepass:env', 'CVT_OUT', '-alias', $Alias, '-file', $c))) { return 'keytool cannot read it' } }
            { $_ -in 'pem', 'crt', 'bundle' } { Copy-Item -LiteralPath $t -Destination $c }
            'cer' { [void](Ossl x509 -in $t -inform DER -out $c) }
            'p7b' { [void](Ossl pkcs7 -in $t -print_certs -out $c) }
            'spc' { [void](Ossl pkcs7 -in $t -inform DER -print_certs -out $c) }
            'key' { $ok = if ($PlainKey) { Ossl pkey -in $t -out $k } else { Ossl pkey -in $t -passin env:CVT_OUT -out $k }; if (-not $ok) { return 'the key cannot be read back' }; if ((Get-PubPem $k) -ne $leafPub) { return 'the key does not match the certificate' }; return $null }
            'pvk' { if (-not ((Ossl rsa -in $t -inform PVK -passin env:CVT_OUT -out $k) -or (Ossl rsa -in $t -inform PVK -passin env:CVT_OUT -out $k -provider default -provider legacy))) { return 'the key cannot be read back' }; if ((Get-PubPem $k) -ne $leafPub) { return 'the key does not match the certificate' }; return $null }
        }
        if (-not (Test-Path -LiteralPath $c) -or (Get-Fp $c) -ne $fp256) { return 'it does not hold the same certificate' }
        if ((Test-Path -LiteralPath $k) -and (Get-Item -LiteralPath $k).Length -gt 0 -and (Get-PubPem $k) -ne $leafPub) { return 'the key does not match the certificate' }
        return $null
    }
    $bad = $false
    foreach ($w in $written) { $e = Test-Output $w.Format $w.File; if ($e) { Write-Say 'ERROR' "$($w.File): $e"; $bad = $true } else { Write-Detail "read back OK: $($w.File)" } }
    if ($bad) { Stop-Convert 5 'An output is not correct (see above). Do not use these files.' }

    # ---------------------------------------------------------------- 6. checksums (SHA-256 and SHA-512 only)
    foreach ($w in $written) {
        foreach ($a in 'SHA256', 'SHA512') {
            $h = (Get-FileHash -LiteralPath $w.File -Algorithm $a).Hash.ToLowerInvariant()
            [System.IO.File]::WriteAllText("$($w.File).$($a.ToLowerInvariant())", "$h  $(Split-Path -Leaf $w.File)`n", [System.Text.UTF8Encoding]::new($false))
        }
    }
    $fpf = Join-Path $OutFolder "$Name-certificate-fingerprints.txt"
    [System.IO.File]::WriteAllText($fpf, (@("Certificate fingerprints (hash of the DER certificate). Made by Convert-CodeSignCert.ps1 $script:ToolVersion",
                "Subject : $($cert.Subject)", "Issuer  : $($cert.Issuer)", "Serial  : $($cert.SerialNumber)", "SHA-256 : $fp256", "SHA-512 : $fp512") -join "`n") + "`n", [System.Text.UTF8Encoding]::new($false))
    Write-Host '----- WRITTEN (each with .sha256 and .sha512) ------------------------------------'
    foreach ($w in $written) { Write-Host ('  {0,-9} {1}' -f $w.Format, $w.File) }
    Write-Host ('  {0,-9} {1}' -f 'fingerprints', $fpf)
    if ($want | Where-Object { $_ -in 'keystore', 'jks', 'pfx', 'p12' }) { Write-Say 'INFO' "Alias in .keystore / .jks / .pfx: $Alias" }
    Write-Say 'OK' "Converted: $($written.Count) file(s), every one read back and checked."
}
catch [ConvertExit] { Write-Say 'ERROR' $_.Exception.Message; $exit = $_.Exception.Code }
catch { Write-Say 'ERROR' $_.Exception.Message; $exit = 1 }
finally {
    if ($work -and (Test-Path -LiteralPath $work)) { Remove-Item -LiteralPath $work -Recurse -Force -ErrorAction SilentlyContinue }
    Remove-Item Env:\CVT_IN, Env:\CVT_OUT -ErrorAction SilentlyContinue
}
exit $exit
