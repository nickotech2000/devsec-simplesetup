.EXAMPLE
    .\Convert-CodeSignCert.ps1 -In .\codesign.pfx -Platform Android, Java
.EXAMPLE
    .\Convert-CodeSignCert.ps1 -In .\codesign.crt -Key .\codesign.key -Chain .\ca-bundle.crt -To pfx
.EXAMPLE
    .\Convert-CodeSignCert.ps1 -In .\release.keystore -To pfx, crt, key
