need() { [ $# -ge 2 ] && [ -n "$2" ] || { echo "[ERROR] $1 needs a value." >&2; exit 1; }; }
while [ $# -gt 0 ]; do
  case "$1" in
    --folder) need "$@"; FOLDER="$2"; shift 2 ;;
    --include) need "$@"; INCL+=("$2"); shift 2 ;;
    --exclude) need "$@"; EXCL+=("$2"); shift 2 ;;
    --no-recurse) NOREC=1; shift ;;
    --name) need "$@"; NAME="$2"; shift 2 ;;
    --out-folder) need "$@"; OUTF="$2"; shift 2 ;;
    --unsigned) UNSIGNED=1; shift ;;
    --pfx) need "$@"; PFX="$2"; shift 2 ;;
    --pfx-password-env) need "$@"; PFX_ENV="$2"; shift 2 ;;
    --cert-pem) need "$@"; CERT_PEM="$2"; shift 2 ;;
    --key-pem) need "$@"; KEY_PEM="$2"; shift 2 ;;
    --key-password-env) need "$@"; KEY_ENV="$2"; shift 2 ;;
    --chain-file) need "$@"; CHAINF="$2"; shift 2 ;;
    --timestamp) need "$@"; TS_LIST="$2"; shift 2 ;;
    --timestamp-url) need "$@"; TS_URL="$2"; shift 2 ;;
    --verify) need "$@"; VERIFY="$2"; shift 2 ;;
    --root) need "$@"; ROOT="$2"; shift 2 ;;
    --expect-sha256) need "$@"; EXPECT+=("$(printf '%s' "$2" | tr -d ': ' | tr '[:upper:]' '[:lower:]')"); shift 2 ;;
    --strict) STRICT=1; shift ;;
    --sign-cat) need "$@"; SIGNCAT="$2"; shift 2 ;;
    --ci) CI=1; shift ;;
    --verbose) VERBOSE=1; shift ;;
    -h|--help) show_help | help_pager; exit 0 ;;
    --version) pki_version_info; exit 0 ;;
    *) echo "[ERROR] Unknown option: $1  (see --help)" >&2; exit 1 ;;
  esac
done

