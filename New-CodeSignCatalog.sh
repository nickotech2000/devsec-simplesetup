say() {
  local lvl="$1"; shift; local c=''
  case "$lvl" in OK) c="$C_G" ;; WARN) c="$C_Y" ;; ERROR) c="$C_R" ;; esac
  printf '%s[%s]%s %s\n' "$c" "$lvl" "$C_0" "$*"
  if [ "$lvl" = ERROR ] || [ "$lvl" = WARN ]; then
    local t=error; [ "$lvl" = WARN ] && t=warning
    case "$ENVK" in github) echo "::$t::$*" ;; azure) echo "##vso[task.logissue type=$t]$*" ;; msbuild) echo "New-CodeSignCatalog : $t CT0001: $*" ;; esac
  fi
}
