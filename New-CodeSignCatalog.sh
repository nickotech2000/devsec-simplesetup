cat <<'HELP_EOF'
====================================================================================================
 New-CodeSignCatalog.sh  -  a signed catalog of files (json, config, js ...) and its check
 Version 7.9.5
 Author : Nicko Satria Utama
 Company: Agantra Inovatif OÜ (NextMantra)
 Email  : nicko@nextmantra.com
====================================================================================================
 On a terminal: SPACE = next page, ENTER = next line, Q = quit.
 Manual : docs/New-CodeSignCatalog-MANUAL.txt               Windows twin: New-CodeSignCatalog.ps1
 Runs on: Linux and macOS (bash 4+). By hand, after a build (MSBuild Exec, Gradle, Maven, npm), in
          VS Code or JetBrains (a terminal or a task), or on a build agent: GitHub Actions, Azure
          DevOps Services (cloud) and Server (on premises), GitLab CI/CD, AWS CodeBuild, Alibaba
          Cloud Yunxiao Flow, Azure, Google Cloud Build, Jenkins, Bitbucket, TeamCity.
 STANDALONE: copy this one file into your repository (for example build/New-CodeSignCatalog.sh).

WHAT IT IS
  Many files cannot hold a signature: appsettings.json, web.config, .xml, .js, .css, .html, images.
  A CATALOG signs them all at once: one list with the hash of every file, and ONE signature on the
  list. Change one byte of one file and the check of the catalog says which file was changed.
  Two kinds:
    PORTABLE (this script makes it, on any system)
      <name>.sha256 / <name>.sha512        the lists (the sha256sum / sha512sum format)
      <name>.sha256.p7s / .sha512.p7s      the signature of each list (CMS, with the certificate)
      <name>.sha256.p7s.tsr / ...tsr       the timestamp of each signature (RFC 3161)
    WINDOWS .cat (made on Windows by New-CodeSignCatalog.ps1 or Sign-Code.ps1 -Catalog)
      this script can SIGN an existing .cat (--sign-cat) and check its signature (--verify).
  Only SHA-256 and SHA-512. Never MD5 or SHA-1.

QUICK START
  Make and sign a catalog of a publish folder (the catalog files go into the folder):
     SIGN_PFX_PASSWORD='...' ./New-CodeSignCatalog.sh --folder ./publish --pfx codesign.pfx
  Check it later (on the server, in the pipeline, by the auditor):
     ./New-CodeSignCatalog.sh --verify ./publish/publish.sha256 --chain-file ca-bundle.pem
  Sign a Windows catalog that was made on Windows:
     ./New-CodeSignCatalog.sh --sign-cat ./publish/app.cat --pfx codesign.pfx

MAKE A CATALOG
  --folder <dir>           The folder. Every file in it, in sub-folders too (--no-recurse: not).
  --include / --exclude <glob>   On the path inside the folder (for example --exclude 'logs/*').
  --name <base>            File name of the catalog. Default: the name of the folder.
  --out-folder <dir>       Where the catalog goes. Default: into --folder (it then ships with the
                           files; the catalog files themselves are never in the list).
  --unsigned               Only the .sha256 / .sha512 lists, no signature.

THE CERTIFICATE (a code-signing certificate; never a password on the command line)
  --pfx <file>             A .pfx / .p12. Password: the variable named by --pfx-password-env
                           (default SIGN_PFX_PASSWORD); not set + a terminal = you are asked.
  --cert-pem <f> --key-pem <f>   PEM files. Key password: --key-password-env (default SIGN_KEY_PASSWORD).
  --chain-file <pem>       CA certificates: put into the signature, and trusted by --verify.

TIMESTAMP (without one the signature ends when the certificate expires)
  --timestamp <list>       Servers tried in this order until one answers. Default: digicert,globalsign.
                           Names: digicert globalsign sectigo sslcom certum entrust microsoft
                           identrust quovadis swisssign buypass harica freetsa, a URL, or none.
  --timestamp-url <url>    Your own RFC 3161 server (tried first).

CHECK A CATALOG
  --verify <file>          <name>.sha256 / .sha512 (portable) or a .cat (Windows). It checks:
                           the signature of the list, the certificate (subject, key, SHA-256 /
                           SHA-512 fingerprint), the timestamp, the chain, and EVERY file of the
                           list: changed = TAMPERED, missing = FAILED. Files that are NOT in the
                           list are named (WARN; --strict: FAILED).
  --root <dir>             The folder the list is about. Default: the folder of the list.
  --expect-sha256 <hex>    The signing certificate must be this one.
  --strict                 An untrusted chain or a file that is not in the list fails.
  A .cat on Linux / macOS: its signature and timestamp are checked (osslsigncode). Which files it
  covers is checked on Windows (New-CodeSignCatalog.ps1 -Verify, Test-FileCatalog).

OTHER
  --sign-cat <file.cat>    Sign a Windows catalog (osslsigncode), timestamp it, check it, and write
                           <file>.cat.sha256 / .sha512.
  --ci       Pipeline mode (no questions; also on by itself in a known build system).
  --verbose  Every command line.     --help  This text.     --version  Version and system report.

EXIT CODES
  0 done / every file matches   1 wrong option or input   2 the certificate is refused
  3 no timestamp server answered   4 a tool is missing (nothing written)   6 the check failed
  (TAMPERED, missing file, bad signature)   7 no file in the folder
HELP_EOF
}

