FOLDER=''; INCL=(); EXCL=(); NOREC=0; NAME=''; OUTF=''; UNSIGNED=0; PFX=''; PFX_ENV=SIGN_PFX_PASSWORD; CERT_PEM=''; KEY_PEM=''
