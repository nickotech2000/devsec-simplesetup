pki_version_info() {
  # --version: the same report in every script (.ps1 and .sh). Plain text, 100 columns, no changes to the system.
  set +e +u +o pipefail 2>/dev/null
  local rule dash name uname_s kind osname osver patch arch platform id vid pretty rel maj ok
  rule="$(printf '%100s' '' | tr ' ' '=')"; dash="$(printf '%100s' '' | tr ' ' '-')"
  _row() { local label="$1" value="$2" first rest; first="${value%%$'\n'*}"; printf ' %-15s: %s\n' "$label" "$first"
           if [ "$value" != "$first" ]; then rest="${value#*$'\n'}"; printf '%s\n' "$rest" | while IFS= read -r l; do printf '%18s%s\n' '' "$l"; done; fi; }
  _run() { timeout 8 "$@" 2>&1 | tr -d '\000'; }
  _first() { printf '%s\n' "$1" | head -n1 | sed 's/[[:space:]]*$//'; }
  _find() { type -ap "$1" 2>/dev/null | awk '!s[$0]++'; }
  _key() { printf '%s\n' "$1" | sed -E 's/^([0-9]+(\.[0-9]+){0,3}).*/\1/'; }
  uname_s="${PKI_FAKE_UNAME:-$(uname -s 2>/dev/null)}"
  arch="$(uname -m 2>/dev/null)"; case "$arch" in x86_64) arch=X64 ;; aarch64|arm64) arch=Arm64 ;; i?86) arch=X86 ;; esac
  kind=other; osname="$uname_s"; osver=''; patch=''; platform='NOT supported'
  if [ "$uname_s" = Darwin ]; then
    kind=macos; osname=macOS; platform='REJECTED (macOS is not supported)'
  elif [ "$uname_s" = Linux ]; then
    kind=linux; rel="${PKI_OS_RELEASE_FILE:-/etc/os-release}"; id=''; vid=''; pretty=''
    if [ -r "$rel" ]; then id="$( . "$rel"; echo "${ID:-}")"; vid="$( . "$rel"; echo "${VERSION_ID:-}")"; pretty="$( . "$rel"; echo "${PRETTY_NAME:-}")"; fi
    osname="${pretty:-Linux}"; osver="$vid"; patch="kernel $(uname -r 2>/dev/null)"
    maj="${vid%%.*}"; case "$maj" in ''|*[!0-9]*) maj=0 ;; esac; ok=0
    case "$id" in ubuntu) [ "$maj" -ge 24 ] && ok=1 ;; centos|rhel|rocky|ol) [ "$maj" -ge 10 ] && ok=1 ;; sles|sles_sap|sled|opensuse-leap) [ "$maj" -ge 15 ] && ok=1 ;; opensuse-tumbleweed) ok=1 ;; esac
    if [ "$ok" = 1 ]; then platform='supported: full (Classic and Quantum)'; else platform='NOT supported (see the platform list in the manual)'; fi
  fi
  name="$(basename "$0")"
  echo "$rule"; echo " $name  -  version information"; echo "$rule"
  echo ' SCRIPT'
  _row Name "$name"
  _row Version "$PKI_VER_NUMBER   (build of $PKI_VER_DATE)"
  _row Author 'Nicko Satria Utama'
  _row Company 'Agantra Inovatif OÜ (NextMantra)'
  _row Email 'nicko@nextmantra.com'
  echo "$dash"; echo ' OPERATING SYSTEM'
  _row Name "$osname"
  [ -n "$osver" ] && _row Version "$osver"
  [ -n "$patch" ] && _row Patch/kernel "$patch"
  [ -n "$arch" ] && _row Architecture "$arch"
  _row Platform "$platform"
  if [ "$kind" = macos ]; then echo "$dash"; echo ' macOS is rejected by these scripts. Nothing else is checked.'; echo "$rule"; return 5; fi

  echo "$dash"; echo ' .NET'
  local dn sdks rts first rest
  dn="$(_find dotnet | head -n1)"
  if [ -n "$dn" ]; then
    sdks="$(_run "$dn" --list-sdks | awk '/^[0-9]+\.[0-9]+\.[0-9]+/ {print $1}' | sort -rV)"
    rts="$(_run "$dn" --list-runtimes | awk '/^Microsoft\./ {sub(/^Microsoft\./,"",$1); print $1, $2}' | sort -k1,1 -k2,2Vr | awk '!s[$1]++ {print $1" "$2}')"
    if [ -n "$sdks" ]; then first="$(printf '%s\n' "$sdks" | head -n1)"; rest="$(printf '%s\n' "$sdks" | tail -n +2 | paste -sd, - | sed 's/,/, /g')"
      if [ -n "$rest" ]; then _row 'SDK (latest)' "$first   (also $rest)"; else _row 'SDK (latest)' "$first"; fi
    else _row 'SDK (latest)' 'none installed'; fi
    if [ -n "$rts" ]; then _row Runtime "$rts"; else _row Runtime 'none installed'; fi
  else _row 'SDK (latest)' 'not found'; _row Runtime 'not found'; fi
  _row Framework 'n/a (Windows only)'

  echo "$dash"; echo ' NODE.JS, PYTHON 3, JAVA'
  local nd nv py pp p t jv jt jver jven jc jct
  nd="$(_find node | head -n1)"; nv=''; [ -n "$nd" ] && nv="$(_first "$(_run "$nd" --version)")"
  if printf '%s' "$nv" | grep -Eq '^v?[0-9]+\.[0-9]+\.[0-9]+'; then _row Node.js "$(printf '%s' "$nv" | sed -E 's/^v?([0-9]+\.[0-9]+\.[0-9]+).*/\1/')   $nd"; else _row Node.js 'not found'; fi
  py=''; pp=''
  for c in python3 python; do for p in $(_find $c); do t="$(_first "$(_run "$p" --version)")"; if printf '%s' "$t" | grep -Eq '^Python 3\.[0-9]+'; then py="${t#Python }"; pp="$p"; break; fi; done; [ -n "$py" ] && break; done
  if [ -n "$py" ]; then _row 'Python 3' "$py   $pp"; else _row 'Python 3' 'not found'; fi
  jv="$(_find java | head -n1)"; jt=''; [ -n "$jv" ] && jt="$(_run "$jv" -XshowSettings:properties -version)"
  if printf '%s' "$jt" | grep -Eq 'version "[^"]+"'; then
    jver="$(printf '%s\n' "$jt" | sed -nE 's/.*version "([^"]+)".*/\1/p' | head -n1)"; jven="$(printf '%s\n' "$jt" | sed -nE 's/^ *java\.vendor = (.+)$/\1/p' | head -n1 | sed 's/[[:space:]]*$//')"
    if [ -n "$jven" ]; then _row 'Java runtime' "$jver   $jven"; else _row 'Java runtime' "$jver"; fi
  else _row 'Java runtime' 'not found'; fi
  jc="$(_find javac | head -n1)"; jct=''; [ -n "$jc" ] && jct="$(_run "$jc" -version | grep -m1 '^javac ')"
  if printf '%s' "$jct" | grep -Eq '^javac '; then _row 'JDK (javac)' "${jct#javac }"; else _row 'JDK (javac)' 'not found'; fi

  echo "$dash"; echo ' SHELLS'
  local pl psl bs bt oth f s
  pl=''; for p in $(_find pwsh); do t="$(_run "$p" -NoProfile -Command '$PSVersionTable.PSVersion.ToString()')"; t="$(_first "$t")"; printf '%s' "$t" | grep -Eq '^[0-9]+\.[0-9]+' && pl="$pl$t"$'\n'; done
  psl="$(printf '%s' "$pl" | awk 'NF && !s[$0]++' | sort -V | paste -sd, - | sed 's/,/, /g')"
  if [ -n "$psl" ]; then _row PowerShell "$psl"; else _row PowerShell 'not found'; fi
  bs="$(_find bash | head -n1)"; bt=''; [ -n "$bs" ] && bt="$(_first "$(_run "$bs" --version)")"
  if printf '%s' "$bt" | grep -Eq 'version [0-9]'; then _row Bash "$(printf '%s' "$bt" | sed -E 's/.*version ([^ ]+).*/\1/')   $bs"; else _row Bash 'not found'; fi
  oth=''
  for s in zsh fish tcsh ksh dash csh; do
    f="$(_find $s | head -n1)"; [ -z "$f" ] && continue
    [ "$s" = csh ] && printf '%s' "$oth" | grep -q 'tcsh' && continue
    t=''; case "$s" in zsh|fish|tcsh) t="$(_first "$(_run "$f" --version)")" ;; esac
    if printf '%s' "$t" | grep -Eq '[0-9]+\.[0-9]+'; then oth="$oth$s $(printf '%s' "$t" | grep -Eo '[0-9]+\.[0-9]+(\.[0-9]+)*' | head -n1), "; else oth="$oth$s (present), "; fi
  done
  oth="${oth%, }"; if [ -n "$oth" ]; then _row 'Other shells' "$oth"; else _row 'Other shells' 'none found'; fi

  echo "$dash"; echo ' TLS: SCHANNEL AND OPENSSL'
  _row Schannel 'n/a (Windows only)'
  local cands npath known g cfg sdir sec l real pre ld ver lib vendor own role idx rows seen ok4 line
  cands="$(_find openssl)"; npath=$(printf '%s\n' "$cands" | grep -c .)
  known=''; for g in /usr/bin/openssl /usr/local/bin/openssl /usr/local/ssl/bin/openssl /opt/openssl*/bin/openssl /opt/*/bin/openssl /usr/local/openssl*/bin/openssl; do for f in $g; do [ -x "$f" ] && known="$known$f"$'\n'; done; done
  sdir="$(cd "$(dirname "$0")" 2>/dev/null && pwd)"; cfg="$sdir/pki_tools.cnf"
  if [ -r "$cfg" ]; then known="$known$(awk '/^[ \t]*\[/ {sec=$0; gsub(/[ \t\[\]]/,"",sec)} sec=="openssl" && /^[ \t]*Path[ \t]*=/ {sub(/^[^=]*=[ \t]*/,""); sub(/[ \t]+$/,""); print}' "$cfg" | while IFS= read -r l; do [ -x "$l" ] && echo "$l"; done)"$'\n'; fi
  cands="$(printf '%s\n%s\n' "$cands" "$known" | grep .)"
  seen=''; rows=0; idx=0; ok4=0
  while IFS= read -r p; do
    [ -z "$p" ] && continue
    real="$(readlink -f "$p" 2>/dev/null)"; [ -z "$real" ] && real="$p"
    case "$seen" in *"|$real|"*) idx=$((idx+1)); continue ;; esac; seen="$seen|$real|"
    ld=''; pre="$(dirname "$(dirname "$real")")"; [ -n "$pre" ] && [ "$pre" != /usr ] && ld="$pre/lib64:$pre/lib"
    t="$(LD_LIBRARY_PATH="${ld}${ld:+:}${LD_LIBRARY_PATH:-}" _run "$real" version)"
    if ! printf '%s' "$t" | grep -Eq '(OpenSSL|LibreSSL) [0-9]+\.[0-9]+\.[0-9]+'; then idx=$((idx+1)); continue; fi
    lib="$(printf '%s' "$t" | grep -Eo '(OpenSSL|LibreSSL) [0-9]+\.[0-9]+\.[0-9]+[^ ]*' | head -n1)"; ver="${lib#* }"; lib="${lib%% *}"
    if [ "$lib" = LibreSSL ]; then vendor='LibreSSL project'
    else
      own="$(_first "$(dpkg -S "$real" 2>/dev/null)")"
      if printf '%s' "$own" | grep -Eq '^[a-z0-9][A-Za-z0-9.+_-]*(:[a-z0-9]+)?: /'; then vendor="package $(printf '%s' "$own" | sed -E 's/^([^:]+).*/\1/') (dpkg)"
      else own="$(_first "$(rpm -qf "$real" 2>/dev/null)")"
        if [ -n "$own" ] && ! printf '%s' "$own" | grep -Eqi 'not owned|error|No such'; then vendor="package $own (rpm)"; else vendor='built from source code (openssl.org), not a package'; fi
      fi
    fi
    if [ "$rows" = 0 ] && [ "$idx" -lt "$npath" ]; then role=Default; else role=Side; fi
    _row "$role OpenSSL" "$ver   $real"$'\n'"from: $vendor"
    printf '%s' "$ver" | grep -Eq '^[4-9]\.' && ok4=1
    rows=$((rows+1)); idx=$((idx+1))
  done <<< "$cands"
  if [ "$rows" = 0 ]; then _row OpenSSL 'not found'
  elif [ "$ok4" = 1 ]; then _row 'PKI needs' 'OpenSSL 4.x: found'
  else _row 'PKI needs' 'OpenSSL 4.x: NOT found (Install-DevEnvironment can install it)'; fi
  echo "$rule"
  return 0
}
