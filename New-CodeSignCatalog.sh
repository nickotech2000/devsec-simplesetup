else case "$("$OPENSSL" version 2>/dev/null)" in 'OpenSSL 3.'*|'OpenSSL 4.'*) ;; *) missing+=("OpenSSL 3 or newer (found: $("$OPENSSL" version 2>/dev/null))") ;; esac; fi
if [ "$MODE" = create ] && [ "$UNSIGNED" = 0 ] && [ "${#TS_URLS[@]}" -gt 0 ]; then command -v curl >/dev/null 2>&1 || missing+=('curl (sudo apt install curl   or   sudo dnf install curl)'); fi
case "$MODE:${VERIFY##*.}" in signcat:*|verify:cat|verify:CAT) command -v osslsigncode >/dev/null 2>&1 || missing+=('osslsigncode (Ubuntu: sudo apt install osslsigncode   RHEL: sudo dnf install osslsigncode (EPEL)   macOS: brew install osslsigncode)') ;; esac
if [ "${#missing[@]}" -gt 0 ]; then for m in "${missing[@]}"; do say ERROR "Missing tool: $m"; done; die 4 'Install the missing tool(s) and run again. Nothing was written.'; fi

WORK="$(mktemp -d "${TMPDIR:-/tmp}/codesign-catalog.XXXXXX")"; chmod 700 "$WORK"; trap 'rm -rf "$WORK"' EXIT
run() { detail "> $*"; "$@" >"$WORK/out.log" 2>&1 </dev/null; local rc=$?; [ "$VERBOSE" = 1 ] && sed 's/^/[VERBOSE]   /' "$WORK/out.log"; return $rc; }
SYS_BUNDLE=''; for b in /etc/ssl/certs/ca-certificates.crt /etc/pki/tls/certs/ca-bundle.crt /etc/ssl/ca-bundle.pem /etc/ssl/cert.pem /etc/pki/ca-trust/extracted/pem/tls-ca-bundle.pem; do [ -f "$b" ] && { SYS_BUNDLE="$b"; break; }; done
: > "$WORK/trust.pem"; [ -n "$SYS_BUNDLE" ] && cat "$SYS_BUNDLE" >> "$WORK/trust.pem"; [ -n "$CHAINF" ] && cat "$CHAINF" >> "$WORK/trust.pem"
hexhash() { "$OPENSSL" dgst "-$1" -r "$2" | cut -d' ' -f1; }
write_sums() { local a; for a in sha256 sha512; do printf '%s  %s\n' "$(hexhash $a "$1")" "$(basename "$1")" > "$1.$a"; done; }
cert_line() {  # pem -> prints the certificate block (subject, issuer, key, fingerprints)
  local p="$1" key
  key="$("$OPENSSL" x509 -in "$p" -noout -text 2>/dev/null | awk '/Public Key Algorithm/{a=$NF} /Public-Key:/{gsub(/[()]/,""); b=$(NF-1)} /NIST CURVE|ASN1 OID/{c=$NF} END{if(a~/rsa/) print "RSA-" b; else if (a~/ec/) print "EC " c " (" b " bit)"; else print a " " b}')"
  printf '  %-14s: %s\n' 'Subject' "$("$OPENSSL" x509 -in "$p" -noout -subject -nameopt RFC2253 | sed 's/^subject=//')" \
    'Issuer' "$("$OPENSSL" x509 -in "$p" -noout -issuer -nameopt RFC2253 | sed 's/^issuer=//')" \
    'Valid' "$("$OPENSSL" x509 -in "$p" -noout -startdate | sed 's/.*=//')  to  $("$OPENSSL" x509 -in "$p" -noout -enddate | sed 's/.*=//')" \
    'Key' "$key" \
    'Cert SHA-256' "$("$OPENSSL" x509 -in "$p" -noout -fingerprint -sha256 | sed 's/.*=//; s/://g' | tr '[:upper:]' '[:lower:]')" \
    'Cert SHA-512' "$("$OPENSSL" x509 -in "$p" -noout -fingerprint -sha512 | sed 's/.*=//; s/://g' | tr '[:upper:]' '[:lower:]')"
}

# ---------------------------------------------------------------- the certificate and key (create, sign-cat)
load_certificate() {
  CERT="$WORK/cert.pem"; KEY="$WORK/key.pem"; CHAIN="$WORK/chain.pem"; : > "$CHAIN"; ( umask 077; : > "$KEY" )
  if [ -n "$PFX" ]; then
    local pw="${!PFX_ENV:-}"
    if [ -z "$pw" ] && [ "$CI" = 0 ] && [ -t 0 ]; then read -r -s -p 'PFX password: ' pw; echo; fi
    export CAT_PFX_PASS="$pw"
    local leg=()
    "$OPENSSL" pkcs12 -in "$PFX" -nokeys -clcerts -passin env:CAT_PFX_PASS -out "$CERT" >/dev/null 2>&1 || leg=(-legacy)
    "$OPENSSL" pkcs12 "${leg[@]}" -in "$PFX" -nokeys -clcerts -passin env:CAT_PFX_PASS -out "$CERT" >/dev/null 2>&1 || die 1 "The PFX could not be opened (wrong password in $PFX_ENV?)."
    "$OPENSSL" pkcs12 "${leg[@]}" -in "$PFX" -nocerts -nodes -passin env:CAT_PFX_PASS -out "$KEY" >/dev/null 2>&1 || die 1 'The private key could not be read from the PFX.'
    "$OPENSSL" pkcs12 "${leg[@]}" -in "$PFX" -nokeys -cacerts -passin env:CAT_PFX_PASS -out "$CHAIN" >/dev/null 2>&1 || true
    unset CAT_PFX_PASS
  else
    export CAT_KEY_PASS="${!KEY_ENV:-}"
    awk '/BEGIN CERTIFICATE/{n++} n==1{print} /END CERTIFICATE/{if(n==1) exit}' "$CERT_PEM" > "$CERT"
    awk '/BEGIN CERTIFICATE/{n++} n>=2{print}' "$CERT_PEM" > "$CHAIN"
    "$OPENSSL" pkey -in "$KEY_PEM" -passin env:CAT_KEY_PASS -out "$KEY" >/dev/null 2>&1 || die 1 "The private key could not be opened (password in $KEY_ENV?)."
    unset CAT_KEY_PASS
  fi
  [ -n "$CHAINF" ] && cat "$CHAINF" >> "$CHAIN"
  [ -s "$CERT" ] || die 1 'No certificate was found.'
  # each CA certificate once (the PFX and --chain-file often hold the same ones; CMS refuses a duplicate)
  if [ -s "$CHAIN" ]; then
    local seen one fp k=0; seen=" $("$OPENSSL" x509 -in "$CERT" -noout -fingerprint -sha256 | cut -d= -f2) "; : > "$WORK/chain1.pem"
    while :; do
      k=$((k+1)); one=$(awk -v k=$k '/BEGIN CERTIFICATE/{n++} n==k{print} /END CERTIFICATE/{if(n==k) exit}' "$CHAIN"); [ -n "$one" ] || break
      fp=$(printf '%s\n' "$one" | "$OPENSSL" x509 -noout -fingerprint -sha256 2>/dev/null | cut -d= -f2); [ -n "$fp" ] || continue
      case "$seen" in *" $fp "*) continue;; esac
      seen="$seen$fp "; printf '%s\n' "$one" >> "$WORK/chain1.pem"
    done
    mv -f "$WORK/chain1.pem" "$CHAIN"
  fi
  [ "$("$OPENSSL" x509 -in "$CERT" -noout -pubkey | tr -d ' \n')" = "$("$OPENSSL" pkey -in "$KEY" -pubout 2>/dev/null | tr -d ' \n')" ] || die 2 'The private key does NOT belong to the certificate.'
  "$OPENSSL" x509 -in "$CERT" -noout -checkend 0 >/dev/null || die 2 'The certificate has EXPIRED (or is not valid yet).'
  "$OPENSSL" x509 -in "$CERT" -noout -ext extendedKeyUsage 2>/dev/null | grep -q 'Code Signing' || die 2 'The certificate is not for Code Signing (Extended Key Usage 1.3.6.1.5.5.7.3.3 is missing).'
  echo '----- CERTIFICATE ---------------------------------------------------------------'
  cert_line "$CERT"
}

# ---------------------------------------------------------------- timestamp (RFC 3161) of a file -> <file>.tsr
timestamp_file() {  # file -> 0 when a server answered
  local f="$1" u st
  [ "${#TS_URLS[@]}" -gt 0 ] || return 1
  "$OPENSSL" ts -query -data "$f" -sha256 -cert -out "$WORK/q.tsq" 2>/dev/null || die 3 'OpenSSL could not make a timestamp request.'
  for u in "${TS_URLS[@]}"; do
    detail "> POST $u (RFC 3161)"
    rm -f "$WORK/r.tsr"
    if curl -sS --max-time 20 -H 'Content-Type: application/timestamp-query' --data-binary "@$WORK/q.tsq" -o "$WORK/r.tsr" "$u" 2>"$WORK/curl.log" && [ -s "$WORK/r.tsr" ]; then
      st="$("$OPENSSL" ts -reply -in "$WORK/r.tsr" -text 2>/dev/null | sed -n 's/^Status: *//p' | head -n1)"
      case "$st" in Granted*) cp "$WORK/r.tsr" "$f.tsr"; TS_USED="$u"; return 0 ;; esac
      say WARN "Timestamp server $u answered '$st'. Trying the next one."
    else say WARN "Timestamp server $u does not answer ($(head -c 200 "$WORK/curl.log")). Trying the next one."; fi
  done
  return 1
}

# ================================================================ MAKE A CATALOG
if [ "$MODE" = create ]; then
  FOLDER="$(cd "$FOLDER" && pwd)"; [ -n "$NAME" ] || NAME="$(basename "$FOLDER")"
  [ -n "$OUTF" ] || OUTF="$FOLDER"; mkdir -p "$OUTF"; OUTF="$(cd "$OUTF" && pwd)"
  OUTN="$OUTF/$NAME"
  matches() {
    local n="$1" g ok=1
    if [ "${#INCL[@]}" -gt 0 ]; then ok=0; for g in "${INCL[@]}"; do [[ "$n" == $g || "$(basename "$n")" == $g ]] && ok=1; done; fi
    for g in "${EXCL[@]}"; do [[ "$n" == $g || "$(basename "$n")" == $g ]] && ok=0; done
    [ "$ok" = 1 ]
  }
  depth=(); [ "$NOREC" = 1 ] && depth=(-maxdepth 1)
  LIST=()
  while IFS= read -r -d '' f; do
    rel="${f#"$FOLDER"/}"
    case "$f" in "$OUTN.sha256"|"$OUTN.sha512"|"$OUTN.sha256.p7s"|"$OUTN.sha512.p7s"|"$OUTN.sha256.p7s.tsr"|"$OUTN.sha512.p7s.tsr") continue ;; esac
    matches "$rel" || continue
    LIST+=("$rel")
  done < <(find "$FOLDER" "${depth[@]}" -type f -print0 2>/dev/null | LC_ALL=C sort -z)
  [ "${#LIST[@]}" -gt 0 ] || die 7 "No file in $FOLDER."
  [ "$UNSIGNED" = 1 ] || load_certificate
  # the lists
  for a in sha256 sha512; do
    : > "$WORK/list.$a"
    for rel in "${LIST[@]}"; do printf '%s  %s\n' "$(hexhash $a "$FOLDER/$rel")" "$rel" >> "$WORK/list.$a"; done
  done
  # everything is made in the private temp folder first: a failure (no timestamp server ...) leaves no half catalog behind
  M="$WORK/$NAME"; parts=(sha256 sha512)
  for a in sha256 sha512; do cp "$WORK/list.$a" "$M.$a"; done
  if [ "$UNSIGNED" = 0 ]; then
    cf=(); [ -s "$CHAIN" ] && cf=(-certfile "$CHAIN")
    TS_USED=''
    for a in sha256 sha512; do
      run "$OPENSSL" cms -sign -binary -in "$M.$a" -signer "$CERT" -inkey "$KEY" "${cf[@]}" -md sha256 -nosmimecap -outform DER -out "$M.$a.p7s" \
        || die 1 "The signature could not be made: $(tail -n 3 "$WORK/out.log")"
      parts+=("$a.p7s")
      if [ "${#TS_URLS[@]}" -gt 0 ]; then
        timestamp_file "$M.$a.p7s" || die 3 "No timestamp server answered (tried: ${TS_URLS[*]}). Nothing was written. Use --timestamp none for a test without one."
        parts+=("$a.p7s.tsr")
      fi
    done
    : > "$KEY"
  fi
  written=()
  for x in sha256.p7s sha256.p7s.tsr sha512.p7s sha512.p7s.tsr; do rm -f "$OUTN.$x"; done
  for x in "${parts[@]}"; do cp "$M.$x" "$OUTN.$x"; written+=("$OUTN.$x"); done
  say OK "Catalog of ${#LIST[@]} file(s): $OUTN.sha256, $OUTN.sha512"
  if [ "$UNSIGNED" = 0 ]; then
    if [ -n "$TS_USED" ]; then say OK "Signed and timestamped ($TS_USED)."; else say WARN 'Signed WITHOUT a timestamp (--timestamp none): the signature ends when the certificate expires.'; fi
  fi
  echo '----- WRITTEN -------------------------------------------------------------------'
  for w in "${written[@]}"; do echo "  $w"; done
  say OK "Check it with:  ./New-CodeSignCatalog.sh --verify \"$OUTN.sha256\"$( [ "$OUTF" != "$FOLDER" ] && printf ' --root "%s"' "$FOLDER")$( [ -n "$CHAINF" ] && printf ' --chain-file "%s"' "$CHAINF")"
  exit 0
fi

# ================================================================ SIGN A WINDOWS .cat
if [ "$MODE" = signcat ]; then
  load_certificate
  export CAT_WORK_PASS; CAT_WORK_PASS="$(head -c 24 /dev/urandom | od -An -tx1 | tr -d ' \n')"
  cf=(); [ -s "$CHAIN" ] && cf=(-certfile "$CHAIN")
  "$OPENSSL" pkcs12 -export -inkey "$KEY" -in "$CERT" "${cf[@]}" -out "$WORK/work.pfx" -passout env:CAT_WORK_PASS >/dev/null 2>&1 || die 1 'Could not prepare the signing key.'
  : > "$KEY"
  ts=(); for u in "${TS_URLS[@]}"; do ts+=(-ts "$u"); done
  # -pass: the one-time random password of the temporary key store in the private temp folder (osslsigncode has no variable for it)
  run osslsigncode sign -pkcs12 "$WORK/work.pfx" -pass "$CAT_WORK_PASS" -h sha256 "${ts[@]}" -in "$SIGNCAT" -out "$WORK/signed.cat" \
    || die 1 "osslsigncode could not sign $SIGNCAT: $(grep -m2 -iE 'error|fail' "$WORK/out.log")"
  run osslsigncode verify -in "$WORK/signed.cat" -ignore-cdp
  grep -q 'Signature verification: ok' "$WORK/out.log" || say WARN 'Signed; the chain is not trusted on this computer (normal for a private PKI).'
  cp "$WORK/signed.cat" "$SIGNCAT"; write_sums "$SIGNCAT"
  if [ "${#TS_URLS[@]}" -gt 0 ]; then grep -q 'Timestamp time:' "$WORK/out.log" && say OK "Timestamp: $(grep -m1 'Timestamp time:' "$WORK/out.log" | sed 's/.*: *//')"; fi
  say OK "Signed: $SIGNCAT  (+ .sha256, .sha512)"
  exit 0
fi

# ================================================================ CHECK
failed=0; warns=0
fail() { say ERROR "$*"; failed=$((failed+1)); }
warn() { say WARN "$*"; warns=$((warns+1)); }
case "$VERIFY" in
  *.cat|*.CAT)
    run osslsigncode verify -in "$VERIFY" -ignore-cdp $( [ -n "$CHAINF" ] && printf -- '-CAfile %s -TSA-CAfile %s' "$CHAINF" "$CHAINF")
    if grep -q 'Unable to extract existing signature\|No signature found' "$WORK/out.log"; then fail "$VERIFY: the catalog is NOT signed."
    else
      if grep -q 'MISMATCH' "$WORK/out.log"; then fail "$VERIFY: TAMPERED - the catalog changed after signing."; fi
      osslsigncode extract-signature -in "$VERIFY" -out "$WORK/sig.der" >/dev/null 2>&1 && "$OPENSSL" pkcs7 -inform DER -in "$WORK/sig.der" -print_certs -out "$WORK/certs.pem" 2>/dev/null
      [ -s "$WORK/certs.pem" ] && { awk '/BEGIN CERTIFICATE/{n++} n==1{print} /END CERTIFICATE/{if(n==1) exit}' "$WORK/certs.pem" > "$WORK/leaf.pem"; echo '----- SIGNED BY -----------------------------------------------------------------'; cert_line "$WORK/leaf.pem"; }
      if grep -q 'Signature verification: ok' "$WORK/out.log"; then say OK 'Signature of the catalog: valid, chain trusted.'
      elif [ "$STRICT" = 1 ]; then fail 'The chain of the catalog signature is NOT trusted (give --chain-file for a private PKI).'
      else warn 'The chain of the catalog signature is not trusted here (give --chain-file for a private PKI).'; fi
      if grep -q 'Timestamp time:' "$WORK/out.log"; then say OK "Timestamp: $(grep -m1 'Timestamp time:' "$WORK/out.log" | sed 's/.*: *//')"; else warn 'The catalog has no timestamp.'; fi
      say INFO 'Which files the .cat covers is checked on Windows: New-CodeSignCatalog.ps1 -Verify (Test-FileCatalog).'
    fi ;;
  *)
    LISTF="$(cd "$(dirname "$VERIFY")" && pwd)/$(basename "$VERIFY")"
    case "$LISTF" in *.sha512) ALG=sha512 ;; *.sha256) ALG=sha256 ;; *) die 1 "--verify takes <name>.sha256, <name>.sha512 or a .cat file." ;; esac
    [ -n "$ROOT" ] || ROOT="$(dirname "$LISTF")"; [ -d "$ROOT" ] || die 1 "Folder not found: $ROOT"; ROOT="$(cd "$ROOT" && pwd)"
    P7S="$LISTF.p7s"
    if [ ! -f "$P7S" ]; then
      if [ "$STRICT" = 1 ]; then fail "No signature ($P7S): the list is not signed."; else warn "No signature ($P7S): only the hashes are checked."; fi
    else
      # 1. the signature of the list
      if run "$OPENSSL" cms -verify -binary -inform DER -in "$P7S" -content "$LISTF" -CAfile "$WORK/trust.pem" -purpose any -out /dev/null; then CHAIN_OK=1
      elif run "$OPENSSL" cms -verify -binary -inform DER -in "$P7S" -content "$LISTF" -noverify -out /dev/null; then CHAIN_OK=0
      else CHAIN_OK=x; fi
      if [ "$CHAIN_OK" = x ]; then fail "TAMPERED: the list $(basename "$LISTF") does not match its signature."
      else
        "$OPENSSL" pkcs7 -inform DER -in "$P7S" -print_certs -out "$WORK/certs.pem" 2>/dev/null
        rm -f "$WORK"/c-*.pem; awk -v d="$WORK" '/BEGIN CERTIFICATE/{n++; f=sprintf("%s/c-%02d.pem", d, n)} f{print > f} /END CERTIFICATE/{close(f); f=""}' "$WORK/certs.pem"
        leaf=''; for c in "$WORK"/c-*.pem; do [ -f "$c" ] || continue; "$OPENSSL" x509 -in "$c" -noout -ext basicConstraints 2>/dev/null | grep -q 'CA:TRUE' || { leaf="$c"; break; }; done
        if [ -n "$leaf" ]; then
          echo '----- SIGNED BY -----------------------------------------------------------------'; cert_line "$leaf"
          fp="$("$OPENSSL" x509 -in "$leaf" -noout -fingerprint -sha256 | sed 's/.*=//; s/://g' | tr '[:upper:]' '[:lower:]')"
          if [ "${#EXPECT[@]}" -gt 0 ]; then hit=0; for e in "${EXPECT[@]}"; do [ "$e" = "$fp" ] && hit=1; done; [ "$hit" = 1 ] || fail 'Signed by ANOTHER certificate than --expect-sha256.'; fi
          "$OPENSSL" x509 -in "$leaf" -noout -ext extendedKeyUsage 2>/dev/null | grep -q 'Code Signing' || warn 'The signing certificate has no Code Signing purpose.'
        fi
        say OK "Signature of the list: valid ($(basename "$P7S"))."
        # 2. the timestamp
        TSR="$P7S.tsr"; TSTIME=''
        if [ -f "$TSR" ]; then
          if run "$OPENSSL" ts -verify -data "$P7S" -in "$TSR" -CAfile "$WORK/trust.pem"; then
            TSTIME="$("$OPENSSL" ts -reply -in "$TSR" -text 2>/dev/null | sed -n 's/^Time stamp: *//p' | head -n1)"
            tsa_by="$("$OPENSSL" ts -reply -in "$TSR" -token_out -out "$WORK/tok.der" >/dev/null 2>&1 && "$OPENSSL" pkcs7 -inform DER -in "$WORK/tok.der" -print_certs 2>/dev/null | sed -n 's/^subject=//p' | head -n1)"
            say OK "Timestamp: $TSTIME${tsa_by:+  by $tsa_by}"
          elif grep -qi 'message imprint mismatch\|imprint' "$WORK/out.log"; then fail 'TAMPERED: the timestamp does not belong to this signature.'
          else warn "The timestamp could not be checked: $(grep -m1 -iE 'error|verif' "$WORK/out.log" | sed 's/.*Verify error://; s/.*error:[^:]*:[^:]*:[^:]*://')"; fi
        else warn 'No timestamp: the signature ends when the certificate expires.'; fi
        # 3. the chain (at the time of the timestamp)
        if [ "$CHAIN_OK" = 0 ] && [ -n "$leaf" ] && [ -n "$TSTIME" ]; then
          te="$(date -u -d "$TSTIME" +%s 2>/dev/null || true)"
          [ -n "$te" ] && "$OPENSSL" verify -CAfile "$WORK/trust.pem" -untrusted "$WORK/certs.pem" -attime "$te" "$leaf" >/dev/null 2>&1 && CHAIN_OK=1
        fi
        if [ "$CHAIN_OK" = 1 ]; then say OK 'Chain: trusted.'
        elif [ "$STRICT" = 1 ]; then fail 'Chain: NOT trusted (give --chain-file for a private PKI).'
        else warn 'Chain: not trusted here (give --chain-file for a private PKI).'; fi
      fi
    fi
    # 4. every file of the list
    n=0; bad=0; declare -A INLIST=()
    while IFS= read -r line; do
      [ -n "$line" ] || continue
      want="${line%%  *}"; rel="${line#*  }"; n=$((n+1)); INLIST["$rel"]=1
      if [ ! -f "$ROOT/$rel" ]; then fail "MISSING: $rel"; bad=$((bad+1)); continue; fi
      got="$(hexhash "$ALG" "$ROOT/$rel")"
      if [ "$got" = "$want" ]; then detail "ok: $rel"; else fail "TAMPERED: $rel (the hash differs from the catalog)"; bad=$((bad+1)); fi
    done < "$LISTF"
    say INFO "Files in the catalog: $n, changed or missing: $bad."
    base="${LISTF%.*}"
    while IFS= read -r -d '' f; do
      rel="${f#"$ROOT"/}"
      case "$f" in "$base.sha256"|"$base.sha512"|"$base".sha*.p7s|"$base".sha*.p7s.tsr) continue ;; esac
      [ -n "${INLIST[$rel]:-}" ] && continue
      if [ "$STRICT" = 1 ]; then fail "NOT in the catalog (added later): $rel"; else warn "NOT in the catalog (added later): $rel"; fi
    done < <(find "$ROOT" -type f -print0 2>/dev/null | LC_ALL=C sort -z)
    ;;
esac
if [ "$failed" -gt 0 ]; then say ERROR "Catalog check FAILED ($failed problem(s), $warns warning(s))."; exit 6; fi
say OK "Catalog check passed$( [ "$warns" -gt 0 ] && echo " with $warns warning(s)")."
exit 0
