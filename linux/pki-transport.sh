  [ -t 0 ] || die "No password: use --password-file, PKI_TRANSPORT_PASSWORD, or run in a terminal." 1
  printf 'Package password: '; read -r -s PASS; echo
  [ -n "$PASS" ] || die "Empty password." 1
}

extract_package() {   # -> extracted into $TMP
  local type; type="$(archive_type "$PACKAGE")"
  [ "$type" != unknown ] || die "$PACKAGE is not a zip or 7z archive (first bytes not recognised): not a .certpacked, or damaged." 1
  TMP="$(mktemp -d "${TMPDIR:-/tmp}/certpacked.XXXXXX")" || die "Cannot create a temporary folder." 1
  chmod 700 "$TMP"
  local log="$TMP.log" rc=1
  info "Opening $PACKAGE ($type)"
  find_7z
  if [ "$type" = zip ] && [ -z "$SEVENZ_BIN" ] && command -v unzip >/dev/null 2>&1; then
    unzip -q -o -P "$PASS" -d "$TMP" "$PACKAGE" > "$log" 2>&1; rc=$?
    if [ $rc -ne 0 ] && grep -qiE 'unsupported compression method 99|compression method 99' "$log"; then rc=99; fi
    if [ $rc -eq 0 ]; then rm -f "$log"; return 0; fi
    if [ $rc -ne 99 ]; then if grep -qiE 'incorrect password|bad password|checkdir error' "$log"; then rm -f "$log"; die "WRONG_PASSWORD: the password is wrong (or the file is damaged)." 5; fi; fi
    rm -rf "$TMP"; TMP="$(mktemp -d "${TMPDIR:-/tmp}/certpacked.XXXXXX")"; chmod 700 "$TMP"
  fi
  if [ -z "$SEVENZ_BIN" ]; then
    warn "This package needs 7-Zip (AES-256 or 7z) and none was found."
    if confirm "Install 7-Zip now?" || [ "$DRYRUN" = 1 ]; then
      have_privilege || die "No root and no sudo: cannot install 7-Zip. Install it yourself or use --7z." 6
      install_7z || true
    fi
    find_7z || die "7-Zip is not available. Install it (Ubuntu: apt install 7zip; RHEL family: dnf install p7zip p7zip-plugins from EPEL; SUSE: zypper install 7zip; macOS: brew install sevenzip) or use --7z FILE." 6
  fi
  "$SEVENZ_BIN" x -p"$PASS" -y -bd -o"$TMP" "$PACKAGE" > "$log" 2>&1 < /dev/null; rc=$?
  if [ $rc -ne 0 ]; then
    if grep -qiE 'wrong password|can not open encrypted|data error in encrypted|cannot open encrypted' "$log"; then rm -f "$log"; die "WRONG_PASSWORD: the password is wrong (or the file is damaged)." 5; fi
    err "7-Zip failed:"; tail -4 "$log" >&2; rm -f "$log"; exit 1
  fi
  rm -f "$log"
}

# ------------------------------------------------------------------------------------------------ the package list
FILES_TSV=""
read_manifest() {
  FILES_TSV="$TMP/certpack.tsv"
  [ -f "$FILES_TSV" ] && [ -f "$TMP/certpack.json" ] || die "This archive has no certpack.tsv / certpack.json: it is not a .certpacked made by PkiTransport.ps1." 1
  # every file against its SHA-256
  local bad=0 n=0 role path sha size sha1 store ext kind name pki rel id parent
  while IFS="$TAB" read -r role path sha size sha1 store ext kind name pki rel id parent; do
    case "$role" in '#'*|'') continue ;; esac
    n=$((n+1))
    if [ ! -f "$TMP/$path" ]; then err "missing in the package: $path"; bad=$((bad+1)); continue; fi
    if [ "$(sha256_of "$TMP/$path")" != "$sha" ]; then err "SHA-256 differs: $path"; bad=$((bad+1)); fi
  done < "$FILES_TSV"
  [ "$bad" -eq 0 ] || die "The package does not match its own list of files ($bad problem(s))." 1
  ok "Package opened: $n file(s), every SHA-256 matches."
  local created; created="$(grep -m1 '"createdUtc"' "$TMP/certpack.json" | sed 's/.*: *"\(.*\)".*/\1/')"
  local scope_leaf scope_keys scope_issuing
  scope_leaf="$(grep -A4 '"scope"' "$TMP/certpack.json" | grep '"leafcerts"' | grep -c true)"; scope_keys="$(grep -A4 '"scope"' "$TMP/certpack.json" | grep '"caPrivateKeys"' | grep -c true)"
  scope_issuing="$(grep -A5 '"scope"' "$TMP/certpack.json" | grep '"issuingKeysOnly"' | grep -c true)"
  prepare_rows
  info "Made $created. Scope: CA certificates$([ "$scope_leaf" = 1 ] && echo ' + leaf certificates (private keys)')$([ "$scope_keys" = 1 ] && { [ "$scope_issuing" = 1 ] && echo ' + the PKI folder with the keys of the ISSUING (intermediate) CAs only (no root key)' || echo ' + the whole PKI (CA private keys)'; })."
}

# ------------------------------------------------------------------------------------------------ 7.9.1: several PKIs in one package
# rows.tsv : every file, 13 columns (role path sha256 size sha1 store ext kind name pki release id parent); the rows of a package made
#            before 7.9.1 get their PKI from the source folder name (pki-default-01 ...)
# sel.tsv  : the rows chosen by --pki / --release / --ca (shared files, the bundles and the leaf certificates, always)
WORK=""; SEL_TSV=""; ROWS_TSV=""
prepare_rows() {
  WORK="$TMP/.pki-transport"; mkdir -p "$WORK"; ROWS_TSV="$WORK/rows.tsv"; SEL_TSV="$WORK/sel.tsv"
  local defpki="" defrel="" src leaf
  if ! awk -F'\t' '!/^#/ && $11 != "" { f = 1 } END { exit !f }' "$FILES_TSV"; then
    src="$(grep -m1 '"pkiRoot"' "$TMP/certpack.json" | sed 's/.*"pkiRoot" *: *"\(.*\)".*/\1/' | tr '\\' '/' | sed 's#//*#/#g')"
    leaf="${src%/}"; leaf="${leaf##*/}"
    if printf '%s' "$leaf" | grep -Eq '^pki-[a-z][a-z0-9]*-(nocr-)?[0-9]{2,}$'; then defrel="$leaf"; defpki="$(echo "$leaf" | cut -d- -f2)"; [ "$defpki" = default ] && defpki=agantra; fi
  fi
  awk -F'\t' -v OFS='\t' -v dp="$defpki" -v dr="$defrel" '
    /^#/ || $1 == "" { next }
    { for (i = NF + 1; i <= 13; i++) $i = ""
      if ($11 == "" && dr != "" && $1 !~ /^(bundle|bundle-roots|leaf|leaf-index)$/) { $10 = dp; $11 = dr }
      if ($12 == "" && ($1 == "root" || $1 == "intermediate")) { n = $2; sub(/.*\//, "", n); sub(/\.crt$/, "", n); $12 = n }
      print }' "$FILES_TSV" > "$ROWS_TSV"
  awk -F'\t' -v OFS='\t' -v P="$PKI_SEL" -v R="$REL_SEL" -v C="$CA_SEL" '
    function g2re(g,  r) { r = g; gsub(/[.+^$(){}|\\]/, "\\\\&", r); gsub(/\[/, "\\[", r); gsub(/\]/, "\\]", r); gsub(/\*/, ".*", r); gsub(/\?/, ".", r); return "^" r "$" }
    function isroot(k) { return k == "root" || k == "track" || k == "quadrant" }
    BEGIN { np = split(tolower(P), pa, /[,;]/); nr = split(R, ra, /[,;]/); nc = split(C, ca, /[,;]/) }
    { N++; row[N] = $0; role[N] = $1; path[N] = $2; kind[N] = $8; nm[N] = $9; pk[N] = $10; rl[N] = $11; id[N] = $12; par[N] = $13 }
    END {
      for (i = 1; i <= N; i++) {                                   # 1. the PKIs
        if (rl[i] == "") continue; k = pk[i] "|" rl[i]; if (k in okp) continue; ok = 1
        if (np > 0) { ok = 0; for (j = 1; j <= np; j++) if (pa[j] != "" && tolower(pk[i]) == pa[j]) ok = 1 }
        if (ok && nr > 0) { ok = 0; num = rl[i]; sub(/.*-/, "", num)
          for (j = 1; j <= nr; j++) { if (ra[j] == "") continue; if (ra[j] ~ /^[0-9]+$/) { if ((num + 0) == (ra[j] + 0)) ok = 1 } else if (rl[i] ~ g2re(ra[j])) ok = 1 } }
        okp[k] = ok }
      if (nc > 0) {                                                # 2. the CAs: a root brings every CA below it, any CA its parents
        for (i = 1; i <= N; i++) { if (role[i] != "root" && role[i] != "intermediate") continue; k = pk[i] "|" rl[i]; if (!okp[k]) continue
          key = k "|" id[i]; at[key] = i; slug = path[i]; sub(/.*\//, "", slug); sub(/\.crt$/, "", slug); if (index(slug, rl[i] "-") == 1) slug = substr(slug, length(rl[i]) + 2)
          sl[i] = slug; hit = 0
          for (j = 1; j <= nc; j++) { if (ca[j] == "") continue; re = g2re(ca[j]); if (id[i] ~ re || nm[i] ~ re || slug ~ re) hit = 1 }
          if (hit) { sel[key] = 1; if (isroot(kind[i])) down[key] = 1 } }
        for (key in sel) { x = key; guard = 0; while (x in at && guard < 20) { sel[x] = 1; i = at[x]; if (par[i] == "") break; x = pk[i] "|" rl[i] "|" par[i]; guard++ } }
        do { changed = 0; for (key in at) { i = at[key]; p = pk[i] "|" rl[i] "|" par[i]; if (par[i] != "" && (p in down) && !(key in down)) { down[key] = 1; sel[key] = 1; changed = 1 } } } while (changed)
        for (key in sel) { i = at[key]; keep[pk[i] "|" rl[i]] = 1; cfile[path[i]] = 1; chain[rl[i] "-" sl[i] "-fullchain.crt"] = 1; chain[sl[i] "-fullchain.crt"] = 1 }
        for (k in okp) if (!(k in keep)) okp[k] = 0
      }
      for (i = 1; i <= N; i++) {                                   # 3. the rows
        if (rl[i] == "") { print row[i]; continue }
        if (!okp[pk[i] "|" rl[i]]) continue
        if (nc > 0 && (role[i] == "root" || role[i] == "intermediate") && !(path[i] in cfile)) continue
        if (nc > 0 && role[i] == "chain") { b = path[i]; sub(/.*\//, "", b); if (!(b in chain)) continue }
        print row[i] } }' "$ROWS_TSV" > "$SEL_TSV"
  local npk; npk="$(awk -F'\t' '$11 != "" { print $10 " " $11 }' "$SEL_TSV" | sort -u | wc -l)"
  if [ -n "$PKI_SEL$REL_SEL$CA_SEL" ]; then
    [ "$npk" -gt 0 ] || die "No PKI of this package matches$([ -n "$PKI_SEL" ] && echo " --pki $PKI_SEL")$([ -n "$REL_SEL" ] && echo " --release $REL_SEL")$([ -n "$CA_SEL" ] && echo " --ca $CA_SEL"). It holds: $(awk -F'\t' '$11 != "" { print $10 " " $11 }' "$ROWS_TSV" | sort -u | tr '\n' ',' | sed 's/,$//; s/,/, /g')." 1
  fi
  info "PKIs: $npk of $(awk -F'\t' '$11 != "" { print $10 " " $11 }' "$ROWS_TSV" | sort -u | wc -l) chosen: $(awk -F'\t' '$11 != "" { print $10 " " $11 }' "$SEL_TSV" | sort -u | tr '\n' ',' | sed 's/,$//; s/,/, /g'); $(grep -cE "^(root|intermediate)${TAB}" "$SEL_TSV") CA certificate(s)."
}

pem_sha1() {   # SHA-1 of the first certificate of a PEM file (the Windows thumbprint), upper case; no certificate parser needed (post-quantum too)
  awk '/-----BEGIN CERTIFICATE-----/ { f = 1; next } /-----END CERTIFICATE-----/ { if (f) exit } f' "$1" 2>/dev/null | tr -d '\r\n ' | base64 -d 2>/dev/null | sha1sum | awk '{ print toupper($1) }'
}

# The list of what WE put in the system store: the only proof that a file there is ours. Columns: pki release file sha1 name installedUtc
LEDGER=""
ledger_path() { LEDGER="${PKI_TRANSPORT_STATE_DIR:-${DESTDIR}/var/lib}/pki-transport/installed.tsv"; }
KIT_LEDGER="${PKI_KIT_STATE_DIR:-/var/lib/pki-trust-kit}/installed.tsv"

replace_old_linux() {   # step 1 of the install: the older copy of each chosen PKI goes (STRICT: only files proven ours, never by a name)
  [ "$KEEP_OLD" = 1 ] && { info "--keep-old: older copies of these PKIs stay in the store."; return 0; }
  local target; target="$(store_target)"; ledger_path
  local pkgsha="$WORK/package-sha1"; awk -F'\t' '($1 == "root" || $1 == "intermediate") && $5 != "" { print toupper($5) }' "$ROWS_TSV" | sort -u > "$pkgsha"
  local pairs; pairs="$(awk -F'\t' '($1 == "root" || $1 == "intermediate") && $11 != "" { print $10 "\t" $11 }' "$SEL_TSV" | sort -u)"
  if [ -z "$pairs" ]; then info "This package does not say which PKI it holds: no older copy is removed (remove one with --remove-trust --package <the older package>)."; return 0; fi
  local cand="$WORK/old-candidates"; : > "$cand"
  local pk rl f s
  while IFS="$TAB" read -r pk rl; do
    [ -n "$rl" ] || continue
    # a) the files this script installed for exactly this PKI, with their thumbprint (our list)  b) the files a trust kit installed for it (its list)
    #    A file is never taken because of its name alone: a public CA in a file named like ours stays.
    [ -f "$LEDGER" ] && awk -F'\t' -v p="$pk" -v r="$rl" '!/^#/ && tolower($1) == tolower(p) && $2 == r { print $3 "\t" toupper($4) "\tinstalled earlier (pki-transport list)\t" pfx }' pfx="$PREFIX_NAME" "$LEDGER" >> "$cand"
    [ -f "$KIT_LEDGER" ] && awk -F'\t' -v p="$pk" -v r="$rl" '!/^#/ && $3 == "anchor" && tolower($1) == tolower(p) && $2 == r { print $4 "\t-\tinstalled earlier (trust kit list)\tpki-" tolower(p) "-" }' "$KIT_LEDGER" >> "$cand"
  done <<< "$pairs"
  local n=0 seen="" why want named
  while IFS="$TAB" read -r f want why named; do
    [ -n "$f" ] && [ -f "$f" ] || continue
    case "$f" in "$target"/*) ;; *) continue ;; esac                         # only the system store directory
    case " $seen " in *" $f "*) continue ;; esac; seen="$seen $f"
    case "$(basename "$f")" in "$named"*) ;; *) continue ;; esac            # a file we named: agantra-pki-* (this script), pki-<company>-* (a trust kit of that company)
    s="$(pem_sha1 "$f")"; [ -n "$s" ] || continue
    [ "$want" != "-" ] && [ "$s" != "$want" ] && continue                    # the list says another certificate: not touched
    grep -qx "$s" "$pkgsha" && continue                                      # a certificate of the package itself: kept
    if [ "$DRYRUN" = 1 ]; then dry "rm -f $f   ($why)"; else priv rm -f "$f" || { warn "cannot remove $f"; continue; }; fi
    printf '%s\n' "$s" >> "$WORK/removed-sha1"; n=$((n+1)); ok "removed the old $(basename "$f")   [$why]"
  done < "$cand"
  info "Replace: $(echo "$pairs" | wc -l) PKI(s) in this install; $n older file(s) of exactly these PKIs removed. Public CAs and other PKIs are not touched."
}

ledger_write() {   # after the install: the files placed now (one line each); the rows of the files removed now are dropped
  [ "$DRYRUN" = 1 ] && return 0
  ledger_path; local dir; dir="$(dirname "$LEDGER")"; priv mkdir -p "$dir" 2>/dev/null || return 0
  local tmpl="$WORK/ledger.new"; : > "$tmpl"
  printf '# pki\trelease\tfile\tsha1\tname\tinstalledUtc   (pki-transport.sh: the CA certificates it put in the system store; only these are ever replaced)\n' > "$tmpl"
  if [ -f "$LEDGER" ]; then awk -F'\t' -v rm="$WORK/removed-sha1" -v nw="$WORK/placed" 'BEGIN { while ((getline l < rm) > 0) d[l] = 1; while ((getline l < nw) > 0) { split(l, a, "\t"); d[toupper(a[4])] = 1; f[a[3]] = 1 } } !/^#/ && !(toupper($4) in d) && !($3 in f)' "$LEDGER" >> "$tmpl"; fi
  [ -f "$WORK/placed" ] && cat "$WORK/placed" >> "$tmpl"
  priv cp "$tmpl" "$LEDGER" 2>/dev/null && info "Remembered in $LEDGER (a newer package of the same PKI replaces exactly these files)."
}

want_role() {   # is this role selected by --extract ?  uses $SELECT_LIST (comma separated)
  local role="$1" s
  for s in $(echo "$SELECT_LIST" | tr ',' ' '); do
    case "$s" in
      roots)         case "$role" in root|bundle-roots) return 0 ;; esac ;;
      intermediates) case "$role" in intermediate) return 0 ;; esac ;;
      chains)        case "$role" in chain|bundle|bundle-roots) return 0 ;; esac ;;
      ca)            case "$role" in root|intermediate|chain|bundle|bundle-roots|publish|external|cross) return 0 ;; esac ;;
      leafcerts)     case "$role" in leaf|leaf-index) return 0 ;; esac ;;
      pki)           case "$role" in pki) return 0 ;; esac ;;
      all|fullchain) return 0 ;;
      *) die "Unknown --extract value '$s'. Use roots, intermediates, chains, ca, leafcerts, pki, all (fullchain)." 1 ;;
    esac
  done
  return 1
}

leaf_ok() {   # leaf filter on the top-level folder of leafcerts/<top>/...
  [ -z "$LEAF" ] && return 0
  local path="$1" top s
  top="$(echo "${path#leafcerts/}" | cut -d/ -f1)"
  for s in $(echo "$LEAF" | tr ',' ' '); do case "$top" in $s) return 0 ;; esac; done
  return 1
}

do_list() {
  echo; echo "PKIs IN THIS PACKAGE (chosen): $(awk -F'\t' '$11 != "" { print $10 "|" $11 }' "$SEL_TSV" | sort -u | wc -l)"
  printf '  %-12s %-26s %s\n' COMPANY "PKI FOLDER (--release)" CAs
  awk -F'\t' '($1 == "root" || $1 == "intermediate") { k = $10 "\t" $11; n[k]++ } END { for (k in n) { split(k, a, "\t"); printf "  %-12s %-26s %s\n", a[1], a[2], n[k] } }' "$SEL_TSV" | sort
  echo; printf '%-12s %-24s %-12s %-14s %s\n' COMPANY "PKI FOLDER" KIND ROLE "COMMON NAME   [id]"
  local role path sha size sha1 store ext kind name pki rel id parent n=0
  while IFS="$TAB" read -r role path sha size sha1 store ext kind name pki rel id parent; do
    n=$((n+1))
    case "$role" in root|intermediate) printf '%-12s %-24s %-12s %-14s %s   [%s]\n' "$pki" "$rel" "$kind" "$role" "$name" "$id" ;; esac
  done < "$SEL_TSV"
  echo; local leaves; leaves="$(grep -c "^leaf${TAB}" "$SEL_TSV")"
  info "$n file(s); roles: $(cut -f1 "$SEL_TSV" | sort | uniq -c | awk '{printf "%s=%s ", $2, $1}')"
  [ "$leaves" -gt 0 ] && info "leaf files: $leaves (folders: $(grep "^leaf${TAB}" "$SEL_TSV" | cut -f2 | cut -d/ -f2 | sort -u | tr '\n' ' '))"
}

do_export() {
  mkdir -p "$DEST" || die "Cannot create $DEST" 1
  local role path sha size sha1 store ext kind name pki rel id parent written=0 skipped=0 dst
  while IFS="$TAB" read -r role path sha size sha1 store ext kind name pki rel id parent; do
    want_role "$role" || continue
    case "$role" in leaf|leaf-index) leaf_ok "$path" || continue ;; esac
    dst="$DEST/$path"
    if [ -e "$dst" ]; then
      if [ "$(sha256_of "$dst")" = "$sha" ]; then skipped=$((skipped+1)); continue; fi
      [ "$FORCE" = 1 ] || die "$dst exists and differs. Use --force, or another --dest." 1
    fi
    mkdir -p "$(dirname "$dst")"; cp "$TMP/$path" "$dst"; written=$((written+1))
    case "$path" in leafcerts/*|pki/*) case "$dst" in *.key|*.pfx) chmod 600 "$dst" 2>/dev/null ;; esac ;; esac
  done < "$SEL_TSV"
  [ "$written" -gt 0 ] || [ "$skipped" -gt 0 ] || die "Nothing in this package matches --extract '$SELECT_LIST'." 1
  cp "$TMP/certpack.json" "$TMP/certpack.tsv" "$TMP/README.txt" "$DEST/" 2>/dev/null
  ok "$written file(s) written to $DEST ($skipped identical file(s) left alone)."
}

# ------------------------------------------------------------------------------------------------ trust
trust_candidates() {   # prints the files (relative to $DEST) to install, by --trust
  local role path sha size sha1 store ext kind name pki rel id parent
  while IFS="$TAB" read -r role path sha size sha1 store ext kind name pki rel id parent; do
    case "$TRUST" in
      roots)      [ "$role" = root ] && [ "$ext" != 1 ] && echo "$path" ;;
      enterprise) [ "$role" = root ] && [ "$kind" = root ] && [ "$ext" != 1 ] && echo "$path" ;;
      all-ca)     { [ "$role" = root ] && [ "$ext" != 1 ]; } || [ "$role" = intermediate ] && echo "$path" ;;
    esac
  done < "$SEL_TSV"
}

store_target() { echo "${DESTDIR}${STORE_DIR}"; }

ensure_store_tooling() {   # Linux: the certificate-store tooling of this distribution
  [ "$PLATFORM" = linux ] || return 0
  if [ "$FAMILY" = unknown ] && [ -z "$STORE_DIR_OVERRIDE" ]; then return 0; fi
  local tool="$STORE_TOOL"
  [ -n "$UPDATE_CMD_OVERRIDE" ] && tool="$(echo "$UPDATE_CMD_OVERRIDE" | awk '{print $1}')"
  if command -v "$tool" >/dev/null 2>&1 || [ -n "$DESTDIR" ]; then pass "Certificate store" "$tool found; trust anchors go to $(store_target)"; return 0; fi
  warnx "Certificate store" "$tool not found: the certificate-store tooling of this Linux is not installed"
  [ "$CHECK" = 1 ] && return 0
  if confirm "Install the certificate store package (ca-certificates) now?" || [ "$DRYRUN" = 1 ]; then
    have_privilege || die "No root and no sudo: cannot install ca-certificates." 6
    info "Installing the certificate store ($FAMILY: ca-certificates)"
    pkg_install ca-certificates || die "The package ca-certificates could not be installed." 6
    [ "$DRYRUN" = 1 ] && return 0
    command -v "$tool" >/dev/null 2>&1 || die "$tool is still missing after installing ca-certificates." 6
    ok "Certificate store installed."
  else
    die "The certificate store tooling is missing and was not installed. Install ca-certificates, then run again." 6
  fi
}

update_store() {
  if [ -n "$DESTDIR" ]; then info "--destdir: the store is NOT rebuilt (run '$UPDATE_CMD' on the target system)."; return 0; fi
  info "Rebuilding the system store: $UPDATE_CMD"
  # shellcheck disable=SC2086
  priv $UPDATE_CMD > /tmp/pki-transport-update.$$ 2>&1 || { err "The store update failed:"; tail -5 /tmp/pki-transport-update.$$ >&2; rm -f /tmp/pki-transport-update.$$; return 1; }
  [ "$DRYRUN" = 1 ] || tail -2 /tmp/pki-transport-update.$$ | sed 's/^/        /'
  rm -f /tmp/pki-transport-update.$$
}

install_trust_linux() {
  local target; target="$(store_target)"
  have_privilege || die "Installing into $target needs root (or sudo). Run with sudo, or use --no-trust." 1
  priv mkdir -p "$target"
  [ -n "$(trust_candidates)" ] || die "No CA certificate selected for the store (--trust $TRUST). Extract the CAs: --extract ca." 1
  : > "$WORK/removed-sha1"; : > "$WORK/placed"
  replace_old_linux
  local n=0 f base now; now="$(date -u '+%Y-%m-%d %H:%M')"
  for f in $(trust_candidates); do
    base="$PREFIX_NAME$(basename "$f")"
    case "$base" in *.crt|*.pem) ;; *) base="$base.crt" ;; esac
    if [ "$DRYRUN" = 1 ]; then dry "install -m 0644 $DEST/$f $target/$base"; else priv install -m 0644 "$DEST/$f" "$target/$base" || { err "Cannot write $target/$base"; return 1; }; fi
    awk -F'\t' -v OFS='\t' -v p="$f" -v fl="$target/$base" -v now="$now" '$2 == p { print $10, $11, fl, toupper($5), $9, now; exit }' "$SEL_TSV" >> "$WORK/placed"
    n=$((n+1))
  done
  ok "$n certificate(s) placed in $target (files named ${PREFIX_NAME}*)."
  update_store || return 1
  ledger_write
  INSTALLED_COUNT=$n
}

install_trust_macos() {
  have_privilege || die "Installing into the System keychain needs an administrator (sudo)." 1
  local n=0 bad=0 f role
  for f in $(trust_candidates); do
    role=root; case "$f" in ca/intermediates/*) role=intermediate ;; esac
    if [ "$role" = root ]; then
      if [ "$DRYRUN" = 1 ]; then dry "security add-trusted-cert -d -r trustRoot -k /Library/Keychains/System.keychain $DEST/$f"
      else priv security add-trusted-cert -d -r trustRoot -k /Library/Keychains/System.keychain "$DEST/$f" >/dev/null 2>&1 && n=$((n+1)) || { warn "macOS refused $f (post-quantum certificates may not be supported by this macOS)"; bad=$((bad+1)); }; fi
    else
      if [ "$DRYRUN" = 1 ]; then dry "security add-certificates -k /Library/Keychains/System.keychain $DEST/$f"
      else priv security add-certificates -k /Library/Keychains/System.keychain "$DEST/$f" >/dev/null 2>&1 && n=$((n+1)) || { warn "macOS refused $f"; bad=$((bad+1)); }; fi
    fi
  done
  [ "$DRYRUN" = 1 ] || { [ "$n" -gt 0 ] || die "macOS accepted no certificate." 1; ok "$n certificate(s) added to the System keychain ($bad refused)."; }
  INSTALLED_COUNT=$n
}

verify_chains() {
  [ "$NOVERIFY" = 1 ] && return 0
  [ "$DRYRUN" = 1 ] && return 0
  if [ -z "$OPENSSL" ]; then warn "No OpenSSL 4: the chain proof is skipped."; return 0; fi
  local roots="$DEST/ca/ca-bundle-roots.crt" all="$DEST/ca/ca-bundle-all.crt" ok_n=0 bad_n=0 f bundle
  if [ "$PLATFORM" = linux ] && [ -z "$DESTDIR" ] && [ -r "$SYSTEM_BUNDLE" ]; then bundle="$SYSTEM_BUNDLE"; else bundle="$roots"; fi
  [ -r "$bundle" ] || { warn "No bundle to verify against."; return 0; }
  [ -r "$all" ] || all="$bundle"
  for f in $(trust_candidates) $(grep "^intermediate${TAB}" "$SEL_TSV" | cut -f2); do
    [ -f "$DEST/$f" ] || continue
    if "$OPENSSL" verify -CAfile "$bundle" -untrusted "$all" "$DEST/$f" >/dev/null 2>&1; then ok_n=$((ok_n+1)); else bad_n=$((bad_n+1)); warn "does not verify against $( [ "$bundle" = "$roots" ] && echo 'the package roots' || echo 'the SYSTEM store' ): $f"; fi
  done
  if [ "$bad_n" -eq 0 ]; then ok "$OSSL_TEXT: all $ok_n CA certificate(s) verify against $( [ "$bundle" = "$roots" ] && echo 'the package roots' || echo "the system store ($bundle)")."
  else warn "$bad_n of $((ok_n+bad_n)) CA certificate(s) did not verify."; fi
}

remove_trust() {
  have_privilege || die "Removing from the store needs root (or sudo)." 1
  local n=0 f base target
  if [ "$PLATFORM" = macos ]; then
    local role path sha size sha1 store ext kind name pki rel id parent
    [ -f "$SEL_TSV" ] || die "--remove-trust on macOS needs --package (or --dest with certpack.tsv)." 1
    while IFS="$TAB" read -r role path sha size sha1 store ext kind name pki rel id parent; do
      case "$role" in root|intermediate) ;; *) continue ;; esac
      if [ "$DRYRUN" = 1 ]; then dry "security delete-certificate -Z $sha1 -t /Library/Keychains/System.keychain"; else priv security remove-trusted-cert -d "$TMP/$path" >/dev/null 2>&1; priv security delete-certificate -Z "$sha1" /Library/Keychains/System.keychain >/dev/null 2>&1 && n=$((n+1)); fi
    done < "$SEL_TSV"
    ok "$n certificate(s) removed from the System keychain."; return 0
  fi
  target="$(store_target)"; ledger_path
  local gone=""
  if [ -f "${SEL_TSV:-/nonexistent}" ]; then
    # the files of the chosen PKIs of this package: our file name AND the certificate of the package (thumbprint)
    while IFS="$TAB" read -r f s; do
      base="$PREFIX_NAME$(basename "$f")"; [ -e "$target/$base" ] || continue
      [ "$(pem_sha1 "$target/$base")" = "$(echo "$s" | tr 'a-f' 'A-F')" ] || { warn "$target/$base holds another certificate than the package: left alone."; continue; }
      if [ "$DRYRUN" = 1 ]; then dry "rm -f $target/$base"; else priv rm -f "$target/$base"; fi; n=$((n+1)); gone="$gone $target/$base"
    done < <(awk -F'\t' '$1 == "root" || $1 == "intermediate" { print $2 "\t" $5 }' "$SEL_TSV")
  else
    for f in "$target"/${PREFIX_NAME}*; do [ -e "$f" ] || continue; if [ "$DRYRUN" = 1 ]; then dry "rm -f $f"; else priv rm -f "$f"; fi; n=$((n+1)); gone="$gone $f"; done
  fi
  if [ -f "$LEDGER" ] && [ "$DRYRUN" != 1 ] && [ -n "$gone" ]; then
    local tl; tl="$(mktemp)"
    awk -F'\t' -v g="$gone" 'BEGIN { n = split(g, a, " "); for (i = 1; i <= n; i++) d[a[i]] = 1 } /^#/ || !($3 in d)' "$LEDGER" > "$tl" && priv cp "$tl" "$LEDGER"; rm -f "$tl"
  fi
  ok "$n file(s) ${PREFIX_NAME}* removed from $target."
  if [ -n "$DESTDIR" ]; then return 0; fi
  info "Rebuilding the system store: $UPDATE_CMD$([ "$FAMILY" = debian ] || [ "$FAMILY" = suse ] && echo ' --fresh')"
  if [ "$FAMILY" = debian ] || [ "$FAMILY" = suse ]; then priv $UPDATE_CMD --fresh >/dev/null 2>&1 || priv $UPDATE_CMD >/dev/null 2>&1; else priv $UPDATE_CMD >/dev/null 2>&1; fi
  ok "Store rebuilt."
}

