        if (-not $IsWindows) { Write-PkiLog '-InstallPfx / -InstallTrustedPublisher are for Windows; skipped.' 'WARN' }
        else {
            if ($InstallStore -eq 'LocalMachine') { Assert-Administrator }
            $X = [System.Security.Cryptography.X509Certificates.X509Certificate2]; $fl = [System.Security.Cryptography.X509Certificates.X509KeyStorageFlags]
            foreach ($it in $items) {
                if ($InstallPfx) {
                    if (-not $it.R.Pfx) { Write-PkiLog "No PFX for $($it.R.Stem) (add PFX to -Format); not imported." 'WARN'; continue }
                    $kf = $fl::PersistKeySet -bor $(if ($InstallStore -eq 'LocalMachine') { $fl::MachineKeySet } else { $fl::UserKeySet })
                    $x = $X::new($it.R.Pfx, $Password, $kf)
                    $st = [System.Security.Cryptography.X509Certificates.X509Store]::new('My', $InstallStore); $st.Open('ReadWrite'); try { $st.Add($x) } finally { $st.Close() }
                    Write-PkiLog "  imported   : $($it.R.Stem) -> $InstallStore\My  ($($x.Thumbprint))" 'OK'
                }
                if ($InstallTrustedPublisher) {
                    $pub = $X::new($it.R.Crt)
                    $st = [System.Security.Cryptography.X509Certificates.X509Store]::new('TrustedPublisher', $InstallStore); $st.Open('ReadWrite'); try { $st.Add($pub) } finally { $st.Close() }
                    Write-PkiLog "  trusted    : $($it.R.Stem) -> $InstallStore\TrustedPublisher" 'OK'
                }
            }
        }
    }

    # ---------------- Visual Studio 2026 (MAUI / Xamarin) ----------------
    if ($InstallVisualStudio) {
        if (-not $IsWindows) { Write-PkiLog '-InstallVisualStudio is for Windows; skipped. Copy the .keystore and the .maui-signing.props to the Windows computer.' 'WARN' }
        else { foreach ($it in $items) { Install-PkiCodeSignVisualStudio -Spec $it.Spec -R $it.R -Extra $it.Extra -Password $Password } }
    }

    # ---------------- summary ----------------
    Write-Host ''
    Write-Host 'CODE SIGNING CERTIFICATES' -ForegroundColor Cyan
    Write-Host ("  Folder     : {0}" -f $run.Path)
    Write-Host ("  Level      : {0}   Quadrant {1}   Issuer {2}" -f $level, $quadrant, $iss.Label)
    Write-Host ("  Subject    : {0}" -f (($dn | ForEach-Object { '{0}={1}' -f $_[0], $_[1] }) -join ', '))
    Write-Host ''
    Write-Host ('  {0,-34} {1,-11} {2,-9} {3,-6} {4,-11} {5}' -f 'PLATFORM', 'KEY', 'HASH', 'DAYS', 'EXPIRES', 'SHA-1') -ForegroundColor Cyan
    foreach ($it in $items) {
        Write-Host ('  {0,-34} {1,-11} {2,-9} {3,-6} {4,-11} {5}' -f $it.Spec.CodeSign.Label, $it.R.Actual.Algorithm, $it.Spec.Md, $it.R.Days, $it.R.NotAfter, $it.R.Sha1)
        Write-Host ('  {0,-34} {1}' -f '', $it.Relative) -ForegroundColor DarkGray
    }
    Write-Host ''
    Write-Host '  Files in every platform folder:'
    Write-Host ('      ' + (($items[0].R.Files | ForEach-Object { $_.Replace($items[0].R.Stem, '<name>') }) -join '   '))
    Write-Host ''
    Write-PkiLog "$($items.Count) code signing certificate(s) ready. Sign:  .\Sign-Code.ps1 -UseGenerated -File <file>   (CODESIGN-NOTES.txt in each folder)" 'OK'
    if ($Password -eq 'Abc12345!') { Write-PkiLog 'The PFX password is the lab default Abc12345!. Use -Password for real use.' 'WARN' }
    exit 0
}
catch {
    $failure = $_
    if ($script:RunFolderCreated -and (Test-Path -LiteralPath $script:RunFolderCreated)) {
        try { [void](Unlock-PkiTree -Path @($script:RunFolderCreated)) } catch { }
        Remove-Item -LiteralPath $script:RunFolderCreated -Recurse -Force -ErrorAction SilentlyContinue
    }
    if (-not $Verbose -and $failure.Exception.GetType().Name -eq 'RuntimeException') { Write-Host "[ERROR] $($failure.Exception.Message)" -ForegroundColor Red; exit 1 }
    if (Get-Command Write-PkiFatalError -ErrorAction SilentlyContinue) {
        try { Write-PkiFatalError -ErrorRecord $failure } catch { Write-Host "[FATAL] $($failure.Exception.Message)" -ForegroundColor Red }
    }
    else { Write-Host "[ERROR] $($failure.Exception.Message)" -ForegroundColor Red }
    exit 1
}
finally {
    if ($script:IssuerInfo -and $script:IssuerInfo.Temp -and (Test-Path -LiteralPath $script:IssuerInfo.Temp)) { Remove-Item -LiteralPath $script:IssuerInfo.Temp -Recurse -Force -ErrorAction SilentlyContinue }
    if (Get-Command Clear-PkiSecretEnvironment -ErrorAction SilentlyContinue) { Clear-PkiSecretEnvironment }
}
