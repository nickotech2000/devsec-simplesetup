            $p = [System.Diagnostics.Process]::Start($psi)
            $o = $p.StandardOutput.ReadToEndAsync(); $e = $p.StandardError.ReadToEndAsync()
            if (-not $p.WaitForExit(8000)) { try { $p.Kill() } catch { }; return '' }
            return (($o.Result + "`n" + $e.Result) -replace "`0", '').Trim()
        } catch { return '' }
    }
