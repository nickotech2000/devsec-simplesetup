function Get-FileKind {
    # the kind of a file (or of an Apple bundle folder); Mach-O files without an extension are found by their first bytes
    param([string]$Path)
    $ext = [System.IO.Path]::GetExtension($Path.TrimEnd('\', '/')).TrimStart('.').ToLowerInvariant()
    if (Test-Path -LiteralPath $Path -PathType Container) { if ($ext -in $script:AppleBundles) { return 'apple' }; return $null }
    if ($ext -and $script:Kinds.ContainsKey($ext)) { return $script:Kinds[$ext] }
    if (-not $ext) {
        try {
            $fs = [System.IO.File]::OpenRead($Path); $b = [byte[]]::new(4); $n = $fs.Read($b, 0, 4); $fs.Dispose()
            if ($n -eq 4 -and [Convert]::ToHexString($b) -in 'FEEDFACE', 'FEEDFACF', 'CEFAEDFE', 'CFFAEDFE', 'CAFEBABE', 'BEBAFECA') { return 'apple' }
        }
        catch { }
    }
    return $null
}
