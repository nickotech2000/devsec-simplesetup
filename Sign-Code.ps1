  -Template github|azure|azure-server|gitlab|jenkins|bitbucket|teamcity|aws|gcp|alibaba|msbuild|all
                        Write ready-to-edit pipeline files into transport\signing-ci_<time>\, stop.
  -Help                 this text
  -Version              show version, author, OS and tool versions.

BUILD AGENT SETUP  (DevSecOps)
  The agent needs PowerShell 7+ on Windows (hosted images have it), outbound HTTP (port 80) to the
  timestamp server, and HTTPS to the package sources. On a locked-down agent put the tools in the
  image, add -Installer None and use your own server with -TimestampUrl.
  Secrets: never in the repository, never on the command line.
    Private PKI leaf   store the .pfx as BASE64 in one secret and its password in a second one.
                       Map both to variables, then use  -Ci -PfxBase64Env <NAME>.
                       Make the base64:  [Convert]::ToBase64String([IO.File]::ReadAllBytes("a.pfx"))
    Public OV / EV     the key must be in hardware: use -Provider. The key never reaches the agent.
    Cloud login        use the identity of the pipeline (OIDC, managed identity), not a password.
  Steps: 1) run -Ci -CheckOnly once to prove secret, certificate and timestamp.  2) Put the real
  step AFTER the build and BEFORE publishing.  3) Sign what you ship, not obj\ or test files:
  -Folder <publish folder> -Exclude "*.Tests.dll".  4) Any result other than 0 stops the pipeline.
  Keep sign-report_*.json and the *-signed.sha256 / .sha512 files as proof.

EXAMPLES
