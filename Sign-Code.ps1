function Write-Say {
    param([string]$Level, [string]$Text)
    $c = switch ($Level) { 'OK' { 'Green' } 'WARN' { 'Yellow' } 'ERROR' { 'Red' } default { $null } }
    if ($c) { Write-Host "[$Level] $Text" -ForegroundColor $c } else { Write-Host "[$Level] $Text" }
    if ($script:Ci -and $Level -in 'ERROR', 'WARN') {
        $t = Hide-Secret $Text
        switch ($script:Env) {
            'github' { Write-Host "::$(if ($Level -eq 'ERROR') { 'error' } else { 'warning' })::$t" }
            { $_ -in 'azure', 'azure-server' } { Write-Host "##vso[task.logissue type=$(if ($Level -eq 'ERROR') { 'error' } else { 'warning' })]$t" }
