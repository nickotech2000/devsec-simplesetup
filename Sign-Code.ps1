  Code signing puts your name on a program, so people can see who made it and that nobody changed
  it. This script does the whole job in a safe order:
  1. Reads the code-signing certificate and CHECKS it. A certificate that breaks the rules is
     REFUSED before any file is touched (exit 2).
  2. CHECKS the timestamp server. It must answer, and its own certificate must be valid (exit 3).
  3. Finds the tools it needs. A missing tool is INSTALLED with winget (default) or Chocolatey.
  4. Signs every file you listed, and every supported file in the folders you listed, with a
     timestamp.
  5. Verifies each signature, writes <file>-signed.sha256 and <file>-signed.sha512 next to it and
     prints the certificate.

QUICK START
  0. With the certificates of GenerateCodeSigningCertificate.ps1 (the right one per file type):
        .\Sign-Code.ps1 -UseGenerated -Folder .\bin\Release -Verbose
  1. Check only. Nothing is signed:     .\Sign-Code.ps1 -Pfx .\codesign.pfx -CheckOnly
  2. Sign two files:
        .\Sign-Code.ps1 -Pfx .\codesign.pfx -File .\app.exe, .\app.dll
  3. Sign a whole build folder:         .\Sign-Code.ps1 -Pfx .\codesign.pfx -Folder .\bin\Release
  The PFX password comes from the variable SIGN_PFX_PASSWORD. Not set + a console = you are asked.
  Never write a password on the command line.

THE FILES
  -File <path>         One file, or a list:  -File .\app.exe, .\app.dll
  -Folder <path>       One folder, with its sub-folders, or a list.      -NoRecurse   no sub-folders
  -Include / -Exclude  Wildcards on the file name, e.g. -Exclude "*.Tests.dll"
  -OutFolder <path>    Sign COPIES in this folder. The originals stay untouched. Default: in place.
  -ReportFolder <path> Where sign-report_*.json goes (also env SIGN_REPORT_DIR). Default: transport\ of
                       the DevSec project, or %TEMP%\Sign-Code when this script was copied elsewhere.
  -CleanReports        Delete the old sign-report_*.json of that folder first.
  -ReportFile <file>   ONE report for a whole build session: every run adds its files to it (safe for
                       parallel builds). MSBuild deletes it when a build starts.
  PORTABLE: Sign-Code.ps1 needs no other file of the project: copy it alone into your repository (for
  example build\Sign-Code.ps1) and call it from there (MSBuild: -Template msbuild). Nothing is written
  next to the copy. -UseGenerated then needs -GeneratedRoot (or env SIGN_GENERATED_ROOT).
  -SkipSigned          Do not sign a file that already has a valid signature.
  -RemoveOldSignature  A file that is already signed: remove the old signature first, then sign
                       with the current certificate (PowerShell: the signature block is cut out;
                       Windows files: signtool remove /s). Used by MSBuild for .ps1 files.
  Supported:
    Windows     exe dll sys ocx scr cpl efi ax drv winmd xll msi msp cab cat msix appx vbs js wsf
    PowerShell  ps1 psm1 psd1 ps1xml psc1 cdxml
    .NET        dll / exe of .NET Framework and .NET; NuGet packages nupkg snupkg
    Java        jar war ear (jarsigner)          Android   apk (apksigner), aab (jarsigner)
    Office VBA  docm xlsm pptm dotm xlam ppam xltm potm doc xls ppt dot xla (needs Office: Windows)
    Apple       Mach-O (no extension, found by its first bytes), dylib, bundles .app .framework .appex
                .xpc .kext .plugin .bundle (a FOLDER, signed as one item), dmg, pkg (rcodesign).
                Timestamp: Apple's server unless -Timestamp / -TimestampUrl is given. Gatekeeper
                also needs notarization, which needs a public Apple Developer ID certificate.
  Not supported: Linux packages (rpm, deb, ELF). Use GPG / rpm --addsign.

CATALOG  (files that cannot hold a signature: json, config, xml, js, css, html, images ...)
  -Catalog <file.cat>       After signing, make a Windows catalog (.cat, version 2 = SHA-256) of the
                            folders (and of every -File, also json, config ...), and sign it with
                            the same certificate and timestamp. Auto = <folder>\<folder name>.cat.
                            It gets <file>.cat-signed.sha256 / .sha512 like every signed file.
  -CatalogFolder <dir>      The folders the catalog covers (default: -Folder). With -Catalog and no
                            -File / -Folder, only the catalog is made and signed.
  Check it:  Test-FileCatalog, or New-CodeSignCatalog.ps1 -Verify <file.cat>. A portable catalog
  (any system, SHA-256 + SHA-512 lists): New-CodeSignCatalog.ps1 / .sh.

THE CERTIFICATE  (choose ONE way)
  -UseGenerated             The certificates of GenerateCodeSigningCertificate.ps1 / .sh: it reads
                            leafcerts\codesign\codesign-index.json (or .tsv) and takes, per file, the
                            newest valid certificate of its platform (Windows, Java, Android, Apple,
                            Apple installer for .pkg) and its chain. Password: SIGN_PFX_PASSWORD,
                            not set = the generator default Abc12345!.
    -GeneratedRoot <dir>    Another leafcerts\codesign folder.
    -GeneratedPlatform <p>  Windows | Java | Android | Apple | AppleInstaller: one for all files.
  -Pfx <file>               A .pfx / .p12 file. Password: the variable named by -PfxPasswordEnv
                            (default SIGN_PFX_PASSWORD).
  -CertFolder <dir>         A local folder with the certificate (e.g. leafcerts\codesign\<co>\
                            windows): its newest .pfx, and <name>-chain.crt for the chain check.
  -PfxBase64Env <name>      Name of a variable (a pipeline SECRET) that holds the .pfx as base64.
                            Written to a temporary file, deleted at the end.
  -Thumbprint <hex>         A certificate already in the Windows store (also a smart card / token /
                            HSM key). -StoreLocation CurrentUser (default) or LocalMachine (the
                            Local Machine certificate manager, e.g. a build agent service).
  -Subject <text>           The same, found by subject: the newest valid code signing certificate
                            with a private key, e.g. -Subject "CN=Agantra Inovatif OU".
    -StoreName <name>       The store: My (Personal, default) or any other store name.
  -CertPem <file> -KeyPem <file>
                            Your private PKI leaf as PEM files (GenerateLeafCertificate.ps1
                            -Purpose CodeSigning). Key password: variable -KeyPasswordEnv.
  -Provider <name>          The key lives in a cloud / HSM service and never leaves it (best for
                            pipelines). Give details with -ProviderArg:
                              AzureKeyVault        AzureSignTool   "vault-url|cert-name"
                              AzureTrustedSigning  Artifact Signing  "endpoint|account|profile"
                              AwsKms               Jsign           "region|key-alias"
                              GcpKms               Jsign           "keyring-path|key-alias"
                              Pkcs11               Jsign, any HSM  "pkcs11.cfg"
                              DigiCertKeyLocker    smctl           "key-pair-alias"
                            Tokens and keys are read from the variables the tool expects. This
                            script never puts a secret on a command line.
  -CertFile <file>          With -Provider: the PUBLIC certificate (PEM or .cer), so checks can run.
  -CertSource <x>           PrivatePki | PublicCa | Auto (default). Auto = PublicCa when the chain
                            ends at a root that Windows trusts. PublicCa is stricter (RSA 3072+).
  -ChainFile <file>         CA certificates of your private PKI (ca-bundle.pem) to check the chain.

TIMESTAMP  (without one the signature dies when the certificate expires: always use one)
  -Timestamp <name>         DigiCert,GlobalSign (default: DigiCert first, GlobalSign when DigiCert fails), GlobalSign, Certum, Sectigo, SSLcom, Entrust,
                            Microsoft, Apple, IdenTrust, QuoVadis, SwissSign, Buypass, HARICA,
                            FreeTSA, or a URL. None = no timestamp (Debug builds and tests only:
                            no network, but the signature ends with the certificate).
                            A LIST is tried in order: -Timestamp DigiCert,GlobalSign (the first that
                            answers is used; a file whose timestamp fails is signed again with the
                            next one).
  -TimestampCheckCache <min>  A server that passed its check is not checked again for this many
                            minutes (default 30; 0 = always): many builds in a row save one network
                            round trip each.
  -TimestampUrl <url>       Any RFC 3161 server address (your own TSA too). It is tried first, then -Timestamp.
  -TimestampFallback        The server fails its check: try DigiCert, GlobalSign, Sectigo, SSL.com,
                            Certum, Entrust, Microsoft in that order (good for pipelines).
  -NoRevocationCheck        Faster: no CRL / OCSP download while signing (no check after signing that
                            fetches revocation lists; NuGet: offline revocation mode). Check the
                            files afterwards with Verify-CodeSign.ps1.
  -Digest sha256|sha384|sha512     File and timestamp digest. Default sha256.

