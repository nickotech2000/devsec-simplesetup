function Remove-ScriptSignature {
    # -RemoveOldSignature: cut the Authenticode block out of a PowerShell file (ps1 psm1 psd1: '# SIG # ...',
    # ps1xml / cdxml: '<!-- SIG # ... -->'); the encoding of the file is kept. $true = there was one.
    param([string]$Path)
    $b = [System.IO.File]::ReadAllBytes($Path)
    $enc = if ($b.Length -ge 3 -and $b[0] -eq 0xEF -and $b[1] -eq 0xBB -and $b[2] -eq 0xBF) { [System.Text.UTF8Encoding]::new($true) }
    elseif ($b.Length -ge 2 -and $b[0] -eq 0xFF -and $b[1] -eq 0xFE) { [System.Text.UnicodeEncoding]::new($false, $true) }
    elseif ($b.Length -ge 2 -and $b[0] -eq 0xFE -and $b[1] -eq 0xFF) { [System.Text.UnicodeEncoding]::new($true, $true) }
    else { [System.Text.UTF8Encoding]::new($false) }
    $pre = $enc.GetPreamble().Length
    $t = $enc.GetString($b, $pre, $b.Length - $pre)
    $n = [regex]::Replace($t, '(?s)(\r?\n)?[^\r\n]*SIG # Begin signature block.*?SIG # End signature block[^\r\n]*(\r?\n)?', '')
    if ($n -eq $t) { return $false }
    [System.IO.File]::WriteAllText($Path, $n, $enc)
    return $true
}
# -TimestampCheckCache: a server that passed its check recently is not checked again (one network round trip less per run)
function Get-TsaCacheFile { $d = Join-Path ([System.IO.Path]::GetTempPath()) 'Sign-Code'; [void](New-Item -ItemType Directory -Path $d -Force); return (Join-Path $d 'timestamp-check.txt') }
function Test-TsaCached {
    param([string]$Url)
    if ($TimestampCheckCache -le 0) { return $false }
    try {
        foreach ($l in [System.IO.File]::ReadAllLines((Get-TsaCacheFile))) {
            $c = $l.Split("`t"); if ($c.Count -eq 2 -and $c[0] -eq $Url -and ([DateTime]::UtcNow - [DateTime]::Parse($c[1], [cultureinfo]::InvariantCulture).ToUniversalTime()).TotalMinutes -lt $TimestampCheckCache) { return $true }
        }
    } catch { }
    return $false
}
function Save-TsaCached {
    param([string]$Url, [switch]$Forget)
    if ($TimestampCheckCache -le 0) { return }
    try {
        $f = Get-TsaCacheFile
        $keep = @(if (Test-Path -LiteralPath $f) { [System.IO.File]::ReadAllLines($f) | Where-Object { $_ -and -not $_.StartsWith("$Url`t") } })
        [System.IO.File]::WriteAllLines($f, [string[]](@($keep) + @(if (-not $Forget) { "$Url`t$([DateTime]::UtcNow.ToString('o'))" })))
    } catch { Write-Detail "timestamp check cache not written: $($_.Exception.Message)" }
}
function Write-SessionReport {
    # -ReportFile: ONE report per build session; every run (also in parallel builds) adds its files under a named mutex
    param([string]$Path, [System.Collections.Specialized.OrderedDictionary]$Run)
    $full = [System.IO.Path]::GetFullPath($Path)
    [void](New-Item -ItemType Directory -Path (Split-Path -Parent $full) -Force)
    $key = [Convert]::ToHexString([System.Security.Cryptography.SHA256]::HashData([System.Text.Encoding]::UTF8.GetBytes($full.ToLowerInvariant()))).Substring(0, 32)
    $m = [System.Threading.Mutex]::new($false, "Local\SignCodeReport-$key")
    try { [void]$m.WaitOne() } catch [System.Threading.AbandonedMutexException] { }
    try {
        $doc = $null
        if (Test-Path -LiteralPath $full) { try { $doc = Get-Content -LiteralPath $full -Raw | ConvertFrom-Json -AsHashtable } catch { $doc = $null } }
        if (-not $doc -or -not $doc.ContainsKey('runs')) { $doc = [ordered]@{ tool = 'Sign-Code.ps1'; version = $script:ToolVersion; session = (Get-Date).ToString('o'); signed = 0; skipped = 0; failed = 0; runs = @() } }
        $doc['runs'] = @($doc['runs']) + @($Run)
        $doc['signed'] = [int]$doc['signed'] + [int]$Run.signed; $doc['skipped'] = [int]$doc['skipped'] + [int]$Run.skipped; $doc['failed'] = [int]$doc['failed'] + [int]$Run.failed
        $doc['updated'] = (Get-Date).ToString('o')
        [System.IO.File]::WriteAllText($full, ($doc | ConvertTo-Json -Depth 8), [System.Text.UTF8Encoding]::new($false))
    }
    finally { try { $m.ReleaseMutex() } catch { }; $m.Dispose() }
    return $full
}

function Get-CatalogPlan {
    # -Catalog: the paths the catalog covers and the .cat file. Auto = <first folder>\<folder name>.cat
    $split = { param($v) foreach ($x in @($v | Where-Object { $_ })) { if ((Test-Path -LiteralPath $x) -or $x -notmatch '[,;]') { $x } else { $x -split '[,;]' | ForEach-Object { $_.Trim() } | Where-Object { $_ } } } }
    if ($OutFolder -and -not $CatalogFolder) { [void](New-Item -ItemType Directory -Path $OutFolder -Force) }
    $paths = @(if ($CatalogFolder) { & $split $CatalogFolder } elseif ($OutFolder) { $OutFolder } else { @(& $split $Folder) + @(& $split $File) })
    $paths = @($paths | Where-Object { $_ } | ForEach-Object { if (-not (Test-Path -LiteralPath $_)) { Stop-Sign 1 "Catalog path not found: $_" }; (Resolve-Path -LiteralPath $_).Path.TrimEnd('\', '/') })
    if ($paths.Count -eq 0) { Stop-Sign 1 '-Catalog needs -CatalogFolder, -Folder or -File: what should the catalog cover?' }
    $cat = $Catalog
    if ($cat -eq 'Auto') {
        $d = @($paths | Where-Object { Test-Path -LiteralPath $_ -PathType Container } | Select-Object -First 1)
        if (-not $d) { $d = @(Split-Path -Parent $paths[0]) }
        $cat = Join-Path $d[0] ((Split-Path -Leaf $d[0]) + '.cat')
    }
    if ([System.IO.Path]::GetExtension($cat) -ne '.cat') { $cat += '.cat' }
    return [pscustomobject]@{ Paths = $paths; Cat = [System.IO.Path]::GetFullPath($cat) }
}
function Remove-OldCatalog {
    # the old catalog (and its -signed hash files) goes first: it must not be signed again, nor be listed in the new one
    param([string]$Cat)
    foreach ($f in $Cat, "$Cat-signed.sha256", "$Cat-signed.sha512") { if (Test-Path -LiteralPath $f) { Remove-Item -LiteralPath $f -Force; Write-Detail "old catalog file removed: $f" } }
}
function New-SigningCatalog {
    # a Windows catalog, version 2 (SHA-256), made in the temp folder and then moved to its place
    param($Plan)
    $tmp = Join-Path ([System.IO.Path]::GetTempPath()) ("signcode-cat-" + [Guid]::NewGuid().ToString('N') + '.cat'); $script:Temp.Add($tmp)
    Write-Detail "New-FileCatalog -CatalogVersion 2.0 -Path $($Plan.Paths -join ', ') -CatalogFilePath $tmp"
    [void](New-FileCatalog -CatalogVersion 2.0 -Path $Plan.Paths -CatalogFilePath $tmp -ErrorAction Stop)
    [void](New-Item -ItemType Directory -Path (Split-Path -Parent $Plan.Cat) -Force)
    Move-Item -LiteralPath $tmp -Destination $Plan.Cat -Force
    Write-Say 'OK' "Catalog made: $($Plan.Cat)  (covers $($Plan.Paths -join ', '))"
    return $Plan.Cat
}
function Resolve-TimestampList {
    # -Timestamp DigiCert,GlobalSign / -TimestampUrl / -TimestampFallback: the servers to try, in order
    if ($TimestampUrl) { $names = @($TimestampUrl) + @($Timestamp -split '[,;]' | ForEach-Object { $_.Trim() } | Where-Object { $_ -and $_ -ne 'None' }) }
    else { $names = @($Timestamp -split '[,;]' | ForEach-Object { $_.Trim() } | Where-Object { $_ }) }
    if (-not $TimestampUrl -and ($names.Count -eq 0 -or ($names | Where-Object { $_ -eq 'None' }))) { return @() }
    $urls = [System.Collections.Generic.List[string]]::new()
    foreach ($n in $names) {
        $u = if ($n -match '^https?://') { $n } elseif ($script:TsaTable.Contains($n.ToLowerInvariant())) { $script:TsaTable[$n.ToLowerInvariant()] } else { Stop-Sign 1 "Unknown timestamp name '$n'. Use: $($script:TsaTable.Keys -join ', ') or -TimestampUrl <url>." }
        if (-not $urls.Contains($u)) { $urls.Add($u) }
    }
    if ($TimestampFallback) { foreach ($k in $script:TsaFallback) { $u = $script:TsaTable[$k]; if (-not $urls.Contains($u)) { $urls.Add($u) } } }
    return $urls.ToArray()
}

# ---------------------------------------------------------------- the certificates of GenerateCodeSigningCertificate (-UseGenerated)
$script:PlatformTokens = [ordered]@{ windows = 'Windows'; java = 'Java'; android = 'Android'; apple = 'Apple'; 'apple-installer' = 'AppleInstaller'; multi = 'Windows' }
function Get-GeneratedIndex {
    # codesign-index.json (GenerateCodeSigningCertificate.ps1) or codesign-index.tsv (.sh): newest first, expired ones left out
    param([string]$Root)
    $rows = [System.Collections.Generic.List[object]]::new()
    $json = Join-Path $Root 'codesign-index.json'; $tsv = Join-Path $Root 'codesign-index.tsv'
    if (Test-Path -LiteralPath $json) {
        $n = 0
        foreach ($e in @((Get-Content -LiteralPath $json -Raw | ConvertFrom-Json).certificates)) {
            $n++
            if (-not $e.pfx) { continue }
            $rows.Add([pscustomobject]@{ Order = $n; Platforms = @($e.platforms | ForEach-Object { "$_" }); Level = $e.level; Pfx = (Join-Path $Root $e.pfx); Chain = $(if ($e.chain) { Join-Path $Root $e.chain }); NotAfter = "$($e.notAfter)"; Sha1 = $e.sha1; Name = $e.name })
        }
    }
    elseif (Test-Path -LiteralPath $tsv) {
        $n = 0
        foreach ($l in [System.IO.File]::ReadAllLines($tsv)) {
            if ($l -match '^\s*(#|$)') { continue }
            $c = $l.Split("`t"); if ($c.Count -lt 7) { continue }; $n++
            $pl = if ($script:PlatformTokens.Contains($c[0])) { $script:PlatformTokens[$c[0]] } else { $c[0] }
            $rows.Add([pscustomobject]@{ Order = $n; Platforms = @($pl); Level = $c[1]; Pfx = (Join-Path $Root $c[4]); Chain = (Join-Path $Root ($c[5] -replace '\.crt$', '-chain.crt')); NotAfter = $c[2]; Sha1 = $c[3]; Name = [System.IO.Path]::GetFileNameWithoutExtension($c[5]) })
        }
    }
    else { Stop-Sign 1 "No generated code signing certificate in $Root (codesign-index.json / .tsv). Make one: .\GenerateCodeSigningCertificate.ps1 -Platform Windows   (or give -GeneratedRoot)." }
    $today = [DateTime]::UtcNow.ToString('yyyy-MM-dd')
    return @($rows | Where-Object { -not $_.NotAfter -or $_.NotAfter.Substring(0, [Math]::Min(10, $_.NotAfter.Length)) -ge $today } | Where-Object { Test-Path -LiteralPath $_.Pfx } | Sort-Object Order -Descending)
}
function Invoke-GeneratedSigning {
    # one run of this script per platform, each with the newest generated certificate of that platform
    param([string[]]$Files, $CatPlan)
    $root = if ($GeneratedRoot) { $GeneratedRoot } elseif ($env:SIGN_GENERATED_ROOT) { $env:SIGN_GENERATED_ROOT } else { Join-Path (Join-Path $script:ScriptRoot 'leafcerts') 'codesign' }
    $index = Get-GeneratedIndex -Root $root
    Write-Say 'INFO' "Generated certificates: $root ($($index.Count) valid)"
    $groups = [ordered]@{}
    foreach ($f in $Files) { $pl = if ($GeneratedPlatform -ne 'Auto') { $GeneratedPlatform } else { Get-KindPlatform (Get-FileKind $f) $f }; if (-not $groups.Contains($pl)) { $groups[$pl] = [System.Collections.Generic.List[string]]::new() }; $groups[$pl].Add($f) }
    if ($CheckOnly -and $groups.Count -eq 0) { $groups[$(if ($GeneratedPlatform -ne 'Auto') { $GeneratedPlatform } else { 'Windows' })] = [System.Collections.Generic.List[string]]::new() }
    if (-not [Environment]::GetEnvironmentVariable($PfxPasswordEnv)) {
        [Environment]::SetEnvironmentVariable($PfxPasswordEnv, 'Abc12345!')
        Write-Say 'WARN' "$PfxPasswordEnv is not set: the default password of GenerateCodeSigningCertificate (Abc12345!) is used."
    }
    $pass = @{}
    foreach ($k in $script:BoundArgs.Keys) { if ($k -notin 'File', 'Folder', 'Include', 'Exclude', 'NoRecurse', 'UseGenerated', 'GeneratedRoot', 'GeneratedPlatform', 'Catalog', 'CatalogFolder', 'CleanReports') { $pass[$k] = $script:BoundArgs[$k] } }
    $worst = 0
    foreach ($pl in $groups.Keys) {
        $e = $index | Where-Object { $_.Platforms -contains $pl } | Select-Object -First 1
        if (-not $e -and $pl -eq 'AppleInstaller') { $e = $index | Where-Object { $_.Platforms -contains 'Apple' } | Select-Object -First 1; if ($e) { Write-Say 'WARN' 'No Apple installer certificate: the Apple application certificate signs the .pkg files (make one: -Platform Apple -AppleType Installer).' } }
        if (-not $e) { Write-Say 'ERROR' "No valid generated $pl code signing certificate in $root. Make one: .\GenerateCodeSigningCertificate.ps1 -Platform $(if ($pl -eq 'AppleInstaller') { 'Apple -AppleType Installer' } else { $pl })"; $worst = [Math]::Max($worst, 2); continue }
        Write-Say 'INFO' "---- $pl : $($groups[$pl].Count) file(s) with $($e.Name) ($($e.Level), until $($e.NotAfter))"
        $h = $pass.Clone(); $h['Pfx'] = $e.Pfx
        if (-not $h.ContainsKey('ChainFile') -and $e.Chain -and (Test-Path -LiteralPath $e.Chain)) { $h['ChainFile'] = $e.Chain }
        if ($groups[$pl].Count -gt 0) { $h['File'] = @($groups[$pl]) }
        Write-Detail "& $PSCommandPath -Pfx $($e.Pfx) -File <$($groups[$pl].Count) file(s)>"
        & $PSCommandPath @h
        $worst = [Math]::Max($worst, [int]$LASTEXITCODE)
    }
    if ($CatPlan -and -not $CheckOnly -and $worst -lt 2) {
        # the catalog last (it holds the hashes of the signed files), signed with the newest Windows certificate
        $e = $index | Where-Object { $_.Platforms -contains 'Windows' } | Select-Object -First 1
        if (-not $e) { Write-Say 'ERROR' "No valid generated Windows code signing certificate in $root for the catalog."; return [Math]::Max($worst, 2) }
        $cat = New-SigningCatalog -Plan $CatPlan
        $h = $pass.Clone(); $h['Pfx'] = $e.Pfx; $h['File'] = @($cat)
        if (-not $h.ContainsKey('ChainFile') -and $e.Chain -and (Test-Path -LiteralPath $e.Chain)) { $h['ChainFile'] = $e.Chain }
        Write-Say 'INFO' "---- catalog with $($e.Name)"
        & $PSCommandPath @h
        $worst = [Math]::Max($worst, [int]$LASTEXITCODE)
    }
    return $worst
}

