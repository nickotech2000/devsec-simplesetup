    # ---- the files first: no point checking a certificate when there is nothing to sign
    $sel = Resolve-SigningFiles
    foreach ($s in $sel.Skipped) { Write-Say $(if ($catPlan) { 'INFO' } else { 'WARN' }) "$(if ($catPlan) { 'No signature of its own (the catalog covers it)' } else { 'Not a supported file type, skipped' }): $s" }
    if (-not $CheckOnly -and $sel.Files.Count -eq 0 -and -not $catPlan) { Stop-Sign 7 'No file to sign. Give -File and / or -Folder (supported types: see -Help).' }
    Write-Say 'INFO' "$($sel.Files.Count) file(s) to sign$(if ($catPlan) { ', then the catalog' })."
    if ($UseGenerated) {
        if (@($Pfx, $PfxBase64Env, $Thumbprint, $CertPem, $CertFolder, $Subject) | Where-Object { $_ }) { Stop-Sign 1 '-UseGenerated chooses the certificate itself: leave out -Pfx, -Thumbprint, -Subject, -CertPem, -CertFolder and -PfxBase64Env.' }
        $exit = Invoke-GeneratedSigning -Files $sel.Files -CatPlan $catPlan
        exit $exit
    }

    # ---- the certificate (public part), and a way to sign with it
    $cert = $null; $sigThumb = $null; $pfxPath = $null; $pfxPass = $null; $importedThumb = $null; $script:StoreCert = $false
    $nSrc = @($Pfx, $PfxBase64Env, $Thumbprint, $Subject, $CertPem, $CertFolder) | Where-Object { $_ }
    if ($Provider -eq 'Local') {
        if (@($nSrc).Count -ne 1) { Stop-Sign 1 'Give exactly ONE certificate source: -UseGenerated, -Pfx, -PfxBase64Env, -CertFolder, -Thumbprint, -Subject or -CertPem/-KeyPem (or use -Provider).' }
    }
    elseif (-not $CertFile) { Stop-Sign 1 "-Provider $Provider needs -CertFile <the public certificate> so that the certificate checks can run." }
    if ($CertFolder) {
        # a folder of GenerateCodeSigningCertificate / GenerateLeafCertificate: its .pfx (the newest), and its -chain.crt for the chain check
        if (-not (Test-Path -LiteralPath $CertFolder -PathType Container)) { Stop-Sign 1 "Folder not found: $CertFolder" }
        $pf = Get-ChildItem -LiteralPath $CertFolder -Filter *.pfx -File | Sort-Object LastWriteTime -Descending | Select-Object -First 1
        if (-not $pf) { $pf = Get-ChildItem -LiteralPath $CertFolder -Include *.pfx, *.p12 -File -Recurse | Sort-Object LastWriteTime -Descending | Select-Object -First 1 }
        if (-not $pf) { Stop-Sign 1 "No .pfx / .p12 in $CertFolder." }
        $Pfx = $pf.FullName; Write-Say 'INFO' "Certificate file: $Pfx"
        $ch0 = Join-Path $pf.DirectoryName ($pf.BaseName + '-chain.crt')
        if (-not $ChainFile -and (Test-Path -LiteralPath $ch0)) { $ChainFile = $ch0; Write-Detail "chain: $ch0" }
        if (-not [Environment]::GetEnvironmentVariable($PfxPasswordEnv) -and ($script:Ci -or [Console]::IsInputRedirected)) { [Environment]::SetEnvironmentVariable($PfxPasswordEnv, 'Abc12345!'); Write-Say 'WARN' "$PfxPasswordEnv is not set: the lab default password Abc12345! is tried." }
    }

    $X = [System.Security.Cryptography.X509Certificates.X509Certificate2]
    $flags = [System.Security.Cryptography.X509Certificates.X509KeyStorageFlags]
    if ($Provider -ne 'Local') { $cert = $X::new($CertFile) }
    elseif ($Thumbprint -or $Subject) {
        # the Windows certificate store: CurrentUser or LocalMachine, My (default) or any store name
        $loc = [System.Security.Cryptography.X509Certificates.StoreLocation]::$StoreLocation
        $st = [System.Security.Cryptography.X509Certificates.X509Store]::new($StoreName, $loc); $st.Open('ReadOnly')
        if ($Thumbprint) { $cert = $st.Certificates | Where-Object { $_.Thumbprint -eq ($Thumbprint -replace '\s', '').ToUpperInvariant() } | Select-Object -First 1 }
        else {
            # -Subject: the newest valid code signing certificate with a private key whose subject contains the text
            $now0 = [DateTime]::Now
            $cert = $st.Certificates | Where-Object { $_.Subject -like "*$Subject*" -and $_.HasPrivateKey -and $_.NotAfter -gt $now0 -and $_.NotBefore -lt $now0 -and
                (@($_.Extensions | Where-Object { $_ -is [System.Security.Cryptography.X509Certificates.X509EnhancedKeyUsageExtension] } | ForEach-Object { $_.EnhancedKeyUsages.Value }) -contains '1.3.6.1.5.5.7.3.3') } |
                Sort-Object NotBefore -Descending | Select-Object -First 1
        }
        $st.Close()
        if (-not $cert) { Stop-Sign 1 "No certificate with $(if ($Thumbprint) { "thumbprint $Thumbprint" } else { "a valid code signing certificate with a key and subject like '$Subject'" }) in the $StoreLocation\$StoreName store." }
        Write-Say 'INFO' "Store certificate: $StoreLocation\$StoreName  $($cert.Subject)  ($($cert.Thumbprint))"
        $script:StoreCert = $true
        if (-not $cert.HasPrivateKey) { Write-Say 'WARN' 'The store certificate shows no private key (a hardware token may only show it when plugged in).' }
        $sigThumb = $cert.Thumbprint
    }
    else {
        if ($Pfx) { if (-not (Test-Path -LiteralPath $Pfx -PathType Leaf)) { Stop-Sign 1 "PFX file not found: $Pfx" }; $pfxPath = (Resolve-Path -LiteralPath $Pfx).Path }
        elseif ($PfxBase64Env) {
            $b64 = [Environment]::GetEnvironmentVariable($PfxBase64Env); if (-not $b64) { Stop-Sign 1 "The environment variable $PfxBase64Env is empty or not set. In a pipeline, map the secret to it." }
            $pfxPath = New-TempFile '.pfx'; [System.IO.File]::WriteAllBytes($pfxPath, [Convert]::FromBase64String(($b64 -replace '\s', '')))
        }
        if ($pfxPath) {
            $pfxPass = Get-Secret $PfxPasswordEnv 'PFX password'
            try { $cert = $X::new($pfxPath, $pfxPass, $flags::EphemeralKeySet -bor $flags::Exportable) } catch { Stop-Sign 1 "The PFX could not be opened (wrong password in ${PfxPasswordEnv}?): $($_.Exception.Message)" }
        }
        else {
            if (-not $KeyPem) { Stop-Sign 1 '-CertPem needs -KeyPem as well.' }
            $kp = Get-Secret $KeyPasswordEnv 'Private key password (empty = none)'
            $pem = [System.IO.File]::ReadAllText($CertPem)
            $cert = if ($kp) { $X::CreateFromEncryptedPemFile($CertPem, $kp, $KeyPem) } else { $X::CreateFromPemFile($CertPem, $KeyPem) }
            # a PEM pair has no PFX: make a temporary one for the signing tools
            $pfxPath = New-TempFile '.pfx'; $pfxPass = [Convert]::ToHexString([System.Security.Cryptography.RandomNumberGenerator]::GetBytes(16))
            [System.IO.File]::WriteAllBytes($pfxPath, $cert.Export('Pfx', $pfxPass))
            $cert = $X::new($pfxPath, $pfxPass, $flags::EphemeralKeySet -bor $flags::Exportable)
        }
        Add-Secret $pfxPass
    }

    # ---- classify and CHECK
    $src = $CertSource
    $chainFile = if ($ChainFile) { $ChainFile } else { $null }
    if ($src -eq 'Auto') {
        $probe = Test-CodeSigningCertificate -Cert $cert -Source 'PrivatePki' -Chain $null
        $src = if ($probe.ChainTrusted -and $cert.Subject -ne $cert.Issuer) { 'PublicCa' } else { 'PrivatePki' }
    }
    Write-Say 'INFO' "Certificate source: $src"
    $res = Test-CodeSigningCertificate -Cert $cert -Source $src -Chain $chainFile
    $polText = Get-CertPolicyText $cert
    $isEv = $polText -match '2\.23\.140\.1\.3\b'; $isCsbr = $polText -match '2\.23\.140\.1\.4\.1\b'
    if ($src -eq 'PublicCa') {
        if (-not $res.ChainTrusted) { $res.Errors += "The chain does not end at a root that Windows trusts ($($res.ChainStatus -join ', '))." }
        if (-not ($isEv -or $isCsbr)) { $res.Warnings += 'No CA/Browser Forum code-signing policy (2.23.140.1.4.1 or EV 2.23.140.1.3) found in the certificate.' }
    }
    elseif (-not $res.ChainTrusted) { $res.Warnings += "The chain is not complete / not trusted here ($($res.ChainStatus -join ', ')). Give -ChainFile <ca-bundle.pem> to check it against your private root." }
    foreach ($w in $res.Warnings) { Write-Say 'WARN' $w }
    if ($res.Errors.Count -gt 0) {
        foreach ($e in $res.Errors) { Write-Say 'ERROR' $e }
        Show-CertificateContents $cert $res.KeyText
        Stop-Sign 2 'The certificate does NOT comply with the code-signing rules. Nothing was signed.'
    }
    Write-Say 'OK' "Certificate complies: $($res.KeyText), $(if ($isEv) { 'EV code signing' } elseif ($isCsbr) { 'OV code signing (CA/B Forum)' } else { 'code signing' }), valid until $($cert.NotAfter.ToString('yyyy-MM-dd')), chain length $($res.ChainLength)."

    # ---- the timestamp server
    # the timestamp arguments of every signing tool, taken out for -Timestamp None
    function Remove-TsArgs([object[]]$A) {
        $flags = '/tr', '/td', '-tr', '-td', '-tsa', '-tsadigestalg', '--timestamper', '--timestamp-hash-algorithm'
        $o = [System.Collections.Generic.List[object]]::new()
        for ($k = 0; $k -lt $A.Count; $k++) { if ($A[$k] -is [string] -and $A[$k] -cin $flags) { $k++ } else { $o.Add($A[$k]) } }
        return , $o.ToArray()
    }
    # -Timestamp None (Debug builds, tests): no timestamp server at all, so no network and no wait
    $tsCands = @(Resolve-TimestampList); $tsIdx = 0
    if ($tsCands.Count -eq 0) {
        $tsUrl = $null
        Write-Say 'INFO' 'No timestamp (-Timestamp None): the signature stops being valid when the certificate expires. For Debug builds and tests only.'
    }
    else {
        # the servers in order until one passes its check (a check that passed less than -TimestampCheckCache
        # minutes ago is not repeated); the ones after it stay as spares for a file whose timestamp fails
        $okTs = $null
        for ($k = 0; $k -lt $tsCands.Count; $k++) {
            $u = $tsCands[$k]
            if (Test-TsaCached $u) { Write-Say 'OK' "Timestamp server: $u (checked less than $TimestampCheckCache min ago)"; $okTs = $k; break }
            try { Test-TimestampServer -Url $u; Save-TsaCached $u; $okTs = $k; break }
            catch [SignExit] { if ($tsCands.Count -eq 1) { throw }; Write-Say 'WARN' "$($_.Exception.Message)  Trying the next timestamp server." }
        }
        if ($null -eq $okTs) { Stop-Sign 3 "No timestamp server answered (tried: $($tsCands -join ', '))." }
        $tsIdx = $okTs; $tsUrl = $tsCands[$tsIdx]
    }
    Write-Detail "timestamp server: $(if ($tsUrl) { $tsUrl } else { 'none' })"
    if ($CheckOnly) { Show-CertificateContents $cert $res.KeyText; Write-Say 'OK' 'Checks finished (-CheckOnly): nothing was signed.'; exit 0 }

    # ---- the tools needed for THIS job
    $jobKinds = @(@($sel.Files | ForEach-Object { Get-FileKind $_ }) + @(if ($catPlan) { 'authenticode' }) | Sort-Object -Unique)
    $tool = @{}
    if ($Provider -eq 'Local') {
        if ($jobKinds -contains 'authenticode' -or $jobKinds -contains 'office') { $tool.signtool = Get-SigningTool 'signtool' }
        if ($jobKinds -contains 'java') { $tool.jarsigner = Get-SigningTool 'jarsigner' }
        if ($jobKinds -contains 'apk') { $tool.apksigner = Get-SigningTool 'apksigner'; if (-not (Find-Tool 'jarsigner')) { $tool.jarsigner = Get-SigningTool 'jarsigner' } }
        if ($jobKinds -contains 'nuget') { $tool.dotnet = Get-SigningTool 'dotnet' }
        if ($jobKinds -contains 'apple') { $tool.rcodesign = Get-SigningTool 'rcodesign' }
    }
    else {
        switch ($Provider) {
            'AzureKeyVault' { $tool.azuresigntool = Get-SigningTool 'azuresigntool' }
            'AzureTrustedSigning' { $tool.signtool = Get-SigningTool 'signtool' }
            'DigiCertKeyLocker' { $tool.smctl = Get-SigningTool 'smctl' }
            default { $tool.jsign = Get-SigningTool 'jsign' }
        }
        $bad = @($jobKinds | Where-Object { $_ -in 'java', 'apk', 'nuget', 'office', 'apple' })
        if ($bad.Count -gt 0) { Write-Say 'WARN' "-Provider $Provider signs Windows files and PowerShell scripts only. Skipped kinds: $($bad -join ', '). Use -Provider Local with an exported key for them." }
    }

    # ---- sign with a certificate in a temporary store (no password on any command line)
    $tmpStoreThumb = $null
    if ($Provider -eq 'Local' -and -not $sigThumb -and ($jobKinds | Where-Object { $_ -in 'authenticode', 'powershell', 'office' })) {
        $imp = $X::new($pfxPath, $pfxPass, $flags::PersistKeySet -bor $flags::Exportable)
        # many builds at once (msbuild -m, a solution of many projects): one Sign-Code at a time per certificate,
        # so one run never removes the certificate while another still signs with it
        $script:StoreMutex = [System.Threading.Mutex]::new($false, 'Local\DevSecSignCode-' + $imp.Thumbprint)
        try { [void]$script:StoreMutex.WaitOne() } catch [System.Threading.AbandonedMutexException] { }
        $st = [System.Security.Cryptography.X509Certificates.X509Store]::new('My', 'CurrentUser'); $st.Open('ReadWrite')
        # a certificate (with its key) that was already in the store stays there afterwards
        $had = @($st.Certificates | Where-Object { $_.Thumbprint -eq $imp.Thumbprint -and $_.HasPrivateKey }).Count -gt 0
        if (-not $had) { $st.Add($imp); $tmpStoreThumb = $imp.Thumbprint }
        $st.Close(); $sigThumb = $imp.Thumbprint
        if ($tmpStoreThumb) {
            $script:Cleanup.Add({ $s2 = [System.Security.Cryptography.X509Certificates.X509Store]::new('My', 'CurrentUser'); $s2.Open('ReadWrite'); $c = $s2.Certificates | Where-Object { $_.Thumbprint -eq $tmpStoreThumb }; if ($c) { $s2.RemoveRange($c) }; $s2.Close() })
        }
        $script:Cleanup.Add({ try { $script:StoreMutex.ReleaseMutex() } catch { }; $script:StoreMutex.Dispose() })
    }

    # ---- sign
    $report = [System.Collections.Generic.List[object]]::new(); $failed = 0
    $workRoot = $null
    if ($OutFolder) { $workRoot = $OutFolder; [void](New-Item -ItemType Directory -Path $workRoot -Force) }
    $common = @{}
    $i = 0
    $queue = [System.Collections.Generic.List[string]]::new(); foreach ($f in $sel.Files) { $queue.Add($f) }
    $catDone = $false
    # -Catalog alone (no file to sign): the catalog only
    if ($catPlan -and $queue.Count -eq 0) { $catDone = $true; $queue.Add((New-SigningCatalog -Plan $catPlan)) }
    for ($qi = 0; $qi -lt $queue.Count; $qi++) {
        $src0 = $queue[$qi]
        $i++
        $kind = Get-FileKind $src0
        $target = $src0
        if ($workRoot -and -not ($catPlan -and $src0 -eq $catPlan.Cat)) { $target = Join-Path $workRoot (Split-Path -Leaf $src0); Copy-Item -LiteralPath $src0 -Destination $target -Force -Recurse }
        $row = [ordered]@{ file = $target; kind = $kind; status = 'signed'; message = '' }
        if ($SkipSigned -and (Test-AlreadySigned $target $kind)) { $row.status = 'skipped'; $row.message = 'already signed'; [void]$report.Add([pscustomobject]$row); Write-Say 'INFO' "[$i/$($queue.Count)] already signed, skipped: $target"; continue }
        if ($Provider -ne 'Local' -and $kind -notin 'authenticode', 'powershell') { $row.status = 'skipped'; $row.message = "kind $kind is not signed by -Provider $Provider"; [void]$report.Add([pscustomobject]$row); continue }
        Write-Host "[$i/$($queue.Count)] $target  ($kind)"
        try {
            if ($RemoveOldSignature) {
                # sign again with the current certificate: the old signature goes first
                if ($kind -eq 'powershell') { if (Remove-ScriptSignature $target) { Write-Say 'INFO' "old signature removed: $(Split-Path -Leaf $target)"; $row.resigned = $true } }
                elseif ($kind -eq 'authenticode' -and $tool.signtool -and (Test-AlreadySigned $target $kind)) {
                    Write-Command $tool.signtool @('remove', '/s', $target)
                    $rm = (& $tool.signtool remove /s $target 2>&1) -join "`n"; Write-ToolOutput $rm
                    if ($LASTEXITCODE -eq 0) { Write-Say 'INFO' "old signature removed: $(Split-Path -Leaf $target)"; $row.resigned = $true } else { Write-Say 'WARN' "old signature not removed (signed over it): $rm" }
                }
            }
          while ($true) {
           try {
            $out = ''
            if ($Provider -eq 'Local') {
                switch ($kind) {
                    'authenticode' {
                        $a = @('sign', '/fd', $Digest, '/tr', $tsUrl, '/td', $Digest, '/sha1', $sigThumb); if (-not $tsUrl) { $a = Remove-TsArgs $a }
                        if ($script:StoreCert) { $a += @('/s', $StoreName); if ($StoreLocation -eq 'LocalMachine') { $a += '/sm' } }
                        if ($Description) { $a += @('/d', $Description) }; if ($DescriptionUrl) { $a += @('/du', $DescriptionUrl) }
                        if ($script:Verbose) { $a = @($a[0], '/v') + $a[1..($a.Count - 1)] }
                        $a += $target
                        Write-Command $tool.signtool $a
                        $out = (& $tool.signtool @a 2>&1) -join "`n"; Write-ToolOutput $out; if ($LASTEXITCODE -ne 0) { throw $out }
                        if ($NoRevocationCheck) { $row.message = 'not verified here (-NoRevocationCheck)' }
                        else {
                            Write-Command $tool.signtool @('verify', '/pa', $target)
                            $v = (& $tool.signtool verify /pa $target 2>&1) -join "`n"; Write-ToolOutput $v
                            if ($LASTEXITCODE -ne 0 -and $src -eq 'PublicCa') { throw "verify failed: $v" }
                            if ($LASTEXITCODE -ne 0) { $row.message = 'signature written; the root is not trusted on this PC (normal for a private PKI)' }
                        }
                    }
                    'office' {
                        $a = @('sign', '/fd', $Digest, '/tr', $tsUrl, '/td', $Digest, '/sha1', $sigThumb); if (-not $tsUrl) { $a = Remove-TsArgs $a }
                        if ($script:StoreCert) { $a += @('/s', $StoreName); if ($StoreLocation -eq 'LocalMachine') { $a += '/sm' } }
                        $a += $target
                        Write-Command $tool.signtool $a
                        $out = (& $tool.signtool @a 2>&1) -join "`n"; Write-ToolOutput $out; if ($LASTEXITCODE -ne 0) { throw "$out`n(VBA signing needs Microsoft Office or the Office SIP installed on this PC.)" }
                    }
                    'powershell' {
                        $c0 = Get-ChildItem "Cert:\CurrentUser\$StoreName", "Cert:\LocalMachine\$StoreName", Cert:\CurrentUser\My -ErrorAction SilentlyContinue | Where-Object { $_.Thumbprint -eq $sigThumb } | Select-Object -First 1
                        Write-Detail "Set-AuthenticodeSignature -LiteralPath $target -Certificate $sigThumb -TimestampServer $tsUrl -HashAlgorithm $($Digest.ToUpperInvariant())"
                        $tsP = @{}; if ($tsUrl) { $tsP.TimestampServer = $tsUrl }
                        $r = Set-AuthenticodeSignature -LiteralPath $target -Certificate $c0 @tsP -HashAlgorithm $Digest.ToUpperInvariant()
                        if ($r.Status -notin 'Valid', 'UnknownError') { throw "Set-AuthenticodeSignature: $($r.Status) $($r.StatusMessage)" }
                        if ($r.Status -eq 'UnknownError') { $row.message = 'signature written; the root is not trusted on this PC (normal for a private PKI)' }
                    }
                    'java' {
                        $pw = 'SIGNCODE_JS_PASS'; [Environment]::SetEnvironmentVariable($pw, $pfxPass)
                        $kt = Get-Command keytool -ErrorAction SilentlyContinue
                        $aliasName = $null
                        if ($kt) { $l = (& $kt.Source '-J-Duser.language=en' -list -v -keystore $pfxPath -storetype PKCS12 -storepass:env $pw 2>&1) -join "`n"; $m = [regex]::Match($l, '(?m)^Alias name:\s*(.+?)\s*$'); if ($m.Success) { $aliasName = $m.Groups[1].Value }; Write-Detail "key alias: $aliasName" }
                        if (-not $aliasName) { throw 'Could not read the key alias from the PFX (keytool missing?).' }
                        $dj = $Digest.ToUpperInvariant().Replace('SHA', 'SHA-')
                        $a = @('-keystore', $pfxPath, '-storetype', 'PKCS12', '-storepass:env', $pw, '-digestalg', $dj, '-tsa', $tsUrl, '-tsadigestalg', $dj); if (-not $tsUrl) { $a = Remove-TsArgs $a }
                        if ($script:Verbose) { $a += '-verbose' }
                        $a += @($target, $aliasName)
                        Write-Command $tool.jarsigner $a
                        $out = (& $tool.jarsigner @a 2>&1) -join "`n"; Write-ToolOutput $out
                        if ($LASTEXITCODE -ne 0) { throw $out }
                        Write-Command $tool.jarsigner @('-verify', $target)
                        $v = (& $tool.jarsigner -verify $target 2>&1) -join "`n"; Write-ToolOutput $v; if ($LASTEXITCODE -ne 0) { throw "verify failed: $v" }
                    }
                    'apk' {
                        $pw = 'SIGNCODE_APK_PASS'; [Environment]::SetEnvironmentVariable($pw, $pfxPass)
                        $a = @('sign', '--ks', $pfxPath, '--ks-type', 'PKCS12', '--ks-pass', "env:$pw")
                        if ($script:Verbose) { $a += '--verbose' }
                        $a += $target
                        Write-Command $tool.apksigner $a
                        $out = (& $tool.apksigner @a 2>&1) -join "`n"; Write-ToolOutput $out; if ($LASTEXITCODE -ne 0) { throw $out }
                        Write-Command $tool.apksigner @('verify', '--print-certs', $target)
                        $v = (& $tool.apksigner verify --print-certs $target 2>&1) -join "`n"; Write-ToolOutput $v; if ($LASTEXITCODE -ne 0) { throw "verify failed: $v" }
                        $row.message = 'APK signed without a timestamp (the Android format has none)'
                    }
                    'nuget' {
                        $a = @('nuget', 'sign', $target, '--certificate-path', $pfxPath, '--timestamper', $tsUrl, '--timestamp-hash-algorithm', $Digest, '--hash-algorithm', $Digest, '--overwrite'); if (-not $tsUrl) { $a = Remove-TsArgs $a }
                        if ($pfxPass) { $a += @('--certificate-password', $pfxPass) }
                        if ($script:Verbose) { $a += @('--verbosity', 'detailed') }
                        Write-Command $tool.dotnet $a
                        $out = (& $tool.dotnet @a 2>&1) -join "`n"; Write-ToolOutput $out; if ($LASTEXITCODE -ne 0) { throw $out }
                    }
                    'apple' {
                        # rcodesign: Mach-O, bundles (.app ...), .dmg and installer packages (.pkg). The password goes through a file (0600).
                        $pwf = New-TempFile '.txt'; [System.IO.File]::WriteAllText($pwf, $pfxPass)
                        $appleTs = if (-not $tsUrl) { 'none' } elseif ($TimestampUrl -or $PSBoundParameters.ContainsKey('Timestamp')) { $tsUrl } else { $script:TsaTable['apple'] }
                        $a = @('sign', '--p12-file', $pfxPath, '--p12-password-file', $pwf, '--timestamp-url', $appleTs)
                        if ($target -notmatch '(?i)\.(pkg|dmg)$') { $a += @('--code-signature-flags', 'runtime') }
                        if ($script:Verbose) { $a += '-v' }
                        $a += $target
                        Write-Command $tool.rcodesign $a
                        $out = (& $tool.rcodesign @a 2>&1) -join "`n"; Write-ToolOutput $out; if ($LASTEXITCODE -ne 0) { throw $out }
                        if ($target -notmatch '(?i)\.pkg$') {
                            Write-Command $tool.rcodesign @('verify', $target)
                            $v = (& $tool.rcodesign verify $target 2>&1) -join "`n"; Write-ToolOutput $v; if ($LASTEXITCODE -ne 0) { throw "verify failed: $v" }
                        }
                        $row.message = 'signed for macOS; Gatekeeper also needs Apple notarization (public Apple Developer ID certificate)'
                    }
                }
            }
            else {
                $pa = @($ProviderArg -split '\|')
                switch ($Provider) {
                    'AzureKeyVault' {
                        # secrets: AZURE_CLIENT_ID / AZURE_CLIENT_SECRET / AZURE_TENANT_ID or a managed identity (-kvm)
                        $a = @('sign', '-kvu', $pa[0], '-kvc', $pa[1], '-fd', $Digest, '-tr', $tsUrl, '-td', $Digest); if (-not $tsUrl) { $a = Remove-TsArgs $a }
                        Add-Secret $env:AZURE_CLIENT_SECRET
                        if ($env:AZURE_CLIENT_ID -and $env:AZURE_CLIENT_SECRET -and $env:AZURE_TENANT_ID) { $a += @('-kvi', $env:AZURE_CLIENT_ID, '-kvs', $env:AZURE_CLIENT_SECRET, '-kvt', $env:AZURE_TENANT_ID) } else { $a += '-kvm' }
                        $a += $target
                        Write-Command $tool.azuresigntool $a
                        $out = (& $tool.azuresigntool @a 2>&1) -join "`n"; Write-ToolOutput $out
                    }
                    'AzureTrustedSigning' {
                        $dlib = $env:AZURE_CODESIGNING_DLIB; if (-not $dlib -or -not (Test-Path $dlib)) { throw 'Set AZURE_CODESIGNING_DLIB to the full path of Azure.CodeSigning.Dlib.dll (NuGet package Microsoft.Trusted.Signing.Client).' }
                        $meta = New-TempFile '.json'; [System.IO.File]::WriteAllText($meta, (@{ Endpoint = $pa[0]; CodeSigningAccountName = $pa[1]; CertificateProfileName = $pa[2] } | ConvertTo-Json))
                        $out = (& $tool.signtool sign /v /debug /fd $Digest /tr 'http://timestamp.acs.microsoft.com' /td $Digest /dlib $dlib /dmdf $meta $target 2>&1) -join "`n"
                    }
                    'DigiCertKeyLocker' { $out = (& $tool.smctl sign --keypair-alias $pa[0] --input $target 2>&1) -join "`n" }
                    { $_ -in 'AwsKms', 'GcpKms', 'Pkcs11' } {
                        # the secret goes through an environment variable, never on the command line
                        switch ($Provider) {
                            'AwsKms' { $env:JSIGN_STOREPASS = "$($env:AWS_ACCESS_KEY_ID)|$($env:AWS_SECRET_ACCESS_KEY)$(if ($env:AWS_SESSION_TOKEN) { '|' + $env:AWS_SESSION_TOKEN })"; $stype = 'AWS' }
                            'GcpKms' { $env:JSIGN_STOREPASS = (& gcloud auth print-access-token 2>$null); $stype = 'GOOGLECLOUD' }
                            'Pkcs11' { $env:JSIGN_STOREPASS = $env:SIGN_PKCS11_PIN; $stype = 'PKCS11' }
                        }
                        $out = (& $tool.jsign --storetype $stype --keystore $pa[0] --alias $pa[1] --storepass 'env:JSIGN_STOREPASS' --certfile $CertFile --alg $Digest @(if ($tsUrl) { '--tsaurl', $tsUrl, '--tsmode', 'RFC3161' }) $target 2>&1) -join "`n"
                    }
                }
                if ($LASTEXITCODE -ne 0) { throw $out }
            }
            break
           }
           catch {
                # the timestamp failed: the same file again with the next server of the list (it stays for the next files)
                $msg = "$($_.Exception.Message)"
                if ($tsUrl -and $kind -ne 'apple' -and $msg -match '(?i)time ?stamp|\btsa\b|timestamper|connect(ion)? ?(refused|failed|exception)|could not be reached|unreachable|timed? ?out|name (or service )?not known|no such host' -and $tsIdx + 1 -lt $tsCands.Count) {
                    Save-TsaCached $tsUrl -Forget; $tsIdx++; Write-Say 'WARN' "The timestamp of $tsUrl failed; signing again with $($tsCands[$tsIdx])."
                    $tsUrl = $tsCands[$tsIdx]; continue
                }
                throw
           }
          }
            $h = Write-SignedHashFiles -Path $target
            $row.hashFiles = @($h | ForEach-Object { Split-Path -Leaf $_ })
            Write-Say 'OK' "signed: $(Split-Path -Leaf $target)   -> $(($row.hashFiles) -join ', ')"
        }
        catch {
            $failed++; $row.status = 'failed'; $row.message = ($_.Exception.Message -replace '\s+', ' ').Trim()
            if ($pfxPass) { $row.message = $row.message.Replace($pfxPass, '***') }
            Write-Say 'ERROR' "FAILED: $target : $($row.message)"
        }
        [void]$report.Add([pscustomobject]$row)
        if ($qi -eq $queue.Count - 1 -and $catPlan -and -not $catDone) {
            # every file is signed: now the catalog of them, signed by this same loop (same certificate, timestamp)
            $catDone = $true
            try { $queue.Add((New-SigningCatalog -Plan $catPlan)) }
            catch { $failed++; [void]$report.Add([pscustomobject][ordered]@{ file = $catPlan.Cat; kind = 'catalog'; status = 'failed'; message = ($_.Exception.Message -replace '\s+', ' ').Trim() }); Write-Say 'ERROR' "FAILED: catalog $($catPlan.Cat) : $($_.Exception.Message)" }
        }
    }

    # ---- what happened
    $okN = @($report | Where-Object status -eq 'signed').Count; $skN = @($report | Where-Object status -eq 'skipped').Count
    Show-CertificateContents $cert $res.KeyText
    $run = [ordered]@{ version = $script:ToolVersion; time = (Get-Date).ToString('o'); certificate = $cert.Subject; thumbprint = $cert.Thumbprint; timestamp = $tsUrl; digest = $Digest; provider = $Provider
        revocationCheck = (-not $NoRevocationCheck); catalog = $(if ($catPlan) { $catPlan.Cat }); signed = $okN; skipped = $skN; failed = $failed; files = $report }
    if ($ReportFile) {
        # one report for the whole build session (MSBuild deletes it when the build starts)
        $repFile = Write-SessionReport -Path $ReportFile -Run $run
    }
    else {
        $repDir = if ($workRoot) { $workRoot } else { Get-SignWorkFolder }
        [void](New-Item -ItemType Directory -Path $repDir -Force)
        $repFile = Join-Path $repDir ("sign-report_" + (Get-Date).ToString('yyyyMMdd-HHmmss') + '.json')
        ($run | ConvertTo-Json -Depth 5) | Set-Content -LiteralPath $repFile -Encoding utf8
    }
    Write-Say 'INFO' "Report: $repFile"
    Write-Say $(if ($failed) { 'ERROR' } else { 'OK' }) "Signed $okN, skipped $skN, failed $failed (of $($queue.Count))."
    if ($script:Ci -and $env:GITHUB_STEP_SUMMARY) { Add-Content -LiteralPath $env:GITHUB_STEP_SUMMARY -Value "### Sign-Code`nSigned **$okN**, skipped $skN, failed **$failed**. Certificate: ``$($cert.Subject)``, timestamp $tsUrl" }
    if ($script:Ci -and $script:Env -eq 'azure') { Write-Host "##vso[task.setvariable variable=SignCode.Signed]$okN" }
    if ($failed -gt 0) { $exit = 6 } elseif ($Strict -and ($skN -gt 0 -or $sel.Skipped.Count -gt 0)) { Write-Say 'ERROR' '-Strict: some files were skipped.'; $exit = 6 }
}
catch [SignExit] {
    Write-Say 'ERROR' $_.Exception.Message
    $exit = $_.Exception.Code
}
catch {
    Write-Say 'ERROR' $_.Exception.Message
    $exit = 1
}
finally {
    foreach ($cb in $script:Cleanup) { try { & $cb } catch { } }
    foreach ($t in $script:Temp) { if (Test-Path -LiteralPath $t) { try { Remove-Item -LiteralPath $t -Force } catch { } } }
}
exit $exit
