  A NEW folder, never overwritten:   external-ca\<name>_<yyyyMMdd-HHmmss>\
     <name>.csr            his request, unchanged
     <name>.crt            HIS CA CERTIFICATE, signed by you
     <name>-fullchain.crt  his certificate + your chain (up to, not including, the Enterprise Root)
     <name>-chain.crt      your chain only
     root.crt              your Enterprise Root (the trust anchor)
     our-ca-bundle.crt     chain + root
     ca-info.json  README.txt   signer, subject, key, dates, serial, fingerprint, constraints,
                                the result of the verification
  The certificate is written in the index.txt of the signing root. Revoke it with
  PkiRevocation.ps1 -Action Revoke and it is in the CRL.

WHICH ROOT SIGNS
  (default)  q1-root   Classic, non-FIPS (Quadrant 1)
  -Fips      q2-root   Classic, FIPS (Quadrant 2). -Quadrant 1|2 does the same by number.
  Never an intermediate, never a Quantum Quadrant Root, never the Track or Enterprise Root.
  A Quadrant Root has pathLenConstraint 1, so his CA may issue end-entity certificates only
  (pathLen 0), unless you raise -PathLen.

WHAT HIS REQUEST MUST CONTAIN  (-Level, default OV)
  OV  Subject C (2 letters), O, OU and CN are REQUIRED. ST and L are recommended. Allowed: street,
      postalCode, name, emailAddress, telephoneNumber. Policies: OV + High Assurance + PEN.
  EV  Everything of OV, plus ST, L, serialNumber, businessCategory (Private Organization,
      Government Entity, Business Entity, Non-Commercial Entity) and jurisdictionC. Recommended:
      jurisdictionST, postalCode. Validity 397 days at most.
  DV  CN is required. Any other field is dropped (WARN).
  Key RSA 4096 or 8192, or ECDSA P-384 or P-521. P-256, RSA 2048 or 3072, Ed25519 and ML-DSA are
      refused: this is a Classic CA.
  The signature of the CSR must be valid and SHA-256 or stronger. A CSR that uses the CN of one of
  YOUR CAs is refused.

OPTIONS
  -Csr <file>          His PKCS#10 request (PEM). Required.
  -CsrType Auto|Leaf|IntermediateCA
                       Default Auto: CA:TRUE = a CA request. A LEAF request is refused with the
                       command to use (SignCsr.ps1). A hand-made CA request without CA:TRUE is
                       accepted as a CA request.
  -Level DV|OV|EV      Level written into his certificate. Default OV, EV when the request carries
                       complete EV information.
  -Fips                Sign with q2-root (Classic FIPS).
  -Name <text>         Name of the folder and the files. Default: his CN.
  -Days <n>            Validity. Default 1825 (5 years). EV: 397. Cut to what the signer still has.
  -PathLen 0..3        pathLenConstraint of HIS certificate. Default 0. At most the signer's - 1.
  -PermitDns <a,b>     Name constraint (critical): he may issue only for these DNS names and their
                       sub-domains (for example example.internal).
  -PermitEmail <a,b>   Name constraint: only these e-mail addresses or domains (@example.internal).
  -OutFolder <path>    Where the folders go. Default: external-ca\ next to the pki folder.
  -Check               Check the request and print the report. Sign nothing.
  -Strict              A WARN counts as an ERROR.
  -NoColor             Plain text (also when NO_COLOR is set).
  -Force               Issue even when the signer has pathLenConstraint 0 (lab only).
  -List                List the earlier requests (folders, signer, serial, dates) and stop.
  -Unblock             Unblock and unlock the script folder and the pki folder, then stop.
  -Pki <name>          Which company PKI. Default agantra. List: .\pki_setup.ps1 -ListPki
  -Release <n>         Which release (R1, R2 ...). Default: the latest. A deleted release is not an
                       error: the latest is used and a WARN says so.
  -NoCaRevocationInfo  Use the NoCR family (CA certificates without CRL and OCSP addresses).
  -PkiRoot <folder>    One PKI folder. Overrides -Pki, -Release and -NoCaRevocationInfo.
  -ConfigFile <path>  -OpenSslPath <path>  -FipsModuleConfig <path>  -Verbose
  -Help                This text.
  -Version             Show version, author, OS and tool versions.

HOW HE MAKES THE CSR  (he keeps the key)
  Easiest: New-PkiCsr.ps1 -CertificateType IntermediateCA. By hand:
     openssl genpkey -algorithm RSA -pkeyopt rsa_keygen_bits:4096 -out dept-ca.key
     openssl req -new -key dept-ca.key -sha384 -out dept-ca.csr `
         -subj "/C=EE/ST=Harju/L=Tallinn/O=Dept Ltd/OU=IT Department/CN=Dept Issuing CA G1"
  EV adds /serialNumber=12345678/businessCategory=Private Organization/jurisdictionC=EE

EXAMPLES
  .\SignExternalCa.ps1 -Csr .\dept-ca.csr                      OV, signed by q1-root
  .\SignExternalCa.ps1 -Csr .\dept-ca.csr -Fips -PermitDns dept.internal -Days 3650
  .\SignExternalCa.ps1 -Csr .\dept-ca.csr -Level EV -Check     would an EV CA be accepted?
